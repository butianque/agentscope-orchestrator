"""事件驱动增量判据 —— TRIG-01~04 / PERSIST-01~03 / 相生环周期。

## 判据要证明的事

事件的映射、检查点的增量、合并的可还原性 —— 这三样任何一样写错，
**表面上都看不出来**（都会返回一个像样的 dict）。所以判据必须**造出真缺陷**：

| 段 | 造的缺陷 | 必须的反应 |
|:--|:--|:--|
| ① | 事件 → 检查映射 | 四类事件各自翻对；认不出的类型**按全量**（不猜） |
| ② | **落盘之后坐标链真的多了一个坐标** | 链上多一个，且种类=检查点 |
| ③ | **增量只存变化量** | 第二次检查点**不含**没变的项（用条目数验，不看返回值） |
| ④ | **合并能还原** | 全量+增量合并 == 直接全量算的结果（逐项比） |
| ⑤ | **手工改坏索引文件**（绕过所有 API） | 步数/合并都不抛，且不假装成功 |
| ⑥ | 相生环周期 | 第5步该全量、第6步不该；步数0时不该 |
| ⑦ | 告警级别 | 认不出级别 ⇒ **按最重**（FATAL），不是按最轻 |
| ⑧ | 原子写 | 落账中断不留半个 json（同目录不该有 .tmp 残留） |

★ ⑤⑧ 是这套东西的命门：
  - 不测"坏数据"⇒ 索引坏一次，`步数()` 抛异常 ⇒ **整条调度链死掉**；
  - 不测"原子写" ⇒ 落账中断留下半截 json ⇒ 下次读的人以为"这一步没做"，
    而**这正是最该被发现的情况**（有一步没落账），却被伪装成"正常"。
"""
from __future__ import annotations

import json
import os
import shutil
import sys
from pathlib import Path

仓 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(仓))

_桶 = Path(__file__).resolve().parent / "_run_all_state" / "events"
shutil.rmtree(_桶, ignore_errors=True)
_桶.mkdir(parents=True, exist_ok=True)
os.environ["ORCH_STATE_DIR"] = str(_桶)

from agentscope_orchestrator import events as E      # noqa: E402

失败: list[str] = []


def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


print("① 事件 ⇒ 该跑哪些检查（四类各翻对；认不出的按全量）")
r = E.触发(E.文件变更, "a.py")
断言(r["合法"] and any(x["类"] == "操作覆盖" and x["全量"] for x in r["检查"]),
     f"文件变更 ⇒ 操作覆盖**必须全量**（{[(x['类'], '全量' if x['全量'] else '增量') for x in r['检查']]}）")
断言(any(x["类"] == "运行时" and not x["全量"] for x in r["检查"]),
     "文件变更 ⇒ 运行时**可增量**")
r = E.命令完成
r = E.触发(E.命令完成, "cargo test")
断言(all(not x["全量"] for x in r["检查"]),
     f"命令完成 ⇒ 只跑可增量的那几类（{[(x['类'], x['全量']) for x in r['检查']]}）")
r = E.触发(E.链断裂, "chain")
断言(all(x["全量"] for x in r["检查"]),
     f"链断裂 ⇒ **全部按全量**（链断了一切前提都不确定）")
r = E.触发("月球撞地球", "x")
断言(not r["合法"] and all(x["全量"] for x in r["检查"]),
     "认不出的事件类型 ⇒ 标不合法 + **按全量**（认不出就从严，不猜）")

print("② ★ 落盘之后坐标链真的多了一个坐标（PERSIST-03 的绑定）")
from agentscope_orchestrator import coord_chain as CC   # noqa: E402
链前 = len(CC._读())
体1 = E.检查点({"a": 1, "b": 2, "c": 3}, 事件=E.文件变更, 引用="a.py")
链后 = len(CC._读())
断言(链后 == 链前 + 1, f"落一个检查点 ⇒ 链上多一个坐标（{链前}→{链后}）")
_链 = CC._读()
断言(_链 and _链[-1].种类 == "检查点", f"链上那个坐标的种类=检查点（{_链[-1].种类 if _链 else '无'}）")
断言(体1.get("链") is not None, "检查点里记下了自己挂上的链指纹（没挂上要如实为 None）")
断言(体1["全量"] is True, "首次检查点自动是**全量**（没有基准可选）")

print("③ ★ 增量只存变化量（PERSIST-02）—— 用条目数验，不看返回值")
体2 = E.检查点({"a": 1, "b": 99, "c": 3}, 事件=E.命令完成, 引用="run")
断言(体2["全量"] is False, "第二次检查点不是全量")
断言(set(体2["增量"].keys()) == {"b"},
     f"**只有变了的项**进了增量（增量键={sorted(体2['增量'].keys())}，应当只有 b）")
p2 = Path([r for r in E._读索引()][-1]["路径"])
小2 = p2.stat().st_size
体1p = Path(E._读索引()[0]["路径"])
小1 = 体1p.stat().st_size
print(f"       文件大小：全量 {小1}B · 增量 {小2}B")
断言(小2 < 小1, f"增量文件**真的更小**（{小2} < {小1}）—— 不是只把全量标成增量")

print("④ ★ 合并能还原当前状态（增量存储的立身之本）")
E.检查点({"a": 1, "b": 99, "c": 4}, 事件=E.状态转移, 引用="t")   # 再变一次
合 = E.合并()
断言(合 == {"a": 1, "b": 99, "c": 4},
     f"全量+增量合并 == 当前真实状态（{合}）")
断言(合.get("b") == 99, "合并不是把增量**丢弃**，也不是把旧值盖回去")

print("⑤ ★ 手工改坏索引文件（绕过所有 API）⇒ 不许抛、不许假装成功")
idx = E.检查点索引()
备份 = idx.read_text(encoding="utf-8")
idx.write_text("{这不是合法 json 列表", encoding="utf-8")
断言(isinstance(E.步数(), int), f"索引坏了 ⇒ 步数() 仍返回 int（{E.步数()}）")
断言(isinstance(E.合并(), dict), "索引坏了 ⇒ 合并() 仍返回 dict")
断言(not E.该全量扫描吗(), "索引坏了、步数当 0 ⇒ **不该**判成全量（0 步不是整周期）")
s = E.统计()
断言(isinstance(s, dict) and "检查点数" in s, f"索引坏了 ⇒ 统计() 仍可用（{str(s)[:56]}）")
idx.write_text(备份, encoding="utf-8")

print("⑥ 相生环周期 5（SCHED-03）")
断言(E.该全量扫描吗(0) is False, "第 0 步 ⇒ 不该全量（还没开始走）")
断言(E.该全量扫描吗(E.周期) is True, f"第 {E.周期} 步 ⇒ 该全量（走满一圈）")
断言(E.该全量扫描吗(E.周期 + 1) is False, f"第 {E.周期 + 1} 步 ⇒ 不该全量")
断言(E.该全量扫描吗(E.周期 * 2) is True, f"第 {E.周期 * 2} 步 ⇒ 又该全量")
_步 = E.步数()
断言(isinstance(_步, int) and _步 >= 3, f"步数 = 已落检查点数（{_步}）")

print("⑦ 告警级别：认不出就按**最重**，不是按最轻")
a = E.告警("ERROR", "链断裂", "坐标不连续", "从最近有效坐标重建")
断言(a["阻断"] and a["级别"] == "ERROR", f"ERROR ⇒ 阻断（去向 {a['去向']}）")
b = E.告警("WARN", "编码不一致", "文件不是 UTF-8", "自动重新编码")
断言(not b["阻断"] and b["级别"] == "WARN", f"WARN ⇒ 不阻断（去向 {b['去向']}）")
c = E.告警("这事儿有点怪", "X", "Y")
断言(c["级别"] == "FATAL" and c["认不出级别"],
     f"认不出的级别 ⇒ **按 FATAL 最重**（{c['级别']}），不是静默当 DEBUG")
断言("[" in c["行"] and "]" in c["行"], f"告警行格式 (完整输出不可截断)：{c['行'][:70]}")
_近 = E.告警们(10)
断言(len(_近) >= 3, f"告警真的落了账（{len(_近)} 条）")

print("⑧ 原子写：落账不留半截文件")
d = E.检查点目录()
残留 = list(d.glob("*.tmp"))
断言(not 残留, f"检查点目录里没有 .tmp 残留（{len(残留)} 个）")
左 = list(d.glob("cp_*.json"))
断言(len(左) == E.步数(), f"检查点文件数 == 索引条数（{len(左)} == {E.步数()}）")

print("⑨ 项被删了也算变化（增量不许静默丢删除）")
E.检查点({"a": 1}, 事件=E.状态转移, 引用="del")
末 = E._读索引()[-1]
断言(末["变化数"] >= 2,
     f"从 {{a,b,c}} 变成 {{a}} ⇒ 至少 2 个变化（b、c 被删）（变化数 {末['变化数']}）")
断言("c" not in E.合并(), "合并后 c 确实没了（删除被正确应用）")

print("⑩ 真机：落到真实状态根上跑一轮，看统计"
      "（只读 ORCH_STATE_DIR，不碰仓）")
st = E.统计()
print(f"       检查点 {st.get('检查点数')} · 步数 {st.get('步数')} · 周期 {st.get('周期')}"
      f" · 上次全量 {st.get('上次全量')} · 高级告警 {st.get('高级告警')}")
断言("检查点数" in st, "统计给出检查点数")

print()
if 失败:
    print(f"事件驱动判据：红 {len(失败)} 项 —— {失败[0]}")
    sys.exit(1)
print("事件驱动判据：绿 —— 映射不猜、增量只存变化、合并可还原、坏文件不抛、周期正确、告警从严")
