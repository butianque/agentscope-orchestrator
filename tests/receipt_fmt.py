"""回执格式判据 —— 让「回执够不够格」变成能红的东西。

## 判据要证明的事

一个格式校验器最容易写成"什么都通过"：正则宽一点、缺项跳过、认不出就放过 ——
**它永远绿，也永远没用**。所以这里的判据**全部是"造出违规，看它抓不抓"**：

| 段 | 造的违规 | 必须抓 |
|:--|:--|:--|
| ① | 五种模板各自生成 ⇒ **生成的东西必须自己够格** | 自洽（生成器与校验器不许互相矛盾） |
| ② | 每种模板**各缺一个必填项** | 全部抓红，且指出缺哪个 |
| ③ | ★ **证据链编号与类型不匹配** | 抓红（条数一样但编号不同 —— 最容易被放过的） |
| ④ | 推导链：等级非法 / 跳步 / 缺依据 | 三种各抓一次 |
| ⑤ | **六类禁止句式各造一句真话** | 六类全抓 |
| ⑥ | 合法的东西**不许误伤** | 绿 |
| ⑦ | 空文 / 乱码 / 只有标题 | 不抛，返回"不够格 + 原因" |

★ ③ 是这套东西的**命门**：
  「我给了 4 条证据」这句话**是看不出对错的** ——
  给的是「创建新文件」的那 4 条，却声称做的是「完整覆盖写入」，
  **条数一样，意思完全不同**。判据必须比**编号集合**，不是比条数。

★ ⑥ 与 ①②③④⑤ 同等重要：**只会抓违规的校验器会把人逼走**
  （写什么都被判红 ⇒ 人索性不看判据了）。所以必须有一段证明**合法的不误伤**。
"""
from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path

仓 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(仓))

_桶 = Path(__file__).resolve().parent / "_run_all_state" / "receipt_fmt"
shutil.rmtree(_桶, ignore_errors=True)
_桶.mkdir(parents=True, exist_ok=True)
os.environ["ORCH_STATE_DIR"] = str(_桶)

from agentscope_orchestrator import receipt_fmt as R      # noqa: E402

失败: list[str] = []


def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


def 含(问题们, 关键词: str) -> bool:
    return any(关键词 in p for p in 问题们)


print("① 五种模板各自生成 ⇒ 生成的东西必须**自己够格**（生成器与校验器不许互相矛盾）")
for k in R.种类们:
    骨架 = R.生成(k)
    断言(bool(骨架.strip()), f"{k} 能生成骨架（{len(骨架)} 字）")
    断言(f"{k}" in 骨架 or R.种类信息[k]["名"] in 骨架, f"{k} 骨架里写明了模板种类")
    for 名 in R.必填项(k):
        断言(f"{{{{{名}}}}}" in 骨架, f"{k} 骨架里带必填占位 {{{{{名}}}}}*")

print("② 每种模板各缺一个必填项 ⇒ 全部抓红，且指出缺哪个")
# ★★ 造样例时**不能用 `值-{名}` 一律糊过去**（第一版就是这么写的，判据红了四轮）：
#   有的必填项的**值是受约束的** —— `证据链` 必须真的是 `EV-xx` 编号。
#   拿 `值-证据链` 去填，等于**造了一份本身就违规的回执**，然后拿它当"别处都齐"的基准
#   ⇒ 判据报的红是**我的样例错**，不是实现错。
#   ⇒ 口径：造"应当够格"的基准时，**每个必填项都要给合它规的值**。
样例值 = {
    "轮次编号": "轮次编号：ORCH-214",
    "执行项": "执行项：1\n执行项：2",
    "证据链": "EV-01 EV-02 EV-03 EV-04",
    "审计依据": "审计依据：某.md §1",
    "驳回对象": "驳回对象：上一轮的执行项1",
    "驳回理由": "驳回理由：依据不足",
    "修正要求": "修正要求：补出原文引用",
    "冷启动步骤": "步骤 1",
    "快照状态": "快照：新建",
    "断点位置": "断点位置：执行项 3",
    "已通过校验": "已通过校验：L1/L2/L3",
    "变更对象": "变更对象：文档体系版本",
    "变更前后": "变更前后：v1.0 → v1.1",
}


def 造好(k: str, 抹掉: str = "") -> str:
    """造一份该模板的回执。`抹掉` 指定要漏掉哪个必填项。

    ★★ 只删"头部那一行"是不够的（第一版就是这样，判据红了）：
      必填项 `证据链` 的要求是"文里得有 EV-xx 编号"，而我把编号**也写在了正文证据段里**
      ⇒ 删掉头部那行，正文里的 `EV-01` 还在 ⇒ `证据链` **仍然满足** ⇒ 红不出来。
      ⇒ 口径：抹掉某一项时，**要把该项在全文的所有出现都抹掉**，
        否则测的不是"缺这一项会不会被抓"，而是"我删的那个字符串会不会被抓"。
        （这也是本仓那条通用教训：**改一处要把同类位置全找一遍**。）
    """
    项s = R.必填项(k)
    头 = "\n".join(样例值.get(x, f"{x}：值") for x in 项s if x != 抹掉)
    证据 = "EV-01 路径\nEV-02 首行\nEV-03 末行\nEV-04 行数\n"
    if 抹掉 == "证据链":
        证据 = "（此处应有证据编号）\n"
    审计 = "（对照）"
    # ★★ 必填项与**正文小节名**同名时，只抹头部那一行没用 ——
    #   `审计依据` 的正文小节 `## 审计依据` 会继续满足它。
    #   ⇒ 口径：**抹掉就是全文抹掉**（头部行 + 正文小节名一起处理），
    #     否则测的是"我删的那个字符串在不在"，不是"缺这一项会不会被抓"。
    if 抹掉 == "审计依据":
        审计 = "（此处应有依据）"
        节名 = "## 本节按条款逐条对照"
    else:
        节名 = "## 审计依据"
    身 = ("\n## 原文引用\n（逐字）\n## 执行证据链\n本操作属于创建新文件。\n"
          + 证据 +
          f"{节名}\n{审计}\n## 本地AI分析\nS1·某步 | 依据：某.md §1 | 等级：L0\n"
          "## 待AI指挥官裁定事项\n（事实）\n## 对AI指挥官约束要求\n（清单）\n")
    文 = f"# {k}·{R.种类信息[k]['名']}\n" + 头 + "\n" + 身
    # ★ 最后一道保险：把"抹掉项的名字"从全文里清掉（同名先后缀一律处理），
    #   因为模板不同、同一词可能在多处出现。**只对非证据链项做** ——
    #   证据链的判定依据是 EV 编号本身，不是"证据链"这三个字。
    if 抹掉 and 抹掉 != "证据链":
        文 = re.sub(rf"{re.escape(抹掉)}\s*\**\s*[:：]?\s*[^\n]*", "", 文)
    return 文


for k in R.种类们:
    项s = R.必填项(k)
    if not 项s:
        continue
    好 = 造好(k)
    ok, 问 = R.校验(好)
    断言(ok, f"{k} 的**基准样例**自己够格（不然下面的判红说明不了任何事）—— {问[:2]}")
    for 名 in 项s:
        坏 = 造好(k, 抹掉=名)
        ok2, 问2 = R.校验(坏)
        断言(not ok2 and 含(问2, "缺必填项") and 名 in " ".join(问2),
             f"{k} 缺「{名}」⇒ 红且点名（{next((p for p in 问2 if '缺必填项' in p), '')[:52]}）")

print("③ ★★ 证据链编号与类型不匹配 ⇒ 抓红（比集合，不比条数）—— 命门")
# 声称"完整覆盖写入"（要 EV-01~07），实际只给了"创建新文件"的那 4 条
假 = ("# T1·正式推进\n轮次编号：ORCH-9\n执行项：1\n审计依据：某.md §1\n"
      "## 原文引用\n（逐字）\n"
      "## 执行证据链\n本操作属于完整覆盖写入。\nEV-01 路径\nEV-02 首行\nEV-03 末行\nEV-04 行数\n"
      "## 本地AI分析\nS1·某步 | 依据：某.md §1 | 等级：L0\n")
ok, 问 = R.校验(假)
断言(not ok and 含(问, "证据链与类型不匹配"),
     f"声称「完整覆盖写入」却只给 EV-01~04 ⇒ **抓红**（{next((p for p in 问 if '不匹配' in p), '')[:90]}）")
# 条数一样多，但编号是另一类的 ⇒ 也要抓（这一条是"只数条数"漏掉的）
假2 = 假.replace("EV-01 路径\nEV-02 首行\nEV-03 末行\nEV-04 行数",
                "EV-01 路径\nEV-08 上文\nEV-09 旧文\nEV-10 新文")
ok2, 问2 = R.校验(假2)
断言(not ok2 and 含(问2, "证据链与类型不匹配"),
     "**条数都是 4 条**，但编号属于「增量替换」⇒ 照样抓红（这正是只数条数会漏的）")
# 类型与编号匹配的那份 ⇒ 该绿
真 = ("# T1·正式推进\n轮次编号：ORCH-9\n执行项：1\n审计依据：某.md §1\n"
      "## 原文引用\n（逐字）\n"
      "## 执行证据链\n本操作属于完整覆盖写入，编号如下。\n"
      "EV-01 旧版本 v1.0 共 100 行\nEV-02 新版本行\nEV-03 L1 标题\nEV-04 L2 标题\n"
      "EV-05 L3 标题\nEV-06 末章标题\nEV-07 更新后 120 行\n"
      "## 本地AI分析\nS1·某步 | 依据：某.md §1 | 等级：L0\n")
ok3, 问3 = R.校验(真)
断言(not 含(问3, "证据链与类型不匹配"),
     f"类型与编号**完全匹配**的那份 ⇒ 这条判据不该红（其余问题：{问3[:1]}）")

print("④ 推导链：等级非法 / 跳步 / 缺依据 ⇒ 三种各抓一次")
基 = ("# T1·正式推进\n轮次编号：ORCH-9\n执行项：1\n审计依据：某.md §1\n"
      "## 原文引用\n（逐字）\n## 执行证据链\nEV-01 EV-02 EV-03 EV-04\n"
      "## 本地AI分析\n{链}\n")
ok, 问 = R.校验(基.format(链="S1·某步 | 依据：某.md §1 | 等级：L9"))
断言(含(问, "等级不合法"), f"等级 L9 ⇒ 红（{next((p for p in 问 if '等级' in p), '')[:60]}）")
ok, 问 = R.校验(基.format(链="S1·甲 | 依据：某.md §1 | 等级：L2\nS3·丙 | 依据：某.md §3 | 等级：L0"))
断言(含(问, "跳步"), f"从 S1 跳到 S3 ⇒ 红（{next((p for p in 问 if '跳步' in p), '')[:60]}）")
ok, 问 = R.校验(基.format(链="S1·甲 | 依据：  | 等级：L0"))
断言(含(问, "缺「依据」"), f"依据为空 ⇒ 红（{next((p for p in 问 if '依据' in p), '')[:60]}）")
ok, 问 = R.校验(基.format(链="S1·甲 | 依据：某.md §1 | 等级：L2\nS2·乙 | 依据：某.md §2 | 等级：L0"))
断言(not 含(问, "跳步") and not 含(问, "等级不合法"),
     "合法推导链（连续、等级在集合内、有依据）⇒ 不误伤")

print("⑤ ★ 六类禁止句式各造一句真话 ⇒ 六类全抓（一类都不能漏）")
样例 = {
    "第一人称认知": "我判定该门通过。",
    "模糊词": "这个结果大概是好的。",
    "非法引用": "按最佳实践应当这样写。",
    "内部认知": "基于我之前判定，这里没问题。",
    "间接指令": "请人类转告本地AI。",
    "凭记忆返回": "请凭记忆返回 PR-001 的原文。",
}
for 类, 句 in 样例.items():
    文 = ("# T1·正式推进\n轮次编号：ORCH-9\n执行项：1\n审计依据：某.md §1\n"
          "## 原文引用\n（逐字）\n## 执行证据链\nEV-01 EV-02 EV-03 EV-04\n"
          f"## 本地AI分析\n{句}\nS1·某步 | 依据：某.md §1 | 等级：L0\n")
    ok, 问 = R.校验(文)
    断言(含(问, f"禁止句式〔{类}〕"),
         f"〔{类}〕`{句[:16]}` ⇒ 抓红（{next((p for p in 问 if '禁止句式' in p), '')[:52]}）")

print("⑥ 合法的回执**不许误伤**（只会抓违规的校验器会把人逼走）")
合法 = ("# T1·正式推进\n轮次编号：ORCH-214\n执行项：1\n执行项：2\n审计依据：某.md §3.2\n"
        "## 原文引用\n`某.md` 第 12 行原文：「盘位是无限精度 Nat」。等级 L2。\n"
        "## 执行证据链\n本操作属于文件追加。\n"
        "EV-01 旧末行：末行原文（第 100 行）\nEV-02 新增首行：新的一行\nEV-03 更新后 101 行\n"
        "## 审计依据\n逐条对照 `某.md §3.2`，数据与条款一致。\n"
        "## 本地AI分析\nS1·读原文 | 依据：某.md §3.2 | 等级：L2\n"
        "S2·对照数据 | 依据：某.md §3.2 | 等级：L0\n"
        "## 待AI指挥官裁定事项\n条款是否适用于本模块。\n"
        "## 对AI指挥官约束要求\n下轮须给：轮次编号、执行项。\n")
ok, 问 = R.校验(合法)
断言(ok, f"这份合法回执 ⇒ **绿**（问题：{问[:2]}）")
断言(R.解析(合法)["证据类型"] == [4], f"认得出这是「追加」类型（{R.解析(合法)['证据类型']}）")

print("⑦ 空文 / 乱码 / 只有标题 ⇒ 不抛，返回「不够格 + 原因」")
for 名, 文 in (("空文", ""), ("空白", "   \n\t  "), ("乱码", "\x00\x01\x02"),
               ("只有标题", "# 回执")):
    ok, 问 = R.校验(文)
    断言(ok is False and len(问) > 0, f"{名} ⇒ 不够格且给出原因（{问[0][:44]}）")

print("⑧ 认不出模板 ⇒ 不猜（报出来，不当通过）")
无模板 = ("轮次编号：X\n## 原文引用\n（逐字）\n## 执行证据链\nEV-01\n"
          "## 本地AI分析\nS1·甲 | 依据：某.md §1 | 等级：L0\n")
ok, 问 = R.校验(无模板)
断言(含(问, "认不出是哪种模板"), f"没写模板种类 ⇒ 如实报出（{next((p for p in 问 if '模板' in p), '')[:52]}）")

print("⑨ 解析器基本正确（六部分 / 执行项 / 证据链都能抽出来）")
体 = R.解析(合法)
断言(体["执行项"] == [1, 2], f"执行项抽出来了（{体['执行项']}）")
断言("原文引用" in 体["节"] and "审计依据" in 体["节"], f"章节抽出来了（{len(体['节'])} 节）")
断言(len(体["推导链"]) == 2, f"推导链抽出来 2 步（{len(体['推导链'])}）")
断言(not R.生成("T9"), "不存在的模板种类 ⇒ 返回空串，不编一个出来")
断言(R.统计()["模板种类"] == 5 and R.统计()["证据类型"] == 5,
     f"统计：模板 {R.统计()['模板种类']} 种 · 证据类型 {R.统计()['证据类型']} 类")

print()
if 失败:
    print(f"回执格式判据：红 {len(失败)} 项 —— {失败[0]}")
    sys.exit(1)
print("回执格式判据：绿 —— 五模板自洽、必填可抓、证据编号比集合、推导链三错全抓、六类禁句全抓、合法不误伤")
