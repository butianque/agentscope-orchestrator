"""经验环两门：B 未验条目查询不可见 · C 同一指纹二现命中首现产物且门重跑。

为什么这两门必须单独存在
------------------------
`learning.记()` 有**两条**写入路径（`验证` 字段不同）：
  · 门绿 ⇒ `"门:test_counts"` 之类 —— 这条是**已证**事实；
  · 无门 ⇒ `"门:（未提供）"` —— 这条**只是推测**（`G-044`：猜的被记成知道的）。

而 `取()` 原来**完全不看 `验证`**，只按相似度过滤 ⇒ 未验条目照样被检索出来、
照样注入提示。这正是 G-044 说的「兜底的危害在记忆」——
更坏的是它还会被**当成已验证的结论**引用。

# 门 B（未验条目查询不可见）
判据：若库里只有**未验**条目，`取()` 必须返回 `""`。
      不是「降权」、不是「排后面」——**不可见**。

# 门 C（同一指纹二现命中首现产物且门重跑）
判据两层，都必须成立：
  ① **命中首现**：同一指纹的两条（做法不同），`取()` 给出的必须是**首现**那条的做法。
     依据：首现是**第一次把这条路走通**的记录；后现是复述。复述可能夹带当时环境的
     偶然细节（例如同一错误换了种写法），首现才是那类失败**最干净的解**。
  ② **门重跑**：输出里必须明确「必须自己验证」，且**不得**出现任何
     「已通过/可直接用」的表述 —— 经验只许当**线索**，不许当**判据**。
     这一条是**可证伪的文字约束**：删掉那句提示 ⇒ 本判据翻红。

纯内存 temp 目录，不触真 cargo、不触 DB、不改 `~/.orchestrator`。
"""
from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from agentscope_orchestrator import learning as 学  # noqa: E402

PASS = 0

# 两条同指纹样本：语言/失败门/异常/错误词/后缀 全部相同 ⇒ 指纹逐字段相等。
#
# ★ 证据必须是**真实门格式**（`[test_counts] 通过不足|passed=0…`）：
#   第一版我写成 `### 门 test_counts 未过（rc=1）`，`_失败门()` 只认 `xxx|` 片段
#   ⇒ 解析成「未知」⇒ `_相似()` 见 `门A == "未知"` 直接返回 0.0
#   ⇒ `取()` 无论如何都返回空 ⇒ **门B 断言空转通过**（红判据假绿）。
#   这是本轮抓到的第 2 个空转：判据本身要先证明「它测得到东西」。
命令 = ["python", "-m", "pytest", "-q"]
证据 = ("[test_counts] 通过不足|passed=0 failed=2 skipped=0\n"
        "FAIL: test_to_mb\nAssertionError: places differ\n"
        "assertAlmostEqual within 1 places failed\n")


def check(cond, msg):
    global PASS
    if not cond:
        raise SystemExit(f"FAIL: {msg}")
    PASS += 1


def 写库(路径: Path, 条们: list[dict]) -> None:
    路径.parent.mkdir(parents=True, exist_ok=True)
    with 路径.open("w", encoding="utf-8") as f:
        for 条 in 条们:
            f.write(json.dumps(条, ensure_ascii=False) + "\n")


def 造条(做法: str, 验证: str, 时间: str) -> dict:
    return {
        "时间": 时间,
        "指纹": 学.指纹(命令, 证据, [f"src/{做法}.py"]),
        "症状": f"症状-{做法}",
        "根因": f"根因-{做法}",
        "做法": [{"op": "write", "path": f"src/{做法}.py"}],
        "验证": 验证,
        "键": 做法,
    }


def main() -> int:
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d)
        库 = tmp / ".orchestrator" / "experience.jsonl"
        os.environ["ORCH_PROFILE"] = str(tmp / "p.yml")
        check(str(学.经验文件()) == str(库),
              f"经验库路径应跟着 ORCH_PROFILE 走，实得 {学.经验文件()}")

        # ══════════════════════════════════════════════════════════════
        # 【反空转】先证明这一门**测得到东西** —— 否则下面的「返回空」毫无意义。
        #
        # 实测踩过：假证据格式不对 ⇒ 失败门=「未知」⇒ `_相似` 恒 0 ⇒ `取()` 恒空
        # ⇒ 门B 断言 `出 == ""` **自动通过**，什么也没验。比红更坏。
        # ⇒ 此处强制：先造一条**已验**同指纹条目，`取()` 必须**非空**。
        #   它非空，才证明「返回空」是门B 的效果，不是相似度坏掉的效果。
        # ══════════════════════════════════════════════════════════════
        写库(库, [造条("对照已验", "门:test_counts", "2026-10-31T08:00:00")])
        对照 = 学.取(命令, 证据)
        check(对照 != "",
              "【反空转】同指纹的**已验**条目都取不出来 ⇒ 本判据测不到东西"
              "（先修指纹/相似度，再谈门B）。")

        # ══════════════════════════════════════════════════════════════
        # 门 B：未验条目查询不可见
        # ══════════════════════════════════════════════════════════════
        写库(库, [造条("未验甲", "门:（未提供）", "2026-10-31T10:00:00")])
        出 = 学.取(命令, 证据)
        check(出 == "",
              f"【门B】库里只有**未验**条目，`取()` 必须返回空（不可见），实得：{出!r}")

        # 未验条目也不得出现在统计的「可检索」口径里
        统 = 学.统计()
        check(统.get("未验条数") == 1 and 统.get("已验条数") == 0,
              f"【门B】统计须区分已验/未验，实得 {统}")

        # ══════════════════════════════════════════════════════════════
        # 门 C：同一指纹二现 ⇒ 命中首现产物 + 门重跑
        # ══════════════════════════════════════════════════════════════
        # 两条**指纹相同**、做法不同、都已验；首现时间更早。
        首现 = 造条("首现产物", "门:test_counts", "2026-10-31T09:00:00")
        后现 = 造条("后现复述", "门:test_counts", "2026-10-31T11:00:00")
        check(首现["指纹"] == 后现["指纹"],
              "构造失败：两条样本的指纹本应逐字段相同")
        写库(库, [后现, 首现])          # ★ 故意把**后现**写在文件前面（物理序 ≠ 时间序）

        出 = 学.取(命令, 证据)
        check(出 != "", "【门C】已验条目应可检索，实得空")
        # ① 命中首现的**做法**
        check("首现产物" in 出,
              f"【门C①】同一指纹二现，必须命中**首现**产物，实得：{出!r}")
        check("后现复述" not in 出,
              f"【门C①】不得命中后现复述（`上限=2` 也只许给首现那一条），实得：{出!r}")
        # ② 门重跑：必须带「必须自己验证」的约束，且不得宣称「已通过/可直接用」
        check("必须自己验证" in 出,
              f"【门C②】输出必须明确要求**门重跑**（原文须含「必须自己验证」），实得：{出!r}")
        for 禁词 in ("已通过", "可直接用", "照抄即可", "无需验证"):
            check(禁词 not in 出,
                  f"【门C②】输出不得出现「{禁词}」——经验只许当线索，不许当判据，实得：{出!r}")

        # ══════════════════════════════════════════════════════════════
        # 门 C 的可证伪性：把首现删掉，就必须改命中后现（否则说明排序根本没按时间）
        # ══════════════════════════════════════════════════════════════
        写库(库, [后现])
        出2 = 学.取(命令, 证据)
        check("后现复述" in 出2,
              f"【门C·可证伪】只剩后现时应当命中它，实得：{出2!r}")

    print(f"[learning_gates] 全绿（PASS={PASS}）—— 门B 未验不可见 · 门C 首现优先+门重跑")
    return 0


if __name__ == "__main__":
    sys.exit(main())
