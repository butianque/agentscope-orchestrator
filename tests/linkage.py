"""四方文档联动判据：LINK-01~05 —— 快照/任务书/回执/状态索引互锁。

## 判据要证明的事

`linkage.py` 的五条联动，如果只是"我调 API 我返回 True"，那它就是零价值。
所以本判据**全部用真文档样例**（不是自造的对象），并且每条判据都要求
**造出一个真缺陷，看它能不能红**：

| 判据 | 造的缺陷 | 必须的反应 |
|:--|:--|:--|
| LINK-01 | 任务书引用一个快照里**不存在**的编号 | 红，并指出是哪个 |
| LINK-01 | 任务书**一个都不引用**（纯新增） | **绿**（不该误伤） |
| LINK-02 | 任务书声明 v0.1，快照已是 v0.2 | 红（漂移） |
| LINK-02 | 任务书没声明版本 | 绿但提示（老任务书本来就没这行） |
| LINK-03 | 任务书 3 项、回执只交 2 项 | 红，指出**漏**了哪项 |
| LINK-03 | 回执多交了任务书没写的项 | 红，指出**越界**（对称差，不是单向） |
| LINK-04 | 任务书按 PR-7 判，回执根本没提 PR-7 | 红 |
| LINK-05 | 回执没进状态索引的归档表 | 红 |
| LINK-05 | 回执已在归档表里 | 绿 |

★ 最后还有一条**最重要**的：**不许"因为认不出而通过"**。
  文档写得不规范时（编号认不出），判据必须报"锚缺失"，**不许猜成通过** ——
  猜出来的通过比红危险得多，因为它把"没验"伪装成了"验过"。
"""
