def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


# ── 造真文档样例（写在磁盘上，不是内存对象）────────────────────────────
def 写(名: str, 文: str) -> Path:
    p = _桶 / 名
    p.write_text(文, encoding="utf-8")
    return p


