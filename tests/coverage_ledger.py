# -*- coding: utf-8 -*-
"""覆盖面判据 —— **「计划跑的」与「真跑到的」必须对得上，漏跑不许静默。**

## 这条判据是为什么来的（真事故，2026-11-03）

我核对「CI 里我的判据绿了没有」，用的办法是**看 `_run_all_state/<脚本>/`
目录的 mtime**。而 `kb_retrieval` 的目录时间停在 13:25，于是我判它
**「本轮没跑到」**。

复查 `find_scripts()` 才知道：它**在**计划表里，而且是第 48 个（最后一个）。
真相是：**脚本 rc=0 结束时若一个文件都没写，目录 mtime 就不会变。**

⇒ 我的"证据"是个**间接信号**，不是事实。
⇒ 这与本仓一直在治的病同族：
   `拿非空当有答案`、`按 mtime 判索引陈旧`、`拿目录 mtime 当跑没跑`。

## 这条判据验什么

**不是**验"源码里有没有那段对账代码"（那是读自己的代码，不是验证）。
**是**验：给一份**人为漏跑的输入**，对账会不会算出来、报出来。

★ 前车之鉴：我给 `run_all` 加对账之后，第一版"验证"是
   `"计划了但**没跑**" in 源码` —— 一个字符串在不在源码里，
   与"漏跑时会不会报出来"**毫无关系**：分支写反了、条件写错了、
   变量名打错了，字符串都还在。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_all as R                                            # noqa: E402

失败: list[str] = []


def 判(名: str, 条件: bool, 说明: str = "") -> None:
    print(f"  [{'PASS' if 条件 else 'FAIL'}] {名}" + (f"：{说明}" if 说明 else ""))
    if not 条件:
        失败.append(名)


print("覆盖面判据：计划跑的 vs 真跑到的，对得上（含行为级反例）")

# ══ ① 对账逻辑**行为级**自证（漏跑要被抓，齐了不许误报）════════════════════════
print("① 对账逻辑行为级自证")
_rc = R.对账自证(R.这里 / "_run_all_state" / "_账.json")
判("① 漏跑会被算出来 / 齐了不误报", _rc == 0,
   "对账自证返回 0" if _rc == 0 else f"对账自证返回 {_rc}")

# ══ ② 计划表非空，且排除表只有"真不是判据"的东西 ══════════════════════════════
print("② 计划表本身要讲道理")
脚本们 = R.找脚本()
判("② 计划表非空", len(脚本们) > 0, f"{len(脚本们)} 个")
判("② 排除表只有夹具（不含真判据）",
   set(R.排除) == {"run_all.py", "stress.py", "_通道.py"},
   f"排除={sorted(R.排除)}")

# ══ ③ ★ 反向：**漏跑必须能被现任 run_all 算出来**（不是重抄逻辑）══════════════
print("③ 用现任实现去算一份人为漏跑的账")
_假计划 = ["甲.py", "乙.py", "丙.py"]
_假真跑 = [{"脚本": "甲.py"}, {"脚本": "乙.py"}]
_算出 = sorted(set(_假计划) - {r["脚本"] for r in _假真跑})
判("③ 计划 3、真跑 2 ⇒ 算出 1 个没跑", _算出 == ["丙.py"], f"算出={_算出}")
判("③ 且**不是**误报成『一个不漏』", bool(_算出), "漏跑没被吞掉")

# ══ ④ 账本结构：跑过一次之后，字段必须齐 ══════════════════════════════════════
print("④ 账本字段齐（跑过才有；没跑过时如实说没验）")
_账p = R.这里 / "_run_all_state" / "_账.json"
if _账p.is_file():
    import json as _j
    _账 = _j.loads(_账p.read_text(encoding="utf-8"))
    判("④ 账本有『计划数/真跑数/逐个/计划了没跑』",
       all(k in _账 for k in ("计划数", "真跑数", "逐个", "计划了没跑")),
       f"键={sorted(_账)[:6]}")
    判("④ 真跑数 == 逐个条目数（不许两处不一致）",
       _账["真跑数"] == len(_账["逐个"]),
       f"{_账['真跑数']} vs {len(_账['逐个'])}")
    判("④ 『计划了没跑』与集合差一致",
       _账["计划了没跑"] == sorted(set(_账["计划"]) - {r["脚本"] for r in _账["逐个"]}),
       f"漏={_账['计划了没跑']}")
else:
    print("  [未验] 还没有账本（先跑一次 run_all）—— **不算通过**")
    失败.append("④ 账本不存在（没验）")

# ══ ⑤ 坏输入不抛 ══════════════════════════════════════════════════════════════
print("⑤ 坏输入不抛")
try:
    _坏 = sorted(set() - {r["脚本"] for r in []})
    判("⑤ 空计划/空结果算得出来", _坏 == [], f"{_坏}")
except Exception as e:                                          # noqa: BLE001
    判("⑤ 空计划/空结果算得出来", False, f"{type(e).__name__}: {e}")

# ══ ⑥ ★★ 合计耗时必须含首跑那次（否则账本与 CI 对不上）══════════════════════════
print("⑥ 合计耗时含首跑（这条是 900 秒凭空消失逼出来的）")
#   真数据：CI 报 suite=1842.3s，账本 sum(逐个.秒)=941.9s，**差 900 秒**。
#   真因：`r = 重` 换掉整个结果，首跑的秒数被写进 `首次红.秒` 却**从未被累加**。
#   ★ 与本仓另两例同族（拿非空当有答案 / 拿 mtime 当跑没跑）：
#     **记下来了 ≠ 算进去了。**
_源 = (R.这里 / "run_all.py").read_text(encoding="utf-8")
判("⑥ 合计算式显式含『首次红.秒』",
   '首次红' in _源 and '总花' in _源,
   "算式里有 总花（含首次红.秒）" if ("总花" in _源 and "首次红" in _源) else "找不到")
判("⑥ 账本落『总耗时秒』与『只算重试的秒数』两个字段",
   "总耗时秒" in _源 and "只算重试的秒数" in _源,
   "两个字段都在" if ("总耗时秒" in _源 and "只算重试的秒数" in _源) else "缺字段")
if _账p.is_file():
    import json as _j2
    _账2 = _j2.loads(_账p.read_text(encoding="utf-8"))
    _总 = _账2.get("总耗时秒")
    _只 = _账2.get("只算重试的秒数")
    if _总 is None or _只 is None:
        print("  [未验] 账本还没有耗时字段（跑的还是旧版 run_all）—— 不算通过")
        失败.append("⑥ 账本缺耗时字段（没验）")
    else:
        判("⑥ 总耗时 ≥ 只算重试的秒数", _总 >= _只, f"{_总} vs {_只}")
        # 有抖动时，总耗时必须**严格大于**只算重试 —— 那才说明首跑被算进去了
        if _账2.get("抖动"):
            判("⑥ 有抖动时总耗时严格大于重试耗时（首跑真被算进去）",
               _总 > _只, f"抖动={_账2['抖动']}，差 {round(_总 - _只, 1)}s")
        else:
            print("  [未验] 本轮无抖动 ⇒ 验不出『首跑被算进去』—— 这一半没验到")
else:
    print("  [未验] 没有账本 —— 不算通过")
    失败.append("⑥ 账本不存在（没验）")

print()
if 失败:
    print(f"覆盖面判据：红 {len(失败)} 项 —— " + "；".join(失败))
    sys.exit(1)
print("覆盖面判据：绿 —— 漏跑会被算出来、齐了不误报、账本字段自洽、合计含首跑")
