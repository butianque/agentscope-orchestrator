"""判据：**模型抽词不能自己凑答案**（问句里没有强术语时，模型词必须有共现证据）。

钉的漂移（2026-11-05，套件实测）：负对照「哞哞哞咩咩咩吽吽吽咕噜噜噗呲噗呲」
**偶发**返回 20 个文件（单跑是 0）。原因：模型那次把拟声词抽成了「声音」「拟声」
这类通用词，每个都能撞上一批文件 ⇒ 正是「能凑出几个最像的」= **假能力**。
⇒ 规则做成**确定性**的，不依赖"模型那次抽得好不好"：
   · 问句自身无强术语 + 模型词 ≥2 ⇒ 只认**同一文件共现 ≥2 个**；
   · 问句自身无强术语 + 模型词只有 1 ⇒ 它必须很罕见（df ≤ 3%，比"够专"更严）。

本判据用**合成语料**（不受真仓内容漂移影响），并**屏蔽模型**（monkeypatch 抽词）：
  ① **整批模型词都是常见词且互不共现** ⇒ 回空（这正是套件里那条漂移的确定性版本）；
  ② 同义词（固定点/不动点）共现 ⇒ 13 个文件全回来（**能力本体不许被误伤**）；
  ③ 单个模型词 ⇒ **信任**（不做共现检验；实测过：给单词加严闸会把真能力打死）；
  ④ 单个罕见词 ⇒ 正常返回；
  ⑤ 问句自身有强术语 ⇒ 与模型无关，照常返回。

★ 闸只对"**整批都是满仓通用词**"生效 —— 那正是拟声词被抽成「声音」「拟声」的样子。
  任何一条"含罕见词"的正常抽取都不许被拦（同一天为此翻车两次，详见 concept.py 注释）。
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from agentscope_orchestrator import concept as C  # noqa: E402

坏: list[str] = []


def _造语料() -> tuple[C.概念索引, list[Path]]:
    """400 个文件的合成语料；倒排手写，内容只是占位（不做切词）。"""
    根 = Path(tempfile.mkdtemp(prefix="concept_evi_"))
    文件们: list[Path] = []
    for i in range(400):
        名 = "x.lean" if i % 2 else f"f{i}.rs"
        子 = 根 / f"d{i % 20}"
        子.mkdir(parents=True, exist_ok=True)
        p = 子 / f"{i}_{名}"
        p.write_text(f"// {i}\n", encoding="utf-8")
        文件们.append(p)

    倒排: dict[str, list[int]] = {}
    倒排["通用词A"] = list(range(100, 120))           # 与 B 不交
    倒排["通用词B"] = list(range(200, 220))
    同样 = list(range(300, 313))                     # 同义词共现的 13 个文件
    倒排["固定点"] = list(同样)
    倒排["不动点"] = list(同样)
    倒排["中等常见"] = list(range(220, 240))          # df 20 / 400 = 5% > 3%
    倒排["罕见词"] = list(range(240, 250))            # df 10 / 400 = 2.5% ≤ 3%
    return C.概念索引(倒排, 文件们, 400), 文件们


def _召回(idx, 问句: str, 模型词: list[str], 上限: int = 20) -> dict:
    原 = C.模型抽词
    C.模型抽词 = lambda _q: list(模型词)             # noqa: ARG005 屏蔽真模型
    原缓存 = dict(C._抽词缓存)
    C._抽词缓存.clear()
    try:
        return idx.召回(问句, 上限文件=上限, 上限定理=上限)
    finally:
        C.模型抽词 = 原
        C._抽词缓存.clear()
        C._抽词缓存.update(原缓存)


def main() -> int:
    idx, _ = _造语料()
    无意义 = "哞哞哞咩咩咩吽吽吽咕噜噜噗呲噗呲"

    r1 = _召回(idx, 无意义, ["通用词A", "通用词B"])
    print(f"    ① 两个不共现的通用词：代码 {len(r1['代码'])} / 证明 {len(r1['证明'])} · {r1['说明'][:80]}")
    if r1["代码"] or r1["证明"]:
        坏.append(f"模型词不共现也凑出了答案（代码 {len(r1['代码'])}/证明 {len(r1['证明'])}）")

    r2 = _召回(idx, "那个反复作用到自己身上直到不再变的东西", ["固定点", "不动点"])
    print(f"    ② 同义词共现：代码 {len(r2['代码'])} / 证明 {len(r2['证明'])}")
    if len(r2["代码"]) + len(r2["证明"]) < 13:
        坏.append(f"真同义词共现却被误伤（只回 {len(r2['代码'])+len(r2['证明'])} < 13）")

    r3 = _召回(idx, 无意义, ["中等常见"])
    print(f"    ③ 单个模型词：代码 {len(r3['代码'])} / 证明 {len(r3['证明'])}（按设计**信任单词**）")
    if not (r3["代码"] or r3["证明"]):
        坏.append("单个模型词被拦 ⇒ 真能力会被误伤"
                  "（实测过：自然语召回 1.00 → 0.00/0.05，两次都是这样翻的车）")

    r4 = _召回(idx, 无意义, ["罕见词"])
    print(f"    ④ 单个罕见词：代码 {len(r4['代码'])} / 证明 {len(r4['证明'])}")
    if len(r4["代码"]) + len(r4["证明"]) < 10:
        坏.append(f"单个罕见词被误伤（只回 {len(r4['代码'])+len(r4['证明'])} < 10）")

    r5 = _召回(idx, "固定点", [])
    print(f"    ⑤ 问句自带强术语：代码 {len(r5['代码'])} / 证明 {len(r5['证明'])}")
    if len(r5["代码"]) + len(r5["证明"]) < 13:
        坏.append(f"问句自有术语被误伤（只回 {len(r5['代码'])+len(r5['证明'])} < 13）")

    if 坏:
        print("模型词证据闸：红 —— " + "；".join(坏))
        return 1
    print("模型词证据闸：绿 —— **整批常见词不共现 ⇒ 凑不出答案 · 真同义词不误伤 · "
          "单个模型词照信（否则真能力被打死）· 单个罕见词照常 · 问句自有术语优先**。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())