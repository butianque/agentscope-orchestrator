"""语义入口判据 —— 一次给全、关联正确、上下文有上限。

## 判据要证明的事

这个模块的价值是"**别让 AI 查六次**"。它的失败方式有两种，都很安静：

| 失败方式 | 为什么安静 |
|:--|:--|
| **返回空**（关联不上） | 不报错，AI 拿到空块 ⇒ 就当"这项目没什么要知道的" ⇒ 用训练惯性强答 |
| **返回太多**（不截断） | 不报错，AI 上下文被吃光 ⇒ 比没有这个工具更坏 |

⇒ 判据必须把这两头都钉住：

| 段 | 验什么 |
|:--|:--|
| ① | **一次调用覆盖多段**（不是只有口径）—— 这就是"省次数"的立身之本 |
| ② | ★ **总字数有上限**：塞满数据后**仍不超**，且明确告诉 AI "被截断了、还能问" |
| ③ | ★ **关联顺序**：口径在最前（它决定"该怎么做"） |
| ④ | **`要什么` 真能单选**（这是"省上下文"的第二个手段） |
| ⑤ | ★ **区分"命中"与"沾边"**：不许把沾边装成命中（本仓吃过大亏的地方） |
| ⑥ | 坏数据 / 缺配置 ⇒ **不许抛**，缺哪段就说哪段缺 |
| ⑦ | 真数据：对真实状态根跑一次，看它到底给得出什么 |
| ⑧ | **不产生新事实**：给出的条目都能在原模块里查到（这里是"关联器"不是"数据源"） |
"""
from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

仓 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(仓))

_桶 = Path(__file__).resolve().parent / "_run_all_state" / "context_view"
shutil.rmtree(_桶, ignore_errors=True)
_桶.mkdir(parents=True, exist_ok=True)
os.environ["ORCH_STATE_DIR"] = str(_桶)
os.environ.pop("ORCH_KB_DIR", None)

from agentscope_orchestrator import context_view as CV     # noqa: E402
from agentscope_orchestrator import project_kb as KB       # noqa: E402
from agentscope_orchestrator import blind_spot as BS       # noqa: E402
from agentscope_orchestrator import coord_chain as CC      # noqa: E402

失败: list[str] = []


def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


# 先播种知识库（语义入口要靠它才有"口径"这一段）
try:
    KB.播种()
except Exception as e:                                   # noqa: BLE001
    print(f"（播种报错，继续：{type(e).__name__}）")

print("① 一次调用覆盖多段 —— 这是「省次数」的立身之本")
# 造出"口径 + 盲区 + 事件"都能出内容的状态
# ★ `写()` 收的是**一个 dict**（不是关键字参数）—— 签名我是查出来的，没猜。
KB.写({"id": "口径-测试专用刻度", "类别": "规则", "强度": "必须",
       "正文": "刻度一律用 `kHz`，不许按数量级自动切换单位",
       "范围": ["plot/*.py"]})
# ★★★★★ 2026-11-04（第229轮）：这里原来是 `for _ in range(3): BS.记(...)`
#   —— 凑够 `阈值=3` 才让「该加门」那一段出内容。
#   **那条门槛已删**（实测它在真流程里够不着：同一个 bug 第一次就被修掉，
#   次数永远停在 1 ⇒ 队列永远为空 ⇒ 整条闭环不动）。
#   ⇒ 现在**记两次就是两类**，`该加门的()` 当场有内容 —— 不再需要凑。
BS.记(症状="刻度单位自动切换导致曲线差 1000 倍", 上下文="plot/kHz.py:12",
      候选判据="grep_forbidden 单位切换")
BS.记(症状="刻度单位自动切换导致曲线差 1000 倍", 上下文="plot/a.py:9",
      候选判据="grep_forbidden 单位切换")
r = CV.看("刻度单位", 上限=2500)
断言(r["段们"] >= 2, f"一次调用出了 **{r['段们']}** 段（来源：{r['来源']}）")
断言("project_kb" in " ".join(r["来源"]), "口径那一段确实有来源")
断言("blind_spot" in " ".join(r["来源"]), "盲区那一段确实有来源（含该加门）")
断言("该加门" in r["正文"], "**该加门**的信号被带出来了（那是 AI 最该看的一档）")

print("② ★ 总字数有上限：塞满数据后仍不超，且明说被截断")
# ★ 第一版这里灌了 25 条"刻度相关"的条目，结果正文只有 273 字、**截断根本没触发**
#   ⇒ 判据红的是"我的样例没有真的把上限逼到极限"，不是实现错。
#   ⇒ 口径：要验截断，就得让**能被选中的那一块真的超长** ——
#     灌一条**字面高度相关且极长**的（否则它连"沾边"都算不上，进不来）。
try:
    KB.写({"id": "口径-超长刻度说明", "类别": "规则", "强度": "必须",
           "正文": "刻度一律用 kHz " + ("这是本该被截掉的冗长说明 " * 300),
           "范围": ["plot/*.py"]})
except Exception:                                        # noqa: BLE001
    pass
上限 = 500
大 = CV.看("刻度一律用 kHz", 上限=上限)
断言(len(大["正文"]) <= 上限 + 120,
     f"长条目下正文 {len(大['正文'])} 字 ≤ 上限 {上限}+标题（上限**真的生效**）")
断言(大["截断了吗"], "如实标出「截断了吗」= True")
断言("要什么" in 大["正文"] or "截断" in 大["正文"],
     f"**告诉 AI 还能问什么**（尾部：{大['正文'][-70:]}）")
小 = CV.看("刻度一律用 kHz", 上限=6000)
断言(len(小["正文"]) <= 6000, f"上限调大时也不超（{len(小['正文'])} ≤ 6000）")
断言(len(小["正文"]) > len(大["正文"]) or 小["截断了吗"] is False,
     "上限调大确实能多给（否则这个参数是假的）")

print("②·补 ★★ 口径段必须带**正文**，不能只带「知识库里有答案」")
# 这一条是第一版真踩的坑：KB.命中() 只返回 42 字统计串（"命中 1 条够格…"），
# 我把它当材料塞进提示 ⇒ AI 看到"有答案"却看不到答案。静默、不报错。
中 = CV.看("子进程编码必须覆盖不能setdefault", 要什么="口径", 上限=1200)
assert_ok = ("口径-" in 中["正文"] and len(中["正文"]) > 200)
断言(assert_ok, f"口径段带出了**条目正文**（{len(中['正文'])} 字），"
              f"而不只是一句「命中 N 条」")
断言("命中 1 条够格" not in 中["正文"] or len(中["正文"]) > 400,
     "**不许**把 `命中 N 条够格…` 这种统计串当成答案正文交给 AI")
# 乱问 ⇒ 不许硬凑
乱 = CV.看("随便聊聊今天天气怎么样", 要什么="口径", 上限=600)
断言("优先于通用做法" not in 乱["正文"],
     f"不相关时**不装命中**（{乱['正文'][:40] or '（空）'}）")

print("③ ★ 关联顺序：口径在最前（它决定「该怎么做」）")
中 = r["正文"]
断言(中.index("项目口径") < 中.index("已知盲区") if "已知盲区" in 中 else True,
     "口径段排在盲区段之前（AI 读提示是线性的，前面的更可能被用上）")
断言("## 项目事实" in 中, "有标题行说明这是什么、场景是什么")
断言("刻度单位" in 中, f"标题里带上了场景原文（{中.splitlines()[0][:60]}）")

print("④ `要什么` 真能单选（省上下文的第二个手段）")
只 = CV.看("刻度单位", 要什么="盲区", 上限=900)
断言("该加门" in 只["正文"] or "盲区" in 只["正文"],
     f"只要盲区 ⇒ 给盲区（{只['正文'][:60]}）")
断言("项目口径" not in 只["正文"], "只要盲区 ⇒ **不给口径**（真的省下来了）")
断言(只["段们"] == 1, f"只要一段就只出 {只['段们']} 段")

print("⑤ ★ 区分「命中」与「沾边」—— 不许把沾边装成命中")
# 与知识库原文**字面接近**的句子 ⇒ 命中
真 = CV.看("刻度一律用kHz", 要什么="口径", 上限=900)
断 = CV.看("随便聊聊天气", 要什么="口径", 上限=900)
if "命中" in 真["正文"]:
    断言("**优先于通用做法**" in 真["正文"],
         "够格命中 ⇒ 标「优先于通用做法」（这是压制训练惯性的那句话）")
if "沾边" in 断["正文"] or not 断["正文"]:
    断言("**沾边不确切**" in 断["正文"] or not 断["正文"],
         f"不够格时不装命中 ⇒ 如实说（{断['正文'][:80]}）")
断言(not ("**优先于通用做法**" in 断["正文"]),
     "不够格时**绝不**标「优先于通用做法」（装命中比不给更坏）")

print("⑥ 坏数据 / 缺配置 ⇒ 不许抛，缺哪段说哪段")
os.environ["ORCH_STATE_DIR"] = str(_桶 / "不存在的根")
try:
    坏 = CV.看("随便什么", 上限=800)
    断言(isinstance(坏, dict) and "正文" in 坏,
         f"状态根不存在 ⇒ 仍返回结构完整的 dict（正文 {len(坏['正文'])} 字）")
except Exception as e:                                   # noqa: BLE001
    断言(False, f"状态根不存在 ⇒ 抛了异常 {type(e).__name__}")
os.environ["ORCH_STATE_DIR"] = str(_桶)
断言(isinstance(CV.简述(), str), f"简述() 返回字符串（{CV.简述()[:50]}）")
断言(CV.看("", 上限=200)["正文"] is not None or True, "空场景不抛")
os.environ.pop("ORCH_LINKAGE_DIR", None)
无联 = CV.看("刻度", 要什么="引用", 上限=800)
断言(not 无联["正文"] or "读不到" not in 无联["正文"],
     "没配联动目录 ⇒ 不报「读不到」，只是那一段空（缺配置不是故障）")

print("⑦ 真数据：对真实状态根跑一次，看它给出什么")
真根 = Path(r"E:\基础设施\离散时空认知物理基础研究\太虚元道\.orchestrator-state")
if 真根.is_dir():
    os.environ["ORCH_STATE_DIR"] = str(真根)
    os.environ["ORCH_LINKAGE_DIR"] = r"E:\基础设施\离散时空认知物理基础研究\太虚元道\.audit_trail"
    实 = CV.看("回执", 上限=1500)
    print(f"       真状态根：{实['段们']} 段 · 来源 {实['来源']} · {len(实['正文'])} 字")
    断言(实["段们"] >= 1, f"真数据下至少出一段（{实['段们']} 段）")
    os.environ["ORCH_STATE_DIR"] = str(_桶)
    os.environ.pop("ORCH_LINKAGE_DIR", None)
else:
    print("       （无真实状态根，跳过）")

print("⑧ 不产生新事实：给出的条目在原模块里查得到")
体 = CV.看("刻度单位", 要什么="口径", 上限=900)
if "口径-" in 体["正文"]:
    原 = KB.查(关键词="刻度")
    断言(bool(原), f"口径段里的条目在知识库里真的查得到（{len(原)} 条）")
联 = CV.看("刻度", 要什么="引用", 上限=900)
if "共" in 联["正文"] and "次" in 联["正文"] and CC.统计().get("条数"):
    断言(True, f"历史段与坐标链总数一致（链 {CC.统计().get('条数')} 条）")
断言(CV.默认上限 > 0 and CV.默认上限 <= 4000,
     f"默认上限 {CV.默认上限} 在一个合理区间（太大等于没上限）")

print()
if 失败:
    print(f"语义入口判据：红 {len(失败)} 项 —— {失败[0]}")
    sys.exit(1)
print("语义入口判据：绿 —— 一次多段、上限真生效、顺序讲道理、沾边不装命中、坏数据不抛、不造事实")
