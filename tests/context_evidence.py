"""判据：检索命中项要带**正文证据**（可引用的摘录），而不是只有一个文件名。

钉的真事故（2026-11-05，真通道 A/B 实测）：
同一个项目问题，无检索的模型回「不知道」；有检索的模型能回「关系式族差 41‰、
不如增删列表 50‰」——这两个数**只有本仓才有**，说明检索真的纠正了回答。
但它紧接着问「U-005 怎么裁决的」时仍回「不知道」：
因为 `context_view` 只给**文件名**，模型拿不到正文，只能从文件名里抠数字。

⇒ 修法：每类头一条后面补一小段正文摘录（硬上限 300 字）。

本判据只验 `_摘录` 这个纯函数（不碰真索引 ⇒ 不受仓内容变化影响）：
  ① 去 markdown **标记**但**留下内容**（表格/引用里也是正文）；
  ② 硬上限（含省略号）——一个文件不许吃掉整段预算；
  ③ 读不到 / 不是文件 ⇒ 空串，**绝不抛**（增强不是前提）；
  ④ 大文件（>2 MB）不读 ⇒ 空串（问答期不许被大文件拖住）；
  ⑤ ★ 关键词选窗：关键词写在文件**末尾**时，摘录必须落在关键词附近，而不是文件开头；
  ⑥ ★ 反例：把上限设成 10 时，① 必须真的变短 —— 否则"截断"是摆设。

★ ⑤⑥ 是第二版加的。第一版无脑取开头 300 字，结果那份文档里 U-005 的裁决
（写在「⚠️ 结论状态更新」表格里）既**够不到**（在第 600 字处）又被
"表格行整行丢掉"扔干净 ⇒ 摘录看着正常、恰好缺了要证据的那一句。
口径：**证据要落在问题附近，不是落在文件开头；表格里也是正文。**
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from agentscope_orchestrator import context_view as V  # noqa: E402

坏: list[str] = []


def main() -> int:
    根 = Path(tempfile.mkdtemp(prefix="ctx_evi_"))
    有格式 = 根 / "带格式.md"
    有格式.write_text(
        "# 大标题（标记去掉，内容留下）\n\n> 引用行\n\n"
        "**结论**：关系式族差 41‰，不如增删列表 50‰。\n"
        "| 表格里的数 | 也不许丢 |\n"
        "第二段正文继续。\n",
        encoding="utf-8")
    摘 = V._摘录(有格式)
    print(f"    ① 摘录：{摘!r}")
    if not 摘:
        坏.append("有正文的文件却取不到摘录")
    if "\n" in 摘:
        坏.append("摘录里含换行 ⇒ 会把版面塞进上下文")
    if "41‰" not in 摘 or "50‰" not in 摘:
        坏.append("摘录丢了正文里的关键数据（41‰/50‰）")
    # ★ 表格**内容**必须留下（第一版把整行丢了，恰好丢掉证据）
    if "也不许丢" not in 摘:
        坏.append("表格里的内容被整行丢掉了 ⇒ 证据可能就在表格里")
    for 禁 in ("#", "> ", "|"):
        if 禁 in 摘:
            坏.append(f"摘录里残留 markdown 标记 {禁!r}")

    # ⑤ 关键词选窗：关键词在文末 ⇒ 摘录要落在文末附近，不许只取开头
    头重脚轻 = 根 / "头重脚轻.md"
    头重脚轻.write_text(
        "开头全是背景铺垫。" * 80 + "\n\n## 裁决\nU-005 机证：选 C 承认边界。\n",
        encoding="utf-8")
    摘窗 = V._摘录(头重脚轻, 关键词="U-005 裁决", 上限=120)
    print(f"    ⑤ 关键词选窗：{摘窗!r}")
    if "选 C" not in 摘窗:
        坏.append("关键词在文末时摘录没落在它附近（仍是文件开头）⇒ 证据够不到问题")

    # ② 硬上限
    长 = 根 / "很长.md"
    长.write_text("甲乙丙丁" * 500, encoding="utf-8")
    摘长 = V._摘录(长, 上限=50)
    print(f"    ② 上限 50：长度 {len(摘长)} · 结尾={摘长[-6:]!r}")
    if len(摘长) > 50:
        坏.append(f"上限没生效：{len(摘长)} > 50")

    # ③ 读不到 ⇒ 空串
    print(f"    ③ 不存在的文件：{V._摘录(根 / '没有这个文件.md')!r}")
    if V._摘录(根 / "没有这个文件.md") != "":
        坏.append("不存在的文件没回空串")
    if V._摘录(根) != "":
        坏.append("传目录没回空串")

    # ④ 大文件不读
    大 = 根 / "大.md"
    with 大.open("wb") as f:
        f.seek(3 * 1024 * 1024)
        f.write(b"x")
    摘大 = V._摘录(大)
    print(f"    ④ 3MB 文件：{摘大!r}")
    if 摘大 != "":
        坏.append("大文件被读了（问答期会被拖住）")

    # ⑤ 反例：上限 10 必须真的更短
    摘十 = V._摘录(有格式, 上限=10)
    print(f"    ⑤ 上限 10：{摘十!r}（长度 {len(摘十)}）")
    if len(摘十) >= len(摘):
        坏.append(f"上限 10 没让结果变短：{len(摘十)} >= {len(摘)}")

    if 坏:
        print("检索证据：红 —— " + "；".join(坏))
        return 1
    # ⑦ 预算常量：文档摘录必须够长到能装下"结论 + 裁决"两句（实测 300 差 40 字）
    预算 = getattr(V, "文档摘录上限", 0)
    print(f"    ⑦ 文档摘录上限：{预算} 字（默认总预算 {V.默认上限}）")
    if 预算 < 400:
        坏.append(f"文档摘录上限 {预算} < 400 ⇒ 300 字时实测截在裁决前一句，"
                  "答不出「最后选了什么」")
    if 预算 >= V.默认上限 // 2:
        坏.append(f"文档摘录上限 {预算} 占了总预算一半以上 ⇒ 其余各段没地方放")
    print("检索证据：绿 —— **命中项带得动正文（去标记、压一行、硬上限、读不到不抛、大文件不读）**。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())