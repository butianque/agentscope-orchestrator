# -*- coding: utf-8 -*-
"""判据：「本项目相关文件」这一段**真能从记忆索引按名字取回**（不是遍历）。

它守的是本轮最要紧的一根线：索引建好了，**必须有人读**。
改之前 `context` 只查知识库与坐标链 ⇒ 看不见项目本体的 4,354 个文件
——「驱动不了的接线，等于没有接线」。

★ 三条硬读数：
  ① 三样真名字（**定理 / Rust 符号 / 审计回执**）各自取回**正确且存在**的路径；
  ② 假名字必须**报"没命中"**，且返回里不许出现任何路径（区分力）；
  ③ 命中要说清**怎么命中的**（精确/后缀/前缀/包含）—— 差一点看着像就是它，
     所以档位本身要被断言，不只是"有结果"。
"""

from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

这里 = Path(__file__).resolve().parent
仓 = 这里.parent
sys.path.insert(0, str(仓))

_桶 = 这里 / "_run_all_state" / "context_files"
shutil.rmtree(_桶, ignore_errors=True)
_桶.mkdir(parents=True, exist_ok=True)
os.environ["ORCH_STATE_DIR"] = str(_桶)

from agentscope_orchestrator import autoengine as ae      # noqa: E402
from agentscope_orchestrator import context_view as CV    # noqa: E402

失败: list[str] = []


def 断言(条件, 说明):
    print(f"  {'ok  ' if 条件 else 'FAIL'} {说明}")
    if not 条件:
        失败.append(说明)


def 取(词: str) -> str:
    return CV.看(场景=词, 要什么="文件", 上限=2000)["正文"]


print("context_files：按名字取回（定理 / 代码 / 回执）")

# ── ① 三样真名字 ────────────────────────────────────────────────────
体 = 取("verdict_exhaustive")
断言("OrchJudge.verdict_exhaustive" in 体 and ".lean" in 体,
     "① 定理：裸名 `verdict_exhaustive` 取回点式键与 .lean"
     "（改前 `query()` 裸名返回 None —— 这一步是断的）")
断言("后缀" in 体,
     "① 命中档位如实标为**后缀**（键是点式模块键，人只说裸名）")

体 = 取("自主认知齐备度")
断言("自主认知齐备度.rs" in 体 and "精确" in 体,
     "② Rust 符号：`自主认知齐备度` 精确命中 `自主认知齐备度.rs`")

体 = 取("回执255")
断言("回执255_自主认知齐备度三红转绿" in 体,
     "③ 审计回执：**前缀**命中，且名字长的那一份没被截掉"
     "（改前按键长升序排 ⇒ 最相关的一份被截）")

# ── ② 假名字不许"勉强命中" ──────────────────────────────────────────
体假 = 取("绝无此名zzz")
断言("没命中" in 体假, "假名字报「没命中」")
断言(".md" not in 体假 and ".rs" not in 体假 and ".lean" not in 体假,
     "假名字的返回里**没有任何路径**（区分力：不是只要调用就回一堆）")
断言("不是「这一类没进索引」" in 体假,
     "假名字还要说清是「都没这个名字」而不是「这一类没进索引」"
     "—— 这两种「没有」在返回里必须长得不一样")

# ── ③ 覆盖数必须是**文件数**，且与逐条对账一致 ───────────────────────
idx = ae.项目索引()
覆盖 = getattr(idx, "_覆盖", None) or {}
逐条 = list(覆盖.get("逐条") or [])
体 = 取("自主认知齐备度")

# ★ 必须按**逐条声明**报（不是按类合并）：合并根会让
#   「`.audit_trail` 有多少份 .md」**从返回里拆不出来** ——
#   一个 A/B 子代理正是卡在这里、只能回退去列目录。判据替它把这条钉住。
from agentscope_orchestrator.context_view import _逐条读数行   # noqa: E402
_条行 = _逐条读数行(逐条)
断言(_条行 in 体,
     f"逐条声明各自报出根与命中数（**调用同一个渲染函数**，不手抄期望串 "
     f"—— 我栽过两次假红）：{_条行}")
_文件数 = sum(条["命中"] for 条 in 逐条)
_键数 = sum(idx.count(条["kind"]) for 条 in 逐条)
断言(f"合计 **{_文件数}**" in 体,
     f"合计要等于逐条之和（同一件事不许两个数）：{_文件数}")
断言(_键数 != _文件数 and f"合计 **{_键数}**" not in 体,
     f"报的是**文件数**（{_文件数}）不是键数（{_键数}）"
     "—— 每个文件注册两个键，混用会让 4,361 变成 8,700 级")

# ★★ 最强的一条：`.audit_trail` 的份数要能被**独立数真盘**对上。
#    这直接覆盖 A/B 里那个失败点（合并声明 ⇒ 数字不可拆、不可对账）。
import fnmatch as _fn                                     # noqa: E402
import os as _os                                          # noqa: E402
from agentscope_orchestrator import profile as _pf        # noqa: E402
_真数 = 0
for _d, _子, _fs in _os.walk(Path(_pf.get_profile().repo_root) / ".audit_trail"):
    _真数 += sum(1 for _f in _fs if _fn.fnmatch(_f, "*.md"))
_审计条 = [x for x in 逐条 if ".audit_trail" in x["roots"]]
断言(len(_审计条) == 1,
     f"`.audit_trail` 必须**自成一条**声明（实得 {len(_审计条)} 条）"
     "—— 合并根会让份数不可拆")
断言(_审计条[0]["命中"] == _真数,
     f"`.audit_trail` 份数：索引 {_审计条[0]['命中']} vs 独立数真盘 {_真数}")
断言(f"**{_真数}**" in 体,
     f"这个份数**写在返回里**（{_真数}）—— 问「多少份」不该再去列目录")

# ── ④ 档位排序：精确 > 后缀 > 前缀 > 包含 ───────────────────────────
from agentscope_orchestrator.index import UnitIndex          # noqa: E402

小 = UnitIndex()
for k in ("包含abc尾", "abc前缀_这个", "尾.abc", "abc"):
    小.register(k, Path("x"))
序 = [k for k, _ in 小.找("abc", 上限=10)]
断言(序 == ["abc", "尾.abc", "abc前缀_这个", "包含abc尾"],
     f"四档排序 = 精确>后缀>前缀>包含（实得 {序}）")

# ── ⑤ 缓存与刷新：不许每次都重建，也不许偷偷用过期的 ─────────────────
a, b = ae.项目索引(), ae.项目索引()
断言(a is b, "两次取索引是**同一个对象**（进程内缓存 —— 实测全量建库 4.8 秒，"
             "不许每次调用都重建）")
断言(ae.索引年龄() >= 0, f"索引年龄可读（{ae.索引年龄():.1f} 秒）"
                         "—— 「新不新」必须看得见，不许静默过期")
c = ae.项目索引(刷新=True)
断言(c is not a and ae.索引年龄() < 5,
     "`刷新=True` 拿到的是**新对象**且年龄归零（有显式刷新入口）")

# ── ⑥ 自动更新：过了年龄预算**自己重建**，且重建次数是**读得出来的数** ──
d = ae.项目索引(最长年龄=-1)
断言(d is c, "`最长年龄=-1` 时不因年龄重建（判据要能拿到稳定快照）")
# ★ 边界（我第一版就在这里栽过）：预算写 `0` 时，如果 `龄` 恰好是 `0.0`
#   （两次 `time.time()` 落在同一刻度），`龄 > 0` **合法地为假** ⇒ 不重建。
#   那不是机制错，是判据踩在边界上 —— 所以给一个**真实的等待窗**。
import time as _t                                       # noqa: E402
_t.sleep(0.05)                                          # 50 毫秒 ≫ 时钟刻度
次数0 = ae.索引重建次数()
e = ae.项目索引(最长年龄=0.001)
断言(e is not d and ae.索引重建次数() == 次数0 + 1,
     f"预算 0.001 秒、已过 50 毫秒 ⇒ **自动重建**"
     f"（重建次数 {次数0} → {ae.索引重建次数()}）"
     "—— 这就是「随工程进度自动更新」的机制；MCP 服务是长驻进程，"
     "没有它就会全程用几小时前的旧读数")
断言(0 <= ae.索引年龄() < 5, f"重建后年龄归零（{ae.索引年龄():.1f} 秒）")
体 = 取("自主认知齐备度")
断言("重建过" in 体 and "秒前" in 体,
     "「这次建好多久了 / 本进程重建过几次」写在返回里 —— 新不新看得见")

# ── ⑦ 场景是**一句话**时，不许报假「没有」 ──────────────────────────
#   实测踩过：场景「自主认知齐备度 相关的文件都有哪些」整串拿去查索引
#   ⇒ 报「**没命中**」，而 `自主认知齐备度.rs` 明明在索引里。
#   按本仓口径 —— **「看不见」不能当「没有」**。
体自 = 取("自主认知齐备度 相关的文件都有哪些")
断言("自主认知齐备度.rs" in 体自,
     "自然语言场景**拆词后能命中**（整串查会报假「没有」）")
断言("用词" in 体自, "命中处标出**是用哪个词**查到的（不许含糊）")
体假2 = 取("绝无此名zzz 这个词有没有")
断言("我拿这些词查过" in 体假2,
     "拆词后仍没有 ⇒ 要说清**我拿哪些词查过**，而不是笼统说「都没有这个名字」")

print()
if 失败:
    print(f"context_files：红 {len(失败)} 项 —— {失败}")
    sys.exit(1)
print("context_files：绿 —— 定理/代码/回执三类真名字都能**按名字取回**，"
      "假名字不勉强命中，档位与覆盖数如实标注，缓存与刷新都看得见")
