def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


def 未验注(说明: str) -> None:
    print(f"  [未验] {说明}")
    未验.append(说明)


def 指向(root: Path) -> None:
    """把 ORCH_STATE_DIR 指到某个状态根 —— 台账读哪儿由它定（`blind_spot._根()`）。"""
    os.environ["ORCH_STATE_DIR"] = str(root)


def 驱动(*函数们) -> str:
    """驱动**真函数**，把它打给人看的那几行抓回来（判据看的就是这几行）。"""
    缓 = io.StringIO()
    del D._硬阻塞[:]                        # 逐段隔离：上一段的硬阻塞不许串到这一段
    with contextlib.redirect_stdout(缓):
        for f in 函数们:
            f()
    return 缓.getvalue()


def 行(键: str, 状态: str, 验证: str = "") -> dict:
    """一条台账行 —— 字段名**照真库抄**（真库：`.orchestrator-state/blind_spots/台账.jsonl`）。"""
    return {"键": 键, "症状": f"夹具-{键}", "原始症状": f"夹具-{键}\n", "上下文": "夹具",
            "候选判据们": [], "来源们": ["fixloop:轮1:修前修后"], "次数": 1,
            "首次": "2026-11-04T11:11:55", "最近": "2026-11-04T11:32:46",
            "状态": 状态, "门名": f"门-{键}", "否决理由": None,
            "最近证据": "夹具证据", "验证": 验证,
            "判法": "反例实测" if 验证 else "", "核对证据": "",
            "试件结果": None, "假阳性结果": None, "同类结果": None, "同类数": 0}


def 写台账(root: Path, 行们: list[dict]) -> Path:
    d = root / "blind_spots"
    d.mkdir(parents=True, exist_ok=True)
    (d / "台账.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in 行们),
        encoding="utf-8", newline="")
    return root


def 接线行(出: str) -> str:
    """从输出里挑出 `[闭环接线]` 那一行 —— 它是本判据盯的那句读数。"""
    for ln in 出.splitlines():
        if "[闭环接线]" in ln:
            return ln.strip()
    return ""


def 驱动带根(根: Path) -> str:
    """驱动 `check_blind_loop(源码根=…)` —— **判法可注入**是这一段的判据前提。

    ★ 为什么要把 `TypeError` 转成一条 FAIL：`源码根` 这个参数就是「判法能翻条件」
      本身。旧版 `check_blind_loop()` 没有它 ⇒ 抛 `TypeError`；**崩掉也算红**，
      但红得没法读（`run_all` 只会说「这项自己崩了」，看不出红在哪）。
      ⇒ 转成明确的 FAIL，红报告照样能一路报到尾。
    """
    try:
        return 驱动(lambda: D.check_blind_loop(源码根=根))
    except TypeError as e:
        说明 = f"`check_blind_loop(源码根=…)` 调不通 ⇒ **判法不可注入**：{e}"
        print(f"  FAIL {说明}")
        失败.append(说明)
        return ""


def 写源(目录: Path, 名: str, 内容: str) -> Path:
    目录.mkdir(parents=True, exist_ok=True)
    (目录 / 名).write_text(内容, encoding="utf-8", newline="")
    return 目录


