#!/usr/bin/env python
"""体检报告不许写死现状：`doctor` 说「闭环走到哪一步」必须能从事实推出来。

## 这支判据要证明什么

`doctor.py` 里原来有**写死的现状断言**（`doctor.py:523` 与 `:615`）：

```
· 闭环后半段（`提为门` / `验门`）❌ **只有判据里调**
```

**前半句已经过期**：`验门` 早接进了真流程（真库台账里躺着验证读数），
而报告还在说「没人调」；`提为门` 那一句**正在被改**（另一个队友在把它接进
修复环出口）。⇒ 判法**不许写死任何一个方向**，必须**跟着事实翻**。

| 段 | 验什么（全部**驱动真函数**：`doctor.check_blind_loop` / `doctor.check_dispatch`）|
|:--|:--|
| ① | 台账里有 `验证=拦得住` 的行 ⇒ 必须报出**读数行数**；且**不许**出现「只有判据里调」这类话 |
| ② | 台账空（指向空目录）⇒ 必须明说「**还没有一条走过**」，不许沉默、不许报成已闭合 |
| ③ | 台账有行但**没有一行有验证读数** ⇒ 仍须说「还没有一条走过」（**不是**「非空就算走过」）|
| ④ | `提为门`：`ast` 造四个目录 —— **直调** / **经包装函数** / 只写在注释与文档字符串里 / 自调 ⇒ 判法**跟着翻** |
| ⑤ | 分工线：同样的 `该加门` 计数，**动作按读数分档**翻（造不出门 ⇒ 攒知识 ≠ 其余 ⇒ 去提门）|
| ⑥ | 真件：真库台账若含验证读数 ⇒ 用它驱动一次，过期话**在真状态上也不许出现** |
| ⑦ | 报告里「卡在」的说法与扫描**打架** ⇒ 两个方向都要当场指出来（静默转述 = 两句都像真的）|

★ 判法**不许「读源码里有没有某个字符串」来判接线** —— 这既是被判的对象，
  也是本判据自己的纪律：只手算 `ast` 与台账。

## ⑷ 那一档为什么要单独列（本轮实测，不是假想）

判「`提为门` 接没接」时，**真流程接的常常不是它本身，而是同模块的包装函数**：
实测 `fixloop.py:1669` 调的是 `blind_spot.提该加门的`，由它转调 `提为门`
（`blind_spot.py:688/695/702/724/728/735/738`）。
⇒ 只问「有没有**直调点**」会答「没有」，于是报告说
  「**还没接** ⇒ 该接进修复环出口」—— **而出口那时候已经接了**。
  那句建议会让人去接一条**已经接上的线**；这就是本仓反复栽的病：
  **一句过期的话，比没有话更坏。**
⇒ 判法改成「**真流程可达**」：直调 **或** 经（可再往上追的）包装函数；
  上游是**扫出来的**，不写死函数名（写死就等于换个包装函数又过期一次）。
"""

