"""分工线判据：盲区台账 + 分工裁定 —— 「机器做能判的，LLM 做需要知识的」。

## 判据要证明的事

这两个模块是**整件事的收口**（前面三根柱子是地基），所以判据要盯住
"它到底有没有真的分流"，而不是"函数返回了字符串"：

| 段 | 要证明的 |
|:--|:--|
| ① | **有判据 ⇒ 机器判，绝不叫 LLM**（有确定答案的地方不留不确定性） |
| ② | **知识库命中 ⇒ 照知识做，绝不叫 LLM**（人写的优先于模型先验） |
| ③ | **已知盲区 ⇒ 交 LLM 但附上次的候选判据**（不重复造轮子） |
| ④ | **真盲区 ⇒ 交 LLM 且要求留判定依据**（这是新门的原料） |
| ⑤ | **同一类症状只累加次数、不新建条目**（次数是"该不该加门"的唯一客观依据） |
| ⑥ | **归一化真的起作用**：同一类问题换个路径/行号/哈希，仍算同一个盲区 |
| ⑦ | 次数达阈值 ⇒ **要求加门**；提为门必须留门名；否决必须留理由 |
| ⑧ | 台账**坏了也不许抛**（只读工具崩掉比返回"读不了"更糟） |

★ ⑥ 是这套东西的**命门**：不做归一化的话，同一类问题每次路径都不同 ⇒
  每次都算新盲区 ⇒ 次数永远是 1 ⇒ **永远不会触发加门** ⇒ 台账变成一堆
  没人看的条目。判据专门用"同症状换路径/行号/哈希"验这一点。
"""
