def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


print("① 有判据 ⇒ 机器判，绝不叫 LLM")
r = D.裁(命令=["cargo", "check"], 证据="", 判据已命中=True, 判据说明="compile 门真跑退出码")
