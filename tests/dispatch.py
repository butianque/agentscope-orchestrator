断言(not r.要求留依据, "机器判的情况下**不**要求 LLM 留依据（根本没用 LLM）")

print("② 知识库命中 ⇒ 照知识做，绝不叫 LLM")
# 真种一条知识进测试桶，然后问一个**症状完全对得上**的问题
