断言(st0.get("条数", 0) > 0, f"先把随包种子播进测试桶（{st0.get('条数')} 条）")
# 取一条真知识的症状文本当问句 —— 保证能命中
一条 = K.查()[0]
症状 = (一条.get("正文") or "")[:120]
r2 = D.裁(命令=["pytest", "-q"], 证据=症状)
断言(r2.该谁 in ("知识", "台账"),
     f"问一个知识库写过的症状 ⇒ 走知识/台账而**不是**直接甩给 LLM（{r2.该谁}）")
断言(r2.该谁 == "知识", f"且应当是『知识』这一档（人写的优先）（{r2.为什么[:46]}）")
断言(bool(r2.依据.strip()), "命中的知识**原文**要被带出来（不然等于没命中）")

print("③ 真盲区 ⇒ 交 LLM 且要求留判定依据")
怪 = "某个从来没有判据也没有知识覆盖的怪现象XYZ-" + "9" * 8
r3 = D.裁(命令=["run", "x"], 证据=怪)
断言(r3.该谁 == "LLM", f"没有任何东西能答 ⇒ 只能交 LLM（{r3.为什么[:46]}）")
断言(r3.要求留依据, "★ 交给 LLM 时**必须**要求它留判定依据")
断言(r3.记盲区, "★ 且这一步要记盲区 —— 盲区是『下次该加什么门』的原料")
交代 = D.给LLM的交代(r3)
断言("判定依据" in 交代, "给 LLM 的交代里写明『答完必须写清判定依据』")

print("④ 同一类症状 ⇒ 只累加次数，不新建条目（次数是加门的客观依据）")
e1 = D.记这次(证据=怪, 上下文="ctx", 候选判据="想到的判据甲")
e2 = D.记这次(证据=怪, 上下文="ctx", 候选判据="想到的判据乙")
断言(e2["次数"] == 2, f"同一症状记两次 ⇒ 次数累加到 {e2['次数']}（不是两条次数为 1 的）")
断言(B.统计()["条数"] == 1 or B.统计()["条数"] <= 3,
     f"台账条数没有随记录次数线性增长（{B.统计()['条数']} 条）")

print("⑤ ★ 归一化真的起作用：换路径/行号/哈希，仍算同一个盲区（命门）")
a = "AssertionError: want staged, got convergence_failed in C:\\proj\\a.py:124"
b = "AssertionError: want staged, got convergence_failed in D:\\other\\b.py:999"
断言(B._症状键(a) == B._症状键(b),
     f"同症状换路径与行号 ⇒ 归一化后**相同**（{B._症状键(a)[:52]}）")
# ★ 换易变片段时**必须保持同样的句子结构、同样的槽位**：
#   第一版拿"有没有那两段"不同的句子去比（一边带哈希/时刻、一边不带），
#   归一化后当然不等 —— 那**不是归一化没做干净，是我在比两个不同的句子**。
#   ⇒ 口径：测"归一化吃掉易变值"要**固定结构、只换值**。
c = "AssertionError: want staged, got convergence_failed in E:\\x\\z.py:77"
断言(B._症状键(a) == B._症状键(c),
     f"同结构、换盘符/目录/文件名/行号 ⇒ 归一化后**仍相同**（{B._症状键(c)[:60]}）")
# ★ 单独验"哈希与时刻"：**必须与上面的句子分开测**。
#   前三版样例我都在比"结构不同的两个句子"（一边有 `<哈希> <时刻>` 两个槽、一边没有），
#   归一化后当然不等 —— 那不是归一化不行，是**我在比两个不同的句子**。
#   这里给出一个**同一模板的两个实例**：只换哈希值和时刻值，槽位一个不少。
h1 = "hash deadbeef1234 at 2026-11-03T16:00:00 failed"
h2 = "hash cafebabe5678 at 2027-01-01T00:00:00 failed"
断言(B._症状键(h1) == B._症状键(h2),
     f"同模板、只换哈希与时刻的值 ⇒ 归一化后**相同**（{B._症状键(h1)}）")
d = "AssertionError: want promoted, got convergence_failed in C:\\proj\\a.py:124"
断言(B._症状键(a) != B._症状键(d), "但症状词不同（want staged vs want promoted）⇒ **必须不同**")
n0 = B.统计()["条数"]
B.记(a)
n1 = B.统计()["条数"]
B.记(b)
n2 = B.统计()["条数"]
断言(n1 == n0 + 1 and n2 == n1,
     f"归一化让跨路径的同类问题**不新建条目**（{n0}→{n1}→{n2}）")

print("⑥ ★ **记下即提** ⇒ 要求加门；提为门留门名；否决必须留理由")
真怪 = "这是一个会反复出现的怪现象" + "Z" * 6
# ★★★★★ 2026-11-04（第229轮）：这里原来验的是"记满 阈值-1 次 ⇒ 还不要求加门"。
#   **那条门槛删了** —— 实测它在真流程里够不着：同一个 bug 第一次就被模型修掉，
#   次数永远停在 1 ⇒ 队列永远是空的 ⇒ 整条闭环永远不动。
#   ⇒ 现在验**反过来的那条**：**记一次就必须进队列**。
B.记(真怪)
该 = [x for x in B.该加门的() if x["症状"] == B._症状键(真怪)]
断言(bool(该), f"**记一次就在队列里**（不作门槛）（{len(B.该加门的())} 个在等）—— "
              f"否则 自动验门 没原料，验过拦得住的永远是 0")
断言(B.阈值 is None, f"门槛已废止（`B.阈值` 应为 None，实得 {B.阈值!r}）")
# ★ `次数` 换职责后仍要起作用：多记几次，它就该排到队首
for _ in range(3):
    B.记(真怪)
该 = [x for x in B.该加门的() if x["症状"] == B._症状键(真怪)]
断言(bool(该) and int(该[0].get("次数", 1)) >= 4,
     f"**次数照旧累加**且排到队首（次数 {int(该[0].get('次数', 1)) if 该 else '?'}）"
     f"—— 这是 `次数` 换职责后唯一还在起作用的地方")
键 = 该[0]["键"]
断言(B.提为门(键, "test_counts"), "提为门成功")
断言(not any(x["键"] == 键 for x in B.该加门的()), "提为门后**不再**出现在『该加门』里")
_行 = [x for x in B.查(只待加门=False, 上限=99) if x["键"] == 键][0]
断言(_行.get("门名") == "test_counts", f"留了门名（{_行.get('门名')}）—— 否则下次无法核对门还在不在")
try:
    B.否决(键, "")
    断言(False, "否决留空理由**应当抛**")
except ValueError as e:
    print(f"  ok   空理由的否决被拒（{str(e)[:44]}）")
断言(B.否决(键, "这是环境偶发，不值得加门"), "有理由的否决成功")
_行2 = [x for x in B.查(只待加门=False, 上限=99) if x["键"] == 键][0]
断言(_行2.get("状态") == "已否决" and _行2.get("否决理由"),
     f"否决状态与理由都留了（{_行2.get('否决理由')[:26]}）")

print("⑦ 已知盲区 ⇒ 交 LLM 但附上次的候选判据（不重复造轮子）")
二怪 = "另一个会反复出现的怪现象" + "Y" * 6
B.记(二怪, 候选判据="候选判据：按编码检测")
B.记(二怪, 候选判据="候选判据：比对首行字符")
# ★ 直接验"台账提示块"本身，而不是绕道 `D.裁` ——
#   因为 `裁` 的步骤是 判据→**知识库**→台账，而"怪现象"这类文本
#   总会蹭到一两个常见词元（实测：最高分 0.0052、命中 2 词元）。
