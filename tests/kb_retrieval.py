"""外挂知识库（project_kb）的机判：检索能不能命中、改完能不能立刻查到。

★★★ 为什么需要这组判据（2026-11-03 的真事故）：
  外挂知识库**功能完整、注入链路接通、每次真跑都在注入** —— 但它一直是**空转**：
    ① 库是 0 条 ⇒ `注入()` 返回空串；
    ② 检索算法是「整串子串匹配」，而唯一真调用方传进来的是一整段红门证据（几百字）
       ⇒ 必然零命中；更糟的是调用方**连关键词都没传**，注入的是固定 700 字前缀。
  两个缺陷叠加的效果是：**看起来在接、实际一条都到不了模型**。
  而这件事**没有任何判据会红** —— 注入空串不是错误，修复主链照跑。
  ⇒ 所以必须有这组判据：把"知识真的能被查到"变成会红的东西。

判据分四层：
  ① 真症状 → 真条目（拿**本轮真出现过的红门证据原文**当查询）
  ② 无关查询不该塞东西（防"反正都注入"退化成噪声）
  ③ 机制：陈旧索引 / 缺索引 / 空库 / 目录不存在，四种情况都不许"静默查不到"
  ④ 元判据：每条正文必须含「症状：」—— 只有"修法"没有"症状"的条目**检索不到**
"""
import os
import atexit
import shutil
import sys
import tempfile
from pathlib import Path

仓 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(仓 / "src"))
# ★ 必须**钉死**被测对象，不能用 setdefault 继承外部环境：
#   否则调用方一旦导出了 ORCH_KB_DIR（比如指到空目录做对照臂），
#   这条判据会拿空库去跑，然后报"检索失败" —— 而它测的根本不是仓库里的知识。
#   这正是本仓刚立的禁则「判据不许依赖调用方环境」用在自己身上的样子。
os.environ["ORCH_KB_DIR"] = str(仓 / "src" / "agentscope_orchestrator" / "kb_seed")

from agentscope_orchestrator import project_kb as K  # noqa: E402

失败 = []


def 断言(条件, 说明: str) -> None:
    if 条件:
        print(f"  ok   {说明}")
    else:
        print(f"  FAIL {说明}")
        失败.append(说明)


# ══ ① 真症状 → 真条目 ═══════════════════════════════════════════════════════
print("① 真症状能不能查到对应的那条知识")
情形 = [
    ("GBK 判据编码",
     "cause=退出码不符|期望0实得1 · rc=1 · err=UnicodeEncodeError: 'gbk' codec "
     "can't encode character '\\ufffd' —— 子进程输出中文 JSON 被按 GBK 写出、按 UTF-8 读入",
     "口径-子进程输出编码自钉"),
    ("测试计数错位",
     "cause=计数不符|期望 passed=10 实得 passed=0 · 文=passed=10 failed=3 skipped=0",
     "口径-计数解析key前缀优先"),
    ("聚合层 rc=None",
     "error=TypeError: '>' not supported between instances of 'NoneType' and 'int' · 门数=0",
     "口径-聚合rc要容忍None"),
    ("顶层 cmd 未补进门",
     "cause=未知|regression_parity 需要 baseline_cmd 与 cmd 两条命令 · rc=1",
     "口径-顶层cmd要补进门"),
    ("门类型被判非法",
     "任务书驳回|非法判据门规格项：type 须属于 [axiom_footprint, compile, differential]",
     "口径-门类型清单从执行分支数出来"),
    ("接线判据拿下游随机结果断言",          # 2026-11-03 第211轮：mcp_smoke 套件下抖动
     "FAIL mcp_smoke.py · AssertionError: want staged, got convergence_failed: None · rc=1",
     "口径-下游随机结果不当上游判据"),
]
for 名, 证, 期望 in 情形:
    块 = K.注入(关键词=证, 上限字=700)
    断言(期望 in 块, f"{名}：注入块命中 `{期望}`（块 {len(块)} 字）")

# ══ ② 无关查询不许塞东西 ═════════════════════════════════════════════════════
print("② 无关查询不该被塞进任何条目")
_无关 = K.注入(关键词="今天下午天气不错，适合出门散步买杯奶茶", 上限字=700)
断言(_无关 == "", f"无关查询 ⇒ 注入块为空（实得 {len(_无关)} 字）")

# ══ ③ 机制：四种"看起来在接、实际查不到"的情况 ══════════════════════════════
print("③ 机制：陈旧索引 / 缺索引 / 空库 / 目录不存在")
_真库 = os.environ.get("ORCH_KB_DIR")
_临时 = Path(tempfile.mkdtemp(prefix="kb判据-"))
atexit.register(shutil.rmtree, _临时, ignore_errors=True)  # 跑完不留临时目录（包根会脏）
try:
    os.environ["ORCH_KB_DIR"] = str(_临时)
    # 空库：不许炸，返回空串
    try:
        空 = K.注入(关键词="随便什么", 上限字=700)
        断言(空 == "", "空库 ⇒ 注入块为空且不抛异常")
    except Exception as e:                       # noqa: BLE001
        断言(False, f"空库不许抛异常（实得 {type(e).__name__}: {e}）")

    # 人写一条 md（**不重建索引**）—— 必须能立刻查到
    (_临时 / "items").mkdir(parents=True, exist_ok=True)
    (_临时 / "items" / "手改条.md").write_text(
        "---\nid: 手改条\n类别: 规则\n强度: 必须\n来源: 判据\n等级: SOLID\n版本: 1\n---\n"
        "症状：`某个奇奇怪怪的报错 XYZ123` 出现。修法：照做就行。\n", encoding="utf-8")
    块 = K.注入(关键词="遇到报错 XYZ123 该怎么办", 上限字=700)
    断言("手改条" in 块, f"人改 md 后**不重建索引**也能立刻查到（块 {len(块)} 字）")

    # 删掉索引文件 —— 必须自动重建
    (_临时 / "_index.json").unlink(missing_ok=True)
    块2 = K.注入(关键词="遇到报错 XYZ123 该怎么办", 上限字=700)
    断言("手改条" in 块2, f"索引文件被删也能自动重建后查到（块 {len(块2)} 字）")

    # 再加一条，且**故意把索引 mtime 变新**（模拟"同一秒内改文件"）——
    # 靠比时间戳的朴素实现会判"不陈旧"⇒ 静默漏条。指纹判据必须抓住。
    (_临时 / "items" / "第二条.md").write_text(
        "---\nid: 第二条\n类别: 规则\n强度: 必须\n来源: 判据\n等级: SOLID\n版本: 1\n---\n"
        "症状：`另一个诡异报错 ABC789` 出现。修法：也照做。\n", encoding="utf-8")
    K._索引路径().touch()                        # 让索引看起来"比源新"
    块3 = K.注入(关键词="遇到报错 ABC789 该怎么办", 上限字=700)
    断言("第二条" in 块3, f"同秒改文件靠指纹也能抓到（块 {len(块3)} 字）")

    # ★ 2026-11-03 改口径（原来是"目录不存在 ⇒ 空串"）：那等于**把静默失效写成判据**。
    #   真事故：知识种子搬进包内后，MCP 配置里那条硬路径成了死路径 ⇒ 库 0 条 ⇒
    #   注入空串 ⇒ 一切都不报错。而当时这条判据正好**认可**了那个行为 ——
    #   判据把一个缺陷锁成了"期望"。
    #   现在的口径：路径无效 ⇒ **回落到状态库**（退到"有东西可用"那一档）并把回落原因报出来；
    #   而"存在的空目录"仍然被尊重（调用方要能拿到干净空库——A/B 冷臂、隔离测试都靠它）。
    os.environ["ORCH_KB_DIR"] = str(_临时 / "根本不存在")
    try:
        落 = K.注入(关键词="报错 XYZ123", 上限字=700)
        断言(K.回落原因() is not None, "ORCH_KB_DIR 指向不存在的目录 ⇒ 记下回落原因")
        断言(K.库根() == Path(os.environ["ORCH_STATE_DIR"]) / "kb",
             f"  回落目标是**当前状态根**下的 kb（实得 {K.库根()}）")
        _st = K.统计()
        断言(bool(_st.get("配置回落")), "  统计里能看见「配置回落」（否则'0 条'会被误读成本来就没知识）")
        # 落的那个库里有没有东西取决于调用方环境 —— 这里只断言"不炸且回落被记下来"
        断言(isinstance(落, str), f"回落读取不抛异常（块 {len(落)} 字）")
    except Exception as e:                       # noqa: BLE001
        断言(False, f"回落路径不许抛异常（实得 {type(e).__name__}: {e}）")

    # 存在的空目录**必须仍然被尊重**：不许回落到状态库（否则 A/B 冷臂就不冷了）
    _真空 = _临时 / "真空库"
    _真空.mkdir(parents=True, exist_ok=True)
    os.environ["ORCH_KB_DIR"] = str(_真空)
    断言(K.回落原因() is None, "存在的空目录不触发回落")
    断言(K.注入(关键词="报错 XYZ123", 上限字=700) == "",
         "  存在的空目录 ⇒ 注入为空（'给我一个干净空库'这个能力不能被回落吃掉）")
finally:
    os.environ["ORCH_KB_DIR"] = _真库
    shutil.rmtree(_临时, ignore_errors=True)

# ══ ④ 元判据：条目必须带「症状：」 ═══════════════════════════════════════════
print("④ 元判据：每条正文必须含症状（否则检索不到）")
_条们 = K.全量()
_无症 = [t.get("id") for t in _条们 if "症状：" not in (t.get("正文") or "")]
断言(bool(_条们), f"知识库非空（{len(_条们)} 条）")
断言(not _无症, f"所有条目都带「症状：」（缺的：{_无症}）")

# ══ ⑤ 门：条目能一键变成判据门（提示 vs 硬约束的分界） ══════════════════════
print("⑤ 可机判的条目要能转成判据门")
_那条 = [t for t in _条们 if t.get("id") == "口径-子进程输出编码自钉"]
# ★★★ 2026-11-04（第229轮）：**这一段原来是 `K.门(条们=_那条, 仓=仓)` 直接断言非空。**
#
#   它被我的改动判红了，**而红得对** —— 新口径是：
#   `grep_required`（"必须出现"）铺到**多个文件**上时不产门，
#   因为"这 N 个文件每一个都必须含它"几乎从来不是人想说的那句话
#   （实测：真仓 55/97 道必红，**全部**来自这种铺开的门；单文件门全绿）。
#
#   ⇒ 判据跟着改到**新语义**上，但**能力断言一条都不许丢**：
#     · "一键变门"这件事仍然测 —— 只是要**指名一个文件**（收敛到一个产物），
#       那正是这条口径教人做的事；
#     · 同时把"铺到多文件时不产门、且理由可见"也钉住。
#   ★ 注：这条规则的「范围」实测是 `tests/*.py` + `tools/*.py`（**不是** `src/**`）——
#     所以指名的那个文件必须在它的范围里，否则门数为 0（这是"范围"在起作用，不是 bug）。
_门 = K.门(条们=_那条, 仓=仓, 文件="tests/run_all.py")
断言(bool(_门), f"指名一个文件时，规则能一键转成判据门（{len(_门)} 条）")
if _门:
    断言(_门[0].get("type") in ("grep_required", "grep_forbidden"),
         f"门类型合法（实得 {_门[0].get('type')}）")
    断言(isinstance(_门[0].get("in"), str),
         f"grep 门的 in 是**单个文件路径**不是 glob 列表（实得 {type(_门[0].get('in')).__name__}）")
# ★ 不指名文件时：`grep_required` 那一半被挡下，且**理由带着下一步动作**
_门铺开 = K.门(条们=_那条, 仓=仓)
未 = K.未转门()
_拦 = 未.get("必须出现却铺到多文件") or []
断言(bool(_拦),
     f"**铺到多文件时不产 `grep_required`、并如实报出**（{str(_拦)[:80]}）—— "
     f"改之前这种门在真仓里 55/97 道必红，与产物好坏无关")
断言(any("收窄" in str(x) or "文件=" in str(x) for x in _拦),
     "理由里**带着能解开它的那个动作**（收窄范围 / 用 `文件=`）—— "
     "指向一个什么都不做的动作，比不说还坏")
断言(all(g.get("type") != "grep_required" for g in _门铺开),
     f"而**禁令那一半照出**（{len(_门铺开)} 道，类型 {sorted({g.get('type') for g in _门铺开})}）—— "
     f"两种极性的量词语义本来就不一样，别一起砍")

print()
if 失败:
    print(f"知识库检索：红 {len(失败)} 项 —— " + "；".join(失败))
    sys.exit(1)
print("知识库检索：绿 —— 真症状能查到真知识，且四种「静默查不到」都被堵住")
