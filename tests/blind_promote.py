def 跑门(门: dict, 内容: str, 仓: Path | None = None) -> tuple[bool, str]:
    """拿真评估器跑一次真门，返回 (是否绿, 因由原文)。

    ★ 写的是**门自己 `in` 指的那个文件**（不是固定写一个文件）—— 否则换一道门就会
      得到「禁词门读不到被测文件」这种红：**红是真的，但红的原因不是我要证的那个**，
      于是判据会拿一个假理由通过（本仓最贵的一种绿）。
    """
    _仓 = 仓 or _仓1
    _目 = _仓 / str(门.get("in") or "src/模.py")
    写(_目, 内容)
    res, audit = GS.evaluate([门], _目, _仓, str(_仓))
    return bool(res.get(门["name"], res.get(门["type"]))), str(
        (audit[0] or {}).get("cause") or "")


