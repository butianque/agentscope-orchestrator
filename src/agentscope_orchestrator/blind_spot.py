            r["最近"] = _t.strftime("%Y-%m-%dT%H:%M:%S")
            r["验证"], r["判法"] = 验证名, 判法名
            # 造不出门 / 没拦住 ⇒ **退回待加门**（没拦住就等于没加）
            r["状态"] = "待加门" if (造不出 or 结论 is False) else "已加门"
            r["核对证据"] = 证据
            # ★★★★★ 2026-11-04（第229轮收尾）：**把三个读数落盘。**
            #
            #   实测发现的洞（真跑第 4 次才显出来）：台账原来**只写结论**
            #   （`验证` / `判法` / `核对证据`），三个判据读数
            #   （`试件结果` / `假阳性结果` / `同类结果`）只在 `return` 里，
            #   **没进台账**。
            #   ⇒ 于是事后翻台账看到「验证=拦得住」，**看不出它凭什么**：
            #     说不出"试件真命中了没有""反例真的放行了吗""同类全命中了没"。
