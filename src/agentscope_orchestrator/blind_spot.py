        #   原来没有它 ⇒ 「试件命中 + **反例也命中** + 同类漏」会被叫成
        #   `拦不住这一类`，而**真正的原因是乱拦**（那道门连合规样本都拦）。
        #   两个缺陷的下一步动作完全不同：
        #     · `拦不住这一类` ⇒ 把模式从"这一次"提到"这一类"（就地改）
        #     · 乱拦           ⇒ **那道门整个是噪声**，得换
        #   ⇒ 名字指错，人就会去改一个不该改的地方
        #     （本仓口径：**阻断信息必须指向真正能解开它的那个动作**）。
        #
        #   ★ 这一条**能写成会红的判据**（⑨ 段的 `_条9e`）——
        #     所以它是修法，不是装饰。
