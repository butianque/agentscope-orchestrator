def 可复用门(*, 档: str = "拦得住", 上限: int = 8, 仓=None) -> list[dict]:
    """**把台账里已经提成的门取出来，直接当 gates 用**（`run_errand` / `orch_run`）。

    ★ 两档**不许混**（`档=` 由调用方显式声明，默认最严的那档）：

      · `档="拦得住"`（默认）—— 只给**实测拦得住**的。这是唯一敢直接挂上去的档
        （`验过门的()` 的口径：推断不算实测）。
      · `档="已提"`       —— 凡是有门规格、状态是「已加门」的都算（含推断档）。
        调用方**知情再用**：它比"没门"强，但还没到"能拦得住"。

    ★ `仓=` —— **跨仓复用前应当给**。`门规格.in` 是**那一次真跑时的相对路径**，
      换个仓多半指不到文件；挂上去只会得到「禁词门读不到被测文件」那种红 ——
      那种红**不是判据，是噪声**（而且没人看得出红的原因，只会以为"这门坏了"）。
      不给 `仓` 就只按台账里存下来的形态给（调用方自担）。

    ★ 返回的是**纯门列表**（一个 list 只放一种东西）—— 每条就是当初存下的门规格，
      可以直接 `gates=可复用门()`。要留痕（哪条盲区、什么时候提的）用 `已提门的()`。
    """
    出: list[dict] = []
    try:
        行s = _读()
    except Exception:                            # noqa: BLE001
        return 出
    for r in 行s:
        g = r.get("门规格")
        if not isinstance(g, dict) or not g:
            continue
        if 档 == "拦得住" and str(r.get("验证") or "") != "拦得住":
            continue
        if 档 != "拦得住" and str(r.get("状态") or "") != "已加门":
            continue
        if 仓 is not None and not 复用门(g, 仓=仓)[0]:
            continue
        出.append(dict(g))
        if len(出) >= max(0, 上限):
            break
    return 出


