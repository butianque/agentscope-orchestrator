    # ★★★★★ 2026-11-03（第225轮）：**"推断"必须与"实测"分开记。**
    #
    #   上面那段让"没给假阳性件"也能得出 `假阳性结果=False`（靠 `模式像噪声吗` 分析
    #   模式本身）。**判据当场红了**，红得对：
