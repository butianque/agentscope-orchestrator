    #     FAIL **只给试件、没给假阳性件 ⇒ 判「未验证」**（拦得住）—— 验了一半不许当验过
    #
    #   ⇒ 旧判据守的纪律是对的：**"我推断它不乱拦" ≠ "我实测它不乱拦"。**
    #     两者不能叫同一个名字 —— 否则"验过"这个词就被稀释了，
    #     而"验过"正是这个台账唯一值钱的东西。
