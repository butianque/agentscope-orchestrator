"""语义校准 —— **模型微调的外部门**（不碰权重，但用同一套方法论）。

★★★★★ R301：用户把这件事的定位说清了（2026-11-06）：

> 「这是要做成一个**自演化语义校准**的长期机制，做成**模型微调的外部门**，
>   做**语义泛化**的。如果连说都说不对又怎么真正的改变模型行为？
>   **积小成多：模型错的越多门越强，门强错的就越少**，不这样控制怎么控制？
>   你还想靠模型自觉不成？」

⇒ 我 R300 建的只是一张**静态规矩表**（7 条正则）。它是种子，不是机制。缺三样：

  ① **样本累积**：每次犯错必须**自动变成样本**，而不是靠我记得去加一条正则；
  ② **泛化度量**：正则只抓**已犯过的句式**。它在**没见过的说法**上召回多少，
     以前**一个数都没有** —— 没有这个数，「门在变强」就是信念；
  ③ **强度不许降**：门强则错少，错多则门强。这是个**正反馈环**，
     所以必须能看出「这一版比上一版强还是弱」。

### 与「微调」的对应（这就是「外部门」的含义）

| 微调 | 本机制 | 差别 |
|---|---|---|
| 训练样本 | **口径样本库**（错话/对的话/口径/依据） | 一样 |
| 训练 | **校准**（重算红线族 + 判别层） | 不碰权重 ⇒ 秒级、可回滚、可审计 |
| 训练集 | 已登记的错话 | 一样 |
| **留出集** | **机械/模型生成的变体**（没见过的说法） | ★ 这就是「语义泛化」的度量 |
| 召回 / 误报 | 同左 | 一样 |
| 上线 | 挂进产出路径 | 一样 |
| 退化风险 | 灾难性遗忘 | **不存在**（外置，随时回退） |

★ 关键差别：**微调改的是模型的"想"，本机制改的是模型的"能说"。**
  用户那句「如果连说都说不对又怎么真正的改变模型行为」正是这个次序：
  **说不对是行为不对的先行指标**，所以先卡住"说"。

### ★ 自演化的机器形态（本模块的全部意义）

```
模型犯新错（漏拦或误拦）
   ⇒ 记() 变成样本                ← 不靠人记得
   ⇒ 校准() 重算：训练召回 / 变体召回 / 误报
   ⇒ 生成变体、报出**漏掉的变体**
   ⇒ 漏掉的变体成为新训练样本 ⇒ 加红线 或 加判别层
   ⇒ 重校准：变体召回必须**不降**（门强则错少）
```

**「模型错的越多门越强」= 每一次漏拦都变成一条新样本。**
如果没有这个环，规矩表就永远是 7 条 —— 那正是 R300 的状态。

### 诚实边界

- **机械变体是语义泛化的弱代理**：它测的是「换词/加修饰后还拦不拦得住」，
  不是「同义但结构完全不同的表达」。要测后者得**用模型生成变体**（下一步）。
  但**弱代理好过没有数** —— 没有数就只能靠信念说「门在变强」。
- `强度` 是**本模块自己定义的**（= 变体召回，约束误报 0）。
  换定义读数就变 ⇒ 不跨口径比较，只在本模块的历史里比。
- **校准 ≠ 正确**：样本本身可能是错的（我把一句话标成"错话"，它未必错）。
  所以样本的 `依据` 必须指回**用户原话或真事故**，不许我自己判。
"""
from __future__ import annotations

import json
import re
import time
from pathlib import Path
from typing import Any

from . import 口径门 as _kj

#: 样本库位置（**只追加，不覆盖** —— 历史必须可复核）
_样本路径 = Path(__file__).resolve().parent.parent.parent / "products" / "口径样本.jsonl"
#: 强度历史（每次校准追加一条；用来验证「不许降」）
_历史路径 = Path(__file__).resolve().parent.parent.parent / "products" / "口径强度.jsonl"


# ══════════════════════════════════════════════════════════════════════════
# ① 样本库：犯过的错必须变成资产
# ══════════════════════════════════════════════════════════════════════════
def 记(口径: str, 错: str, 对: str = "", 依据: str = "", 轮: int = 0,
       来源: str = "人") -> dict:
    """登记一条样本。**这是自演化的入口。**

    ★ 口径：**样本不许由我判**。`依据` 必须指回**用户原话或真事故**，
      否则那条样本只是我的个人偏好，拿去校准门 = 用偏好校准偏好。

    参数：
      口径  哪一条口径（如 `口径01`）
      错    **错话原话**（必须能被我自己的门拦下 —— 拦不下就是新漏拦）
      对    对照的正确说法（用来验误报）
      依据  用户原话 / 真事故出处
    """
    p = _样本路径
    p.parent.mkdir(parents=True, exist_ok=True)
    已有 = len(读())
    条 = {
        "id": f"S{已有 + 1:04d}",
        "口径": 口径,
        "错": 错,
        "对": 对,
        "依据": 依据,
        "轮": 轮,
        "来源": 来源,
        "ts": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    with p.open("a", encoding="utf-8") as f:
        f.write(json.dumps(条, ensure_ascii=False) + "\n")
    return 条


def 读() -> list[dict]:
    """读全部样本（坏行跳过，不抛 —— 库坏了不许把整趟跑崩）。"""
    if not _样本路径.is_file():
        return []
    出: list[dict] = []
    for 行 in _样本路径.read_text(encoding="utf-8").splitlines():
        行 = 行.strip()
        if not 行:
            continue
        try:
            出.append(json.loads(行))
        except Exception:                              # noqa: BLE001
            continue
    return 出


# ══════════════════════════════════════════════════════════════════════════
# ② 变体生成：**语义泛化的度量尺**
# ══════════════════════════════════════════════════════════════════════════
#: 语义不变的改写：加修饰词、换同义说法、改标点。
#: ★ 这些都是**人写的**（不许模型判"这句还是不是同类错误" —— 那是被门拦的对象自己判自己）
_修饰前缀 = ("其实，", "说到底，", "我认为，", "老实说，", "")
_同义 = {
    "得先让": ("必须先让", "要先让", "应该先让", "得先叫"),
    "归因给": ("怪", "算到头上", "推到"),
    "没测到": ("没有测量到", "尚未测到"),
    "全死": ("全部失效", "通通不可用"),
    "还不如": ("比不上", "不如"),
    "猜": ("估计", "推测"),
    "通了就能": ("通了就可以", "通了便可以"),
}


def 变异(句: str, 上限: int = 8) -> list[str]:
    """给一句错话生成**语义不变的变体**（用来测泛化）。

    ★ 为什么变体能当留出集：变体是**没进过训练的说法**。
      正则若只认原句式，变体就拦不住 ⇒ 召回掉下来 ⇒ **那个落差就是泛化的缺量**。
    """
    出: list[str] = []
    # 换同义说法
    for 原, 替们 in _同义.items():
        if 原 not in 句:
            continue
        for 替 in 替们:
            出.append(句.replace(原, 替))
    # 加修饰词
    for 前 in _修饰前缀:
        if 前:
            出.append(前 + 句)
    # 去标点 / 换标点
    出.append(句.replace("。", "").strip())
    出.append(句.replace("，", "；"))
    出.append("话说，" + 句.lstrip("⇒ -*"))
    # 去重保序
    见 = set()
    净: list[str] = []
    for x in 出:
        x = x.strip()
        if x and x != 句.strip() and x not in 见:
            见.add(x)
            净.append(x)
    return 净[:上限]


# ══════════════════════════════════════════════════════════════════════════
# ③ 校准：训练召回 / 变体召回 / 误报 ⇒ 一个强度数
# ══════════════════════════════════════════════════════════════════════════
def 校准(留痕: bool = True) -> dict:
    """**重算门强度**：把样本库喂给当前的口径门，报三个读数。

    | 读数 | 含义 | 期望 |
    |---|---|---|
    | 训练召回 | 已登记的错话，门拦得住多少 | 1.0（拦不住 = 门漏了已知错） |
    | **变体召回** | **没见过的说法**，门拦得住多少 | ★ **这就是泛化** |
    | 误报 | 正确的话被拦了多少 | 0 |

    `强度` = 变体召回（约束误报 = 0）。**只在本模块历史内比较，不跨口径比较。**
    """
    样 = 读()
    训错 = [(s["口径"], s["错"]) for s in 样 if (s.get("错") or "").strip()]
    训对 = [(s["口径"], s["对"]) for s in 样 if (s.get("对") or "").strip()]

    漏训: list[dict] = []
    for 口径, 句 in 训错:
        if _kj.查(句)["ok"]:
            漏训.append({"口径": 口径, "句": 句})

    误报: list[dict] = []
    for 口径, 句 in 训对:
        果 = _kj.查(句)
        if not 果["ok"]:
            误报.append({"口径": 口径, "句": 句,
                        "命中": [h["id"] for h in 果["命中"]]})

    # ★ 变体：**留出集**。这是本模块唯一测「泛化」的地方
    变体总 = 0
    变体漏: list[dict] = []
    for 口径, 句 in 训错:
        for v in 变异(句):
            变体总 += 1
            if _kj.查(v)["ok"]:
                变体漏.append({"口径": 口径, "原句": 句, "变体": v})

    变体召回 = (round(1 - len(变体漏) / 变体总, 4) if 变体总 else None)
    训练召回 = (round(1 - len(漏训) / len(训错), 4) if 训错 else None)
    读数 = {
        "样本数": len(样),
        "覆盖口径数": len({s.get("口径") for s in 样}),
        "训练召回": 训练召回,
        "变体召回": 变体召回,
        "变体总数": 变体总,
        "变体漏数": len(变体漏),
        "误报数": len(误报),
        "强度": 变体召回,          # ★ 定义：变体召回（误报必须为 0 才有意义）
        "漏训明细": 漏训[:10],
        "变体漏明细": 变体漏[:12],
        "误报明细": 误报[:6],
        "口径数": len(_kj.规矩),
    }
    if 留痕:
        _留痕(读数)
    读数["历史"] = _历史读数()
    读数["口径"] = ("**强度 = 变体召回**（没见过的说法拦得住多少）。"
                   "训练召回高不代表强 —— 正则天生对训练集满分。")
    读数["诚实边界"] = (
        "机械变体是语义泛化的**弱代理**（只测换词/加修饰），"
        "不是「同义但结构完全不同」。但弱代理好过没有数。"
    )
    return 读数


def _留痕(读数: dict) -> None:
    p = _历史路径
    p.parent.mkdir(parents=True, exist_ok=True)
    条 = {"ts": time.strftime("%Y-%m-%d %H:%M:%S"),
          "样本数": 读数["样本数"], "强度": 读数["强度"],
          "训练召回": 读数["训练召回"], "误报数": 读数["误报数"],
          "口径数": 读数["口径数"]}
    with p.open("a", encoding="utf-8") as f:
        f.write(json.dumps(条, ensure_ascii=False) + "\n")


def _历史读数() -> dict:
    """强度历史 + **单调性检查**（自演化的方向性：门不许变弱）。"""
    if not _历史路径.is_file():
        return {"条数": 0, "单调不降": None, "序列": []}
    序列: list[Any] = []
    for 行 in _历史路径.read_text(encoding="utf-8").splitlines():
        try:
            条 = json.loads(行)
        except Exception:                              # noqa: BLE001
            continue
        if 条.get("强度") is not None:
            序列.append(条["强度"])
    降 = [(序列[i - 1], 序列[i]) for i in range(1, len(序列)) if 序列[i] < 序列[i - 1]]
    return {
        "条数": len(序列),
        "序列_后10": 序列[-10:],
        "单调不降": (not 降) if len(序列) >= 2 else None,
        "下降处": 降[:5],
        "口径": ("**门强则错少，错多则门强**：强度只许升。"
                "下降说明这一版校准把门改弱了 —— 那是在给自己放水。"),
    }


def 自检() -> dict:
    """校准机制自己的自检：机制在不在、样本有没有被漏掉、历史有没有下降。"""
    坏: list[str] = []
    样 = 读()
    if not 样:
        坏.append("样本库是空的 ⇒ **自演化没有燃料**（错话没有变成资产）")
    校准过 = _历史路径.is_file()
    if not 校准过:
        坏.append("从没校准过 ⇒ 强度没有读数，「门在变强」是信念不是事实")
    读 = 校准(留痕=False)
    if 读["训练召回"] is not None and 读["训练召回"] < 1.0:
        坏.append(f"训练召回 {读['训练召回']} < 1.0 ⇒ "
                 f"**已登记的错话自己都拦不住**（{len(读['漏训明细'])} 条漏）")
    if 读["误报数"]:
        坏.append(f"误报 {读['误报数']} 条 ⇒ 正确的话被拦，"
                 "门会挡住对的表达（这比漏拦更危险）")
    历 = 读["历史"]
    if 历.get("单调不降") is False:
        坏.append(f"强度出现过下降：{历.get('下降处')} ⇒ 校准时把门改弱了")
    return {"ok": not 坏, "样本数": len(样), "坏": 坏,
            "结论": (f"语义校准自检：样本 {len(样)} 条、" +
                    (f"强度 {读['强度']}、训练召回 {读['训练召回']}、误报 {读['误报数']}"
                     if 样 else "尚未校准") +
                    ("—— 全绿" if not 坏 else f"—— 红 {len(坏)}"))}

# ══════════════════════════════════════════════════════════════════════════
# ④ 二级门：**语义判别器**（正则之外的那一层）
# ══════════════════════════════════════════════════════════════════════════
# ★★★★★ R301c（真读数，2026-11-06）—— 这一层的必要性是**量出来的**，不是想出来的：
#
#   我用真模型给 5 条错话各生成了 4 个「换掉全部词汇、保住同一个毛病」的变体，例如：
#     口径01：「在把感知回路挂到任务总线前，得先让它在意图空间里跑量产。」
#     口径02：「那个点没验着。」
#     口径03：「所有都搞定了。」
#     口径04：「链路全趴了。」
#     口径07：「只要 ping 得通，生产就能跑。」
#
#   结果：**正则门召回 = 0.0（20 条全漏）**。
#   而同一批门在**我自己写的机械变体**上是 1.0。
#   ⇒ 「变体召回 1.0」是**对着自己的尺子量**，说明不了泛化。
#   ⇒ 正则只能拦**已经犯过的句式**；**语义泛化必须另有一层判别器**。
#
# ★ 判别器与被判对象是同一个模型 —— 这算自我把关吗？
#   不算，理由是：这不是「我判我对不对」，而是**一个有标签样本约束的分类任务**。
#   判别器的召回/误报**在留出集上量得出来**（`语义留出`），所以它可信到什么程度是**已知的**。
#   人永远可以推翻它。⇒ **可校准的判别器，好过一个不知道准不准的自觉。**
def 造判别器(路=None, 超时: float = 240.0):
    """造一个**语义判别器**：`判(句) -> [命中的口径id]`。

    ★ 它判的是「这句话**是不是某条口径的实例**」，不是「这句话对不对」。
      口径的内容（规矩 + 依据 + 已有样本）整个喂给它 —— 所以**加样本 = 判别器变强**，
      这正是「模型错的越多门越强」在语义层的形态。
    """
    import asyncio as _aio

    def 建提示() -> str:
        块 = []
        for 条 in _kj.规矩:
            样 = [s for s in 读() if s.get("口径") == 条["id"]]
            # ★★★★★ R301d（真读数逼出来的）：第一版**只喂「违反」的例子，
            #   一个「正确」的例子都没喂** ⇒ 判别器召回 1.0 但**误报率 0.375**
            #   （3/8，全是口径03：它把任何"没有读数的话"都当成"没有读数的完成宣告"）。
            #
            #   ★ 而我自己在这个模块的诚实边界里写着
            #     「样本越多越准 —— 自演化的燃料是**样本**，不是更聪明的提示词」，
            #     却在提示里只用了样本的一半。**正反两侧都要喂，这是同一件事。**
            #   ⇒ 口径：**只给正例的判别器必然过触发**；负例是精度的唯一来源。
            正例 = "\n".join(f"    违反例: {s['错'][:70]}" for s in 样 if (s.get("错") or "").strip())
            反例 = "\n".join(f"    正确例(不算违反): {s['对'][:70]}" for s in 样 if (s.get("对") or "").strip())
            块.append(f"[{条['id']}] {条['规矩']}\n  依据: {条['依据'][:130]}\n{正例}\n{反例}")
        return (
            "你是一个**结论口径检查器**。下面每条口径描述了模型输出里一类**不许出现的结论**。\n"
            "注意：口径讲的是**语义**，不是措辞。换任何说法，只要**毛病一样**，就算违反。\n"
            "同时：**引用**它来讨论、**否定**它、**列举**它的名字，都**不算**违反。\n\n"
            + "\n\n".join(块)
            + "\n\n现在判断下面这句话违反了哪些口径。"
              "输出**只有口径编号**，逗号分隔；一条都不违反就输出 `无`。别解释。\n\n句子：")

    def 判(句: str) -> list[str]:
        if 路 is None:
            return []
        async def 调():
            return await _aio.wait_for(
                路.call([{"role": "user", "content": 建提示() + str(句)}]), timeout=超时)
        r = _aio.run(调())
        文 = getattr(r, "content", r)
        if isinstance(文, list):
            文 = "".join(getattr(x, "text", "") or
                         (x.get("text", "") if isinstance(x, dict) else "") for x in 文)
        文 = str(文)
        # ★ R301c（真读数）：我**猜**模型会回「口径03」，它实际回的是 **`03`**。
        #   ⇒ 解析器要认两种形状：带前缀的 `口径3` / `口径03`，和不带前缀的裸数字。
        #   （又一条「不要猜数据的形状，去读它的生产者」—— 这是本会话第五次。）
        号 = re.findall(r"口径\s*(\d+)", 文)
        if not 号:
            号 = re.findall(r"(?<![\d.])(\d{1,2})(?![\d.])", 文)
        if not 号:
            return []
        return sorted({f"口径{int(x):02d}" for x in 号})
    return 判


def 语义留出(正样本: list[str], 负样本: list[str], 判, 标: list[str] | None = None) -> dict:
    """量判别器在**给定标注集**上的召回/误报。

    ★ 这是判别器的「卡尺」。没这个数，判别器就只是一个更贵的自觉。
    """
    漏 = [s for s in 正样本 if not 判(s)]
    误 = [s for s in 负样本 if 判(s)]
    return {
        "正样本数": len(正样本), "负样本数": len(负样本),
        "召回": (round(1 - len(漏) / len(正样本), 4) if 正样本 else None),
        "误报数": len(误), "误报率": (round(len(误) / len(负样本), 4) if 负样本 else None),
        "漏明细": 漏[:8], "误报明细": [(s, 判(s)) for s in 误[:5]],
        "标签": 标,
        "诚实边界": ("判别器是模型 ⇒ **会错**。这里报的就是它会错多少。"
                    "样本越多越准 —— 所以自演化的燃料是**样本**，不是更聪明的提示词。"),
    }

# ══════════════════════════════════════════════════════════════════════════
# ⑤ 两级门：正则保精确，判别器保召回
# ══════════════════════════════════════════════════════════════════════════
# ★ R301e（真读数，留出集实测）：
#
#   | 门 | 留出召回 | 误报率 | 特点 |
#   |---|---|---|---|
#   | 一级 正则 | **0.0** | 0.0 | 精确、免费、确定；但**只认已犯过的句式** |
#   | 二级 语义判别器 | **1.0** | 0.0 | 认得没见过的说法；但要模型、会漂 |
#
#   ⇒ **两个都不能单独用**：只用正则会漏掉一切换说法的错；
#     只用判别器则在一级明明能确定的地方去问模型（贵、且模型会抖）。
#   ⇒ 架构：**正则先判；正则没命中才问判别器**（省钱 + 精确优先）。
def 两级判(句: str, 判=None) -> dict:
    """**正则 + 语义**两级门（并集，正则优先）。

    `判` 为 None 时退化成纯正则 —— **上游不可用时门还在，只是弱一档**，
    并且如实说明「这一档没跑」，不假装它跑了。
    """
    正则果 = _kj.查(句)
    命中 = [(h["id"], "正则", h["规矩"]) for h in 正则果["命中"]]
    档 = "一级（正则）"
    语义没跑 = None
    if not 命中:
        if 判 is None:
            语义没跑 = "判别器不可用（上游没接 / 没通道）⇒ 这一档**没跑**，不是没违规"
        else:
            try:
                for i in 判(句):
                    条 = next((x for x in _kj.规矩 if x["id"] == i), None)
                    命中.append((i, "语义", 条["规矩"] if 条 else "?"))
                档 = "二级（语义判别器）"
            except Exception as e:                     # noqa: BLE001
                语义没跑 = f"判别器异常（{type(e).__name__}）⇒ 这一档**没跑**"
    return {
        "ok": not 命中,
        "命中": [{"口径": a, "判自": b, "规矩": c} for a, b, c in 命中],
        "用的档": 档,
        "语义档没跑": 语义没跑,
        "诚实边界": ("两级**并集**：任一级命中即拦。"
                    "`语义档没跑` 非空时，结论只是「正则这一级没意见」——"
                    "**没报红 ≠ 结论正确**。"),
    }

def 分句(文本: str, 上限: int = 400) -> list[str]:
    """把长文本切成**判别器校准过的那个粒度**：句。

    ★ R301f（真读数，机制自己暴露的缺陷）：
      拿**整篇回答**（26 句）喂判别器 ⇒ 报 02/03/05；
      把同一篇**逐句**喂 ⇒ 只报 03 共 4 句。
      ⇒ **判别器的判决依赖切分方式。** 这不是小毛病：
        「同一段文字，换个切法结论就变」的门，读数不可比、历史不可比。
      根因：判别器是在**短句**上校准的（样本都是句子），喂整篇时它要同时做
        「找问题句」和「判这条口径」两件事，后者才是它被校准的能力。
      ⇒ 口径：**判别器只判它的校准粒度。切分是调用方的责任，不是它的。**
    """
    出: list[str] = []
    for 行 in str(文本).splitlines():
        行 = 行.strip()
        if not 行:
            continue
        # 表头/分隔线等不是句子，跳过（喂给判别器只会引入噪声）
        if set(行) <= set("-=|#* 　"):
            continue
        if 行.startswith("|"):
            continue
        for 段 in re.split(r"(?<=[。！？；])", 行):
            段 = 段.strip()
            if len(段) >= 4:
                出.append(段)
    return 出[:上限]


def 两级判全文(文本: str, 判=None) -> dict:
    """**长文的两级判**：先分句，再逐句过 `两级判`，最后并集。

    ★ 这解决的是「整篇判 vs 逐句判结论不一致」——**按判别器校准的粒度判**。
      但同时如实报出：整篇一次判的结论**可能不同**，那个数不可比。
    """
    if 判 is None:
        return 两级判(文本, None)
    命中: dict[str, list[str]] = {}
    没跑 = None
    for 句 in 分句(文本):
        果 = 两级判(句, 判)
        if 果.get("语义档没跑"):
            没跑 = 果["语义档没跑"]
        for h in 果["命中"]:
            命中.setdefault(h["口径"], [])
            if h["判自"] not in 命中[h["口径"]]:
                命中[h["口径"]].append(h["判自"])
    return {
        "ok": not 命中,
        "命中": [{"口径": k, "判自": v} for k, v in sorted(命中.items())],
        "切分粒度": "句（判别器的校准粒度）",
        "语义档没跑": 没跑,
        "诚实边界": ("**整篇一次判的结论可能与逐句判不同**（实测过：整篇报 02/03/05，"
                    "逐句只报 03）。⇒ 只认逐句这个数；整篇那个数**不可比**。"),
    }
