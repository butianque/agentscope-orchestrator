def 锚定一行(果: dict) -> str:
    """压成一行给简报用 —— 三级各报自己的读数，**弱级别必须带自己的证实率**。"""
    if not 果 or "A级真锚定" not in 果:
        return ""
    a = 果["A级真锚定"]
    s = 果["悬空锚定（点了一个不存在的.lean）"]
    u = 果["未锚定（有证明但没有任何代码点名）"]
    行 = [f"锚定边：**A(文本事实) {a['边数']:,}** 条（涉 {a['涉及.lean文件数']:,} 个 .lean）· "
          f"悬空锚定 **{s['条数']:,}** 条 · 未锚定 **{u['文件数']:,}** 个 .lean（≠没用）"]
    别 = 果.get("在别的根里（仓里有，但不在声明的 lean 根内）") or {}
    if 别.get("条数"):
        行.append(f"  另 {别['条数']:,} 条点名的 .lean **在别的根里**（仓里有、不在声明的 lean 根内 "
                  f"⇒ **档案声明不全**，不是代码错）")
    b = (果.get("B级同名的边") or {}).get("① 1:1（两边各只一处定义）")
    c = 果.get("C级同目录名的边") or {}
    if isinstance(b, dict):
        n2 = (果.get("B级同名的边") or {}).get("② 1:N / N:1（一边唯一、另一边多处）") or {}
        n3 = (果.get("B级同名的边") or {}).get("③ N:M（两边都多处）") or {}
        行.append(f"  B(跨语言同名) 1:1 **{b.get('边数', 0):,}** 条"
                  f"（A级点名命中 {b.get('★精确率的机器可算上界', '?')}）· "
                  f"1:N {n2.get('名字数', 0):,} · N:M {n3.get('名字数', 0):,} ⇒ {b.get('★判据', '?')}")
    if c and "边数" in c:
        行.append(f"  C(同目录名) {c['边数']:,} 条 · fan-out 中位 **{c['fan-out 中位数']}** · "
                  f"命中 {c.get('命中率（机器可算上界）', '?')} ⇒ {c.get('★判据', '?')}")
    # ★ 反向边也要进这一行：只算不报（不进简报）就是**没接线**。
    反 = 果.get("反向锚定") or {}
    反1 = 反.get("①真反向边（点名的.rs在本表收的范围内）") or {}
    反2 = 反.get("②真悬空（点名的.rs全仓都找不到）") or {}
    反3 = 反.get("③在别的根里（仓里有，但不在声明的 rs 根内）") or {}
    if isinstance(反1, dict) and "条数" in 反1:
        行.append(f"  反向(.lean→.rs) 真 **{反1['条数']:,}** 条"
                  f"（双向 {反1.get('★其中双向（该.rs也点名了这个.lean）', '?')}）· "
                  f"悬空 **{反2.get('条数', 0):,}** 条（全仓都没有）· "
                  f"在别的根里 {反3.get('条数', 0):,} 条"
                  f"（仓里有 ⇒ 档案声明不全，**不是悬空**）")
    return "\n".join(行)


