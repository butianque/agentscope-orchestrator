"""R286：**工程失败归因**——分清"是谁的错"，因为下一步动作完全不同。

★ 为什么（真读数，2026-11-06）：
  既定目标里点名了「失败归因」，而此前只有**通道级**的 `gateway._classify_failure`
  （判"硬死 / 读不到"）。**工程失败本身**——一次目标没做成——完全没有归因。
  实测三种失败在回执里长得几乎一样（都只是 `{'nogcc': False}`）：
    · 命令根本无法启动（环境缺工具）   ← 装工具，改代码没用
    · 工具跑了但仓里有错             ← 改代码
    · 判据自己写错了（文件路径不存在）← 改判据，改代码没用
  三种的**下一步动作完全不同**，混成一档会让人去改一个没错的地方。

★ 这是「报错要报最上游那条原因」在**工程失败**上的落地：
  不是把所有失败都说成"未达成"，而是说清**责任在哪一层**。

★ 诚实边界：
  归因是**从证据里读出来的**（cause/err/退出码/文件是否存在），
  不是"推断模型哪里想错了"。认不出的**必须归到 `未知`**，不许硬塞进某一档——
  一个错的归因比没有归因更坏，它会让人去改一个没坏的地方。
"""
from __future__ import annotations

import re
from pathlib import Path

#: 归因档 → (责任层, 该做什么)。★ 每档的动作**互斥**，混了就会改错地方。
档位 = {
    "环境缺工具": ("环境", "装工具 / 换机器（改代码和改判据都没用）"),
    "判据写错": ("判据", "判据本身有问题（路径不存在/规格非法）——改判据，不是改代码"),
    "代码没改对": ("代码", "工具跑通了但门没过 —— 这才是该改代码的时候"),
    "无法启动": ("环境", "命令存在性/权限/工作目录问题"),
    "超时": ("环境", "工具跑了但没在预算内完成；先看是不是命中了慢路径"),
    "未知": ("未知", "**认不出**——别猜，把原文贴出来人工看一眼"),
}

#: 明确说明"命令根本起不来"的关键词（各平台真输出）
_起不来 = (
    "[cmd_not_found]", "系统找不到指定的文件", "no such file or directory",
    "is not recognized", "command not found", "不是内部或外部命令",
    "winerror 2", "winerror 5", "permission denied", "拒绝访问",
    "errno 2", "exec format error",
)
_超时 = ("timed out", "timeout", "超时", "超过预算")


def 归因(条目: dict, 仓根: Path | str | None = None) -> dict:
    """给**一条**门证据归因。返回 {档, 责任, 该做什么, 依据}。"""
    if not isinstance(条目, dict):
        return {"档": "未知", "责任": "未知", "该做什么": 档位["未知"][1],
                "依据": f"证据不是 dict（实得 {type(条目).__name__}）"}

    cause = str(条目.get("cause") or "")
    err = str(条目.get("err") or "")
    文 = (cause + "\n" + err).lower()
    rc = 条目.get("rc")

    # ① 命令根本起不来 —— **最先判**，因为它的 err 里常混着别的东西
    for w in _起不来:
        if w in 文:
            return {"档": "无法启动" if "cmd_not_found" in 文 else "环境缺工具",
                    "责任": "环境", "该做什么": 档位["环境缺工具"][1],
                    "依据": f"输出里出现 {w!r}"}

    # ② 超时
    for w in _超时:
        if w in 文:
            return {"档": "超时", "责任": "环境", "该做什么": 档位["超时"][1],
                    "依据": f"输出里出现 {w!r}"}

    # ③ 判据自己写错
    # ★★★★★ R286b（真读数，2026-11-06）：**别用 `file` 字段判这件事。**
    #   我第一版写"判据点名的文件在仓里不存在 ⇒ 判据写错"，
    #   可实测 `gate_spec.evaluate` 的证据里 `file` 是 **`"repo"`**（**仓目录名**，
    #   表示"被测对象"，不是文件路径）⇒ 三个不同的失败**全被判据写错**：
    #     ④ 真代码错（cause="必需缺失|V = 1"）  → 误判"判据写错"  ← 最坏的一种误判：
    #        它会让调用方去改一个**好好的判据**，而真正的错在代码里。
    #   ⇒ 判据自己已经把话说清了，**去读 cause**（这是生产者写的那句话）：
    #     `门规格非法|读不到|in=…（不存在或不是文件）` 才是判据写错的**唯一**凭据。
    if "门规格非法" in cause or "规格非法" in cause:
        return {"档": "判据写错", "责任": "判据",
                "该做什么": 档位["判据写错"][1],
                "依据": f"判据自己说规格非法：{cause[:120]}"}
    # ★ 兜底：若声明了 `in` 且该路径确实不存在（双保险，但以 cause 为主）
    rel = str(条目.get("in") or "").strip()
    if not rel:
        _m = re.search(r"in=([^（(\s]+)", cause)
        rel = _m.group(1) if _m else ""
    if 仓根 and rel:
        根 = Path(仓根)
        if not any((根 / r2).exists() for r2 in (rel, f"src/{rel}")):
            return {"档": "判据写错", "责任": "判据",
                    "该做什么": 档位["判据写错"][1],
                    "依据": f"判据声明 in={rel!r}，但仓里不存在"}

    # ③b 判据**明确说缺什么**（`必需缺失`/`missing`）⇒ 这是代码没改对，不是判据坏
    if "必需缺失" in cause or 条目.get("missing"):
        return {"档": "代码没改对", "责任": "代码",
                "该做什么": 档位["代码没改对"][1],
                "依据": f"判据说缺 {条目.get('missing') or cause[:80]}"}

    # ④ 工具跑通了但门没过 —— 这才是"代码该改"
    if rc is not None and rc not in (None, 0) or cause or err:
        return {"档": "代码没改对", "责任": "代码",
                "该做什么": 档位["代码没改对"][1],
                "依据": f"命令跑通了但判据不满足（rc={rc}）"}

    return {"档": "未知", "责任": "未知", "该做什么": 档位["未知"][1],
            "依据": "证据里没有可判别的字段（cause/err/rc 都空）"}


def 归因一批(详情: list, 仓根: Path | str | None = None) -> dict:
    """给 `gate_spec.evaluate()` 的**详情**（list）批量归因。

    返回 {
      "逐条": [{gate, file, ok, 档, 责任, 该做什么, 依据}],
      "汇总": {档: [gate 名...]},
      "最该先做的": str,          # 按"改错了会浪费多少"排的下一步
      "诚实边界": str,
    }
    """
    if not isinstance(详情, list):
        return {"逐条": [], "汇总": {}, "最该先做的": "详情不是 list ⇒ 没测到",
                "诚实边界": f"证据形状不对（实得 {type(详情).__name__}）"}

    逐: list[dict] = []
    for e in 详情:
        if not isinstance(e, dict):
            continue
        if e.get("ok"):
            continue
        a = 归因(e, 仓根)
        逐.append({"gate": e.get("gate"), "file": e.get("file"),
                   **a, "rc": e.get("rc")})

    汇总: dict[str, list[str]] = {}
    for x in 逐:
        汇总.setdefault(x["档"], []).append(str(x.get("gate")))

    # ★ 排序有讲究：**先排除"改了也白改"的**，再谈改代码。
    #   真事故：环境缺工具时去改代码，改十轮也不会好。
    if "环境缺工具" in 汇总 or "无法启动" in 汇总:
        先 = ("**先修环境**：有命令根本起不来 —— "
             "这时候改代码和改判据都不会有变化。")
    elif "判据写错" in 汇总:
        先 = ("**先修判据**：判据点名的文件在仓里不存在 —— "
             "这是判据的问题，改代码不会让它变绿。")
    elif "超时" in 汇总:
        先 = "**先看超时**：工具没在预算内跑完，先确认不是命中了慢路径。"
    elif "代码没改对" in 汇总:
        先 = "工具跑通了但门没过 —— 这才是该改代码的时候。"
    elif "未知" in 汇总:
        先 = "**有认不出的失败** —— 不许猜；把原文贴出来人工看一眼。"
    else:
        先 = "没有失败条目。"

    return {
        "逐条": 逐,
        "汇总": 汇总,
        "最该先做的": 先,
        "诚实边界": ("归因是**从证据里读出来的**（cause/err/rc/文件是否存在），"
                  "不是推断'模型哪里想错了'。认不出的一律归 `未知` —— "
                  "一个错的归因比没有归因更坏，它会让人去改一个没坏的地方。"),
    }
