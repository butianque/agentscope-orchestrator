def 主心骨回执路径(根: Path | None = None) -> Path:
    """主心骨回执的落盘位置（**与真跑总账同目录**，便于一起复核）。"""
    基 = Path(根) if 根 else Path(os.environ.get("ORCH_AUDIT_DIR")
                                  or (Path.cwd() / ".audit_trail"))
    基.mkdir(parents=True, exist_ok=True)
    return 基 / "chief_receipt.jsonl"


def 写回执(条目: dict, 根: Path | None = None) -> Path:
    """追加一条回执（**只追加，不改旧条** —— 历史必须可复核）。"""
    p = 主心骨回执路径(根)
    行 = dict(条目)
    行.setdefault("ts", time.strftime("%Y-%m-%d %H:%M:%S"))
    with p.open("a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(行, ensure_ascii=False) + "\n")
    return p


def 读回执(根: Path | None = None) -> list[dict]:
    p = 主心骨回执路径(根)
    if not p.is_file():
        return []
    出 = []
    for x in p.read_text(encoding="utf-8").splitlines():
        x = x.strip()
        if not x:
            continue
        try:
            出.append(json.loads(x))
        except Exception:
            continue
    return 出


