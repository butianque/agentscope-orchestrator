def _解析决定(文本: str) -> dict:
    """从模型输出里抽那份 JSON。抽不到 ⇒ 返回空决定（**不猜**）。"""
    if not isinstance(文本, str):
        return {}
    m = re.search(r"\{.*\}", 文本, re.S)
    if not m:
        return {}
    for 候选 in (m.group(0),):
        try:
            d = json.loads(候选)
        except Exception:
            continue
        if isinstance(d, dict):
            return d
    return {}


