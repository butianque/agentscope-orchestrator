# ★★★★★ R116b：「门**跑不起来**」不得算「样本让它红了」。
#
# 真证据（2026-10-20 第十四次端到端）：两条门被判「契约成立」，
#   而它们的输出是：
#       cargo_check_lib：`命令无法启动|cargo_check_lib`  ⇒ 成立=True
#       anti_fake_gate ：`命令无法启动|anti_fake_gate`   ⇒ 成立=True
#   门**根本没执行**（命令没起来），机器却记下「样本真能让它红 ⇒ 契约成立」。
#
# ★ 这是**假阳性契约**，比「把好门判成恒真门」（R114）更危险：
#   后者是否决太多（不收敛但诚实），前者是**给一条没跑过的门发合格证**
#   —— 它会一路带着 `_chief_契约破裂` 为空走到「全绿」，
#   而那个「全绿」背后一条判据都没被验过。
#
# ★ 与 R95 / R98 / R102 同一族：**「没发生」与「发生了」被压成同一个值。**
#   这里的具体形态是：`绿=False` 这一个比特同时表示
#     (a) 门真跑了、判据真的拒收了样本   ← 契约成立
#     (b) 门压根没跑起来                  ← **什么都没验**
#   两件事必须分开，否则 (b) 会伪装成 (a)。
#
# ★ 判据不是枚举「哪些因由算跑不起来」，而是**全称**的：
#   只有「门**真的执行了**并且返回了失败」才算红。
#   `gate_spec.判据因由` 已经把这些档分开了（命令无法启动 / 超时 / 挂起 /
#   编译错 / 退出码不符 / 缺词 / 多词 …），机器只需要问：
#   **这个因由是不是「执行侧」的**（而不是「判定侧」的）。
_执行侧因由 = ("命令无法启动", "超时", "挂起")


def _因由是执行侧(因由: str) -> bool:
    """这个因由是「门没跑成」还是「门跑了、判据拒收了」？

    ★ 为什么是前缀匹配而不是全等：`gate_spec.判据因由` 的码是
      `"命令无法启动|<名>"`、`"超时|上限60s"` 这种**带参数**的形态。
      只认前缀，不认参数（参数是环境噪声）。
    ★ 诚实边界：本函数只回答「能不能把它当成红的证据」，
      **不改判据**（门本身的红绿仍由 `gate_spec` 决定）。
    """
    s = str(因由 or "").strip()
    return any(s.startswith(k) for k in _执行侧因由)


def _调跑门(跑门, 门spec: dict, 根: Path, 变异相对: str):
    """调 `跑门`，**能带第三参就带**（R114 新增「变异落在哪个文件」）。

    ★ 为什么要探测而不是写死三参：`跑门` 是**调用方注入**的
      （`验否定样本` 的注释写着「本模块不绑定具体执行器」）。
      老调用方只接受两参 ⇒ 直接传三参会 TypeError，
      而那会被上面的 `except Exception` 吞成「门执行异常 ⇒ 不假装已验」
      ⇒ **静默降级**，比报错更糟。
    """
    import inspect as _ins
    try:
        参数 = [p for p in _ins.signature(跑门).parameters.values()
                if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)]
        三参 = len(参数) >= 3
    except (TypeError, ValueError):
        三参 = False
    return 跑门(门spec, 根, 变异相对) if 三参 else 跑门(门spec, 根)


