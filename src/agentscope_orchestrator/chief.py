def 验判据契约(门集: list, 产物文本, 跑门, 工作根: Path | None = None,
              必须: bool = True) -> tuple[bool, list[判据契约]]:
    """对整份门集验契约。

    `必须=True`  ⇒ 任何一条门没有否定样本 / 样本不红 ⇒ 整份不成立（**拒收**）
    `必须=False` ⇒ 无样本的门降级为 unknown（如实报告），但有样本的门仍须成立

    ★ 默认 `必须=True`：这是本件的核心 ——
      「主心骨可以定任何判据，但**每条判据都必须自带一个它必须拒收的样本**」。
    """
    契约们: list[判据契约] = []
    全好 = True
    for 门 in (门集 or []):
        if not isinstance(门, dict):
            continue
        契 = 判据契约(门)
        成立, 报告 = 验否定样本(产物文本, 门, 跑门, 工作根)
        契.报告 = 报告
        契.状态 = 契.判状态()          # ★ R148：四种「不成立」分开
        契.成立 = bool(成立)
        契约们.append(契)
        if not 契.样本们 and not 必须:
            continue                      # 降级：如实报告，不判死
        if not 契.成立:
            全好 = False
    return 全好, 契约们


