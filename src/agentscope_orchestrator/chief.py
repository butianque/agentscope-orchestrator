def 抽否定样本(门: dict) -> list[dict]:
    """从一条门里抽出它的**否定样本**。

    形态（主心骨输出，机器读）：

        {"name": "...", "type": "compile", "cmd": [...],
         "否定样本": [{"旧": "<产物里应当存在的串>",
                       "新": "<把它改坏成什么>",
                       "说明": "为什么这必须让门红"}]}

    ★ 为什么是「旧串→新串」而不是「一整份坏文件」：
      · 一整份坏文件要模型重写全部内容 ⇒ 贵、且它可能顺手改别的地方；
      · 「改一处」**精确指向这条判据管的那件事** ——
        如果门对「那一处被改坏」没反应，它就是恒真门，没有第二种解释。

    ★ 返回空表 = 这条门**没有契约** ⇒ 由调用方决定是拒收还是降级
      （见 `验判据契约` 的 `必须` 参数）。
    """
    if not isinstance(门, dict):
        return []
    原 = 门.get("否定样本")
    if 原 is None:
        原 = 门.get("否定")
    if 原 is None:
        return []
    if isinstance(原, dict):
        原 = [原]
    if not isinstance(原, list):
        return []
    出: list[dict] = []
    for x in 原:
        if not isinstance(x, dict):
            continue
        旧 = x.get("旧")
        新 = x.get("新")
        if 旧 is None:
            旧 = x.get("from")
        if 新 is None:
            新 = x.get("to")
        if not isinstance(旧, str) or not 旧:
            continue
        出.append({"旧": 旧,
                   "新": "" if 新 is None else str(新),
                   "说明": str(x.get("说明") or x.get("why") or "")})
    return 出


def _应用否定样本(文本: str, 样本: dict) -> str | None:
    """把一条否定样本应用到产物文本上。**命中不到 ⇒ 返回 None**（契约失效）。"""
    旧 = 样本.get("旧") or ""
    if not 旧 or 旧 not in 文本:
        return None
    return 文本.replace(旧, 样本.get("新") or "", 1)


