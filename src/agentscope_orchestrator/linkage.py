"""四方文档联动 —— 快照 / 任务书 / 回执 / 状态索引 四者的互锁判据。

## 这个模块治的是什么病（**不是"再加一套校验"**）

本项目的四份文档各自都写得不错，问题是**它们互不相认**：

- **快照**声明了「快照版本 v0.1」「§五.1 合法概念全集 6 条」—— 但它**不声明谁在用它**；
- **任务书**可以凭空写，**不需要引用快照里存在的任何一条** —— 于是任务书能整篇
  建立在"项目里没有的假设"上，而且**从任务书本身看不出来**；
- **回执**写完就落地，**没人归档** ⇒ 状态索引的「回执归档记录」章节要靠**人手工**一行行补；
- **状态索引**少了一轮，看起来像"那轮没做"，其实做了只是没归档。

⇒ 四份文档之间**没有任何机器判据**。所以"哪里断了"只能靠人翻 ——
  而长线项目上人翻不过来，于是**断就断了，没人知道**。

本模块把四者互锁成**可机判的判据**。联动条目（LINK-01~05）来自上游设计，
这里逐条落地；每条都注明**为什么这样判**。

## 为什么这些判据值得存在（而不是"形式主义"）

每一条对应的都是**AI 长线工程里的真实失效模式**：

| 判据 | 治的失效 |
|:--|:--|
| LINK-01 任务书必须引用快照里存在的条目 | 任务书**凭空写**，建立在项目里不存在的东西上 |
| LINK-02 任务书必须声明快照版本 | 快照改了，任务书还在按老版本写，**没人发现** |
| LINK-03 回执执行项 ⇄ 任务书执行项一一对应 | 任务书 6 项，回执只交 4 项，**漏了没人知道** |
| LINK-04 回执判定依据覆盖任务书标注的依据 | 任务书说要按 PR-X 判，回执根本没提 PR-X |
| LINK-05 回执归档 ⇒ 状态索引自动追加 | **回执写完没人归档**（本项目实测：几十轮全靠手工补） |

★ 本模块**只判、不写**（除 LINK-05 的归档外）：判据的价值在于"能红"，
  自动去"修"会让判据失去意义（谁判谁修 ⇒ 永远绿）。
"""
from __future__ import annotations

import re
import time
from pathlib import Path

# ══════════════════════════════════════════════════════════════════════════
# 解析：四种文档各有自己的"锚"格式，这里只解析**必要字段**，不做全文理解
# ══════════════════════════════════════════════════════════════════════════
# ★ 口径：解析器**尽量宽进**（多种写法都认），因为文档是人写的、格式会漂；
#   但**判据严出**（认不出就报"锚缺失"，不猜）。猜出来的"通过"比红更危险。


def _读(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8")
    except OSError:
        return ""
    except UnicodeDecodeError:
        try:
            return p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return ""


# 快照版本：`> 快照版本：v0.1（未锁定）` / `| 快照版本 | v0.1 |`
_版本行 = re.compile(r"快照版本\s*[:：|]\s*(v?[\w.]+)")

# ★★ 编号锚：**行内任意位置**，不锚行首。
#
#   第一版写的是 `^(?:\|\s*)?(PR-\d+...)`（锚行首）—— 判据当场判红三次，全是同一个根因：
#   真实的写法是 **行中引用**：`按 PR-7 改参数`、`判定依据：PR-7`。
#   锚行首的解析器把整份任务书读成"一条都不引用" ⇒ **LINK-01 直接失效**
#   （它会把"引用了不存在的 PR-999"误判成"纯新增任务书，通过"）。
#
#   ★ 这是本项目反复出现的那类病：**判据接上了，但接错了对象**。
#     而它错得特别安静——解析器不报错，只是**什么都没找到**，于是判据一路绿。
#     判据里专门有一条测这个（⑧ 段"认不出就报锚缺失"），正是它逼出了这个 bug。
#
#   口径：编号可以被 `「」` `、` `（）` 包着，也可以紧贴中文；只认编号本体。
_编号模式 = (r"(?:PR|G|AD|TS|COORD|TRIG|LINK|FIXLOOP|PERSIST|PROOF|INHERIT|CONDVER)"
             r"-\d+(?:[\w.-]*\d)?")
_条款号 = re.compile(_编号模式)


def 解析快照(路径) -> dict:
    """从快照里抽出 **版本号** 与 **可引用的条目集合**。

    ★ 为什么"条目集合"要抽两样：编号（PR-/G-/TS-…）与 §五.1 表里的**概念名**。
      任务书既可以引用编号，也可以引用概念（"按『盘位』的定义"）——
      设计上两种都允许，所以两种都要能被查到。
    """
    p = Path(路径)
    文 = _读(p)
    if not 文:
        return {"存在": False, "路径": str(p), "版本": None, "条目": set(), "概念": set()}
    m = _版本行.search(文)
    条目 = set(_条款号.findall(文))
    概念: set[str] = set()
    # §五.1 合法概念全集表格：| 概念 | 定义原文 | 首次出现 | 知识等级 |
    for ln in 文.splitlines():
        s = ln.strip()
        if not s.startswith("|") or "---" in s:
            continue
        格 = [x.strip() for x in s.strip("|").split("|")]
        if len(格) >= 3 and 格[0] and not 格[0].startswith("概念") and len(格[0]) <= 24:
            概念.add(格[0])
    return {"存在": True, "路径": str(p), "版本": (m.group(1) if m else None),
            "条目": 条目, "概念": 概念, "行数": 文.count("\n") + 1}


# 任务书版本声明：`绑定快照版本: v0.1` / `快照版本：v0.1`
_任务书版本 = re.compile(r"(?:绑定)?快照版本\s*[:：]\s*(v?[\w.]+)")
# 任务书执行项：`1. xxx` / `执行项1` / `| TS-001 |`
_执行项 = re.compile(r"^\s*(?:(\d+)[.、)]\s+|执行项\s*(\d+))", re.MULTILINE)


def 解析任务书(路径) -> dict:
    p = Path(路径)
    文 = _读(p)
    if not 文:
        return {"存在": False, "路径": str(p), "版本": None, "引用": set(), "执行项": []}
    项 = []
    for m in _执行项.finditer(文):
        n = m.group(1) or m.group(2)
        项.append(int(n))
    # 任务书里引用的编号：全文扫（不只表头），因为引用可以出现在任何执行项里
    引用 = set(_条款号.findall(文))
    v = _任务书版本.search(文)
    return {"存在": True, "路径": str(p), "版本": (v.group(1) if v else None),
            "引用": 引用, "执行项": sorted(set(项)), "行数": 文.count("\n") + 1}


# 回执执行项：`执行项1 ✅` / `1. xxx ✅` / `| 执行项1 |`
def 解析回执(路径) -> dict:
    p = Path(路径)
    文 = _读(p)
    if not 文:
        return {"存在": False, "路径": str(p), "执行项": [], "依据": set(), "批号": None}
    项 = []
    for m in _执行项.finditer(文):
        n = m.group(1) or m.group(2)
        项.append(int(n))
    # ★ 批号写法实测有三种：`**批号**: ORCH-1`、`批号：ORCH-1`、`| 批号 | ORCH-1 |`
    #   第一版正则没考虑 markdown 的 `**` 加粗 ⇒ 真回执全都解析不出批号（`批号=None`），
    #   而 LINK-05 靠文件名兜底、看着还是绿的 ⇒ **又是一个"接错对象但看不见"**。
    b = re.search(r"批号\*{0,2}\s*[:：|]\*{0,2}\s*([\w-]{2,})", 文)
    return {"存在": True, "路径": str(p), "批号": (b.group(1) if b else None),
            "执行项": sorted(set(项)), "依据": set(_条款号.findall(文)),
            "行数": 文.count("\n") + 1}


# 状态索引：`| 轮次 | 日期 | 回执报告 | 状态 |` 表格 + `### 回执归档记录` 章节
def 解析状态索引(路径) -> dict:
    p = Path(路径)
    文 = _读(p)
    if not 文:
        return {"存在": False, "路径": str(p), "归档": [], "快照版本": None}
    归档: list[str] = []
    见章 = False
    在表 = False
    for ln in 文.splitlines():
        s = ln.strip()
        if s.startswith("#") and "回执归档" in s:
            见章 = True
            在表 = True
            continue
        if 在表 and s.startswith("#"):          # 下一个章节 ⇒ 表结束
            在表 = False
        if 在表 and s.startswith("|") and "---" not in s:
            格 = [x.strip() for x in s.strip("|").split("|")]
            if 格 and 格[0] and 格[0] not in ("轮次", "回执"):
                归档.append(格[0])
    v = re.search(r"依赖工程快照\s*[:：]?\s*(\S+)\s*(v?[\w.]+)", 文)
    # ★ 区分「没有这一章」与「有章但表空」—— 两种都是问题，但**修法不同**：
    #   没章 ⇒ 快照/索引的**结构**没按约定写（去补章节）；
    #   有章空表 ⇒ 结构对，是**归档这一步没做**（去跑归档）。
    #   第一版没区分，LINK-05 对"有章空表"报的是"没有章节" —— 把人指去改结构。
    return {"存在": True, "路径": str(p), "归档": 归档, "有归档章节": 见章,
            "快照版本": (v.group(2) if v else None), "行数": 文.count("\n") + 1}


# ══════════════════════════════════════════════════════════════════════════
# 五条联动判据
# ══════════════════════════════════════════════════════════════════════════
def link01_任务书引用可查(任务书: dict, 快照: dict) -> tuple[bool, str]:
    """LINK-01：任务书引用的编号，必须**能在快照里查到**。

    ★ 为什么这是最要紧的一条：它把"任务书可以凭空写"这件事堵死了。
      没有它，任务书能整篇建立在**项目里不存在的假设**上 ——
      而 AI 最擅长干这个（用预训练里的通用做法补上"应该是怎样的"）。
      一旦任务是凭空写的，后面的判据再严也救不回来：**方向就错了**。

    ★ 宽出口径：任务书**一条都不引用**时判**通过但提示** ——
      因为有的任务书是纯新增（不基于现有条款）。但**引用了一条查不到的**，
      一律判红：那不是"没引用"，是**引用了不存在的东西**。
    """
    if not 快照.get("存在"):
        return False, "快照读不到 ⇒ 无法核对引用（这是硬条件，不是「跳过」）"
    if not 任务书.get("存在"):
        return False, "任务书读不到"
    引 = 任务书.get("引用") or set()
    if not 引:
        return True, "任务书没有引用任何编号（纯新增任务，可以；若要引用请写清编号）"
    有 = 快照.get("条目") or set()
    缺 = sorted(引 - 有)
    if 缺:
        return False, (f"任务书引用了 {len(引)} 个编号，其中 **{len(缺)} 个在快照里查不到**："
                       f"{'、'.join(缺[:6])}{'…' if len(缺) > 6 else ''}"
                       f" ⇒ 任务书建立在项目里**不存在**的假设上，先补快照或改任务书")
    return True, f"任务书引用 {len(引)} 个编号，**全部**在快照里可查"


def link02_任务书版本不漂移(任务书: dict, 快照: dict) -> tuple[bool, str]:
    """LINK-02：任务书声明的快照版本，必须与快照当前版本**一致**。

    ★ 为什么"漂移"要单独判：版本不一致说明**任务书写在旧快照上**。
      此时任务书里的条款编号可能还在（编号不会消失），但**含义可能已经变了**
      —— 例如"block=w32/grid=46"曾经是对的，快照改过之后它是错的。
      ⇒ 光靠 LINK-01 查不到这种错（编号还在，所以查得到）。

    ★ 版本号缺失不判红（判"未声明"），因为老任务书本来就没有这一行；
      靠人先补。但**声明了且不一致**一律红。
    """
    if not 快照.get("存在"):
        return False, "快照读不到 ⇒ 无法核对版本"
    if not 任务书.get("存在"):
        return False, "任务书读不到"
    当 = 快照.get("版本")
    声 = 任务书.get("版本")
    if not 当:
        return False, "快照里**没有版本行** ⇒ 请补 `> 快照版本：vX.Y`（否则无法判漂移）"
    if not 声:
        return True, f"任务书**未声明**快照版本（快照当前 {当}）⇒ 建议补上；不判红"
    if 声 != 当:
        return False, (f"**漂移**：任务书写的是 {声}，快照已经是 {当} ⇒ "
                       f"任务书可能过期；条款编号可能还在但**含义已变**")
    return True, f"版本一致（{当}）"


def link03_回执执行项对齐(回执: dict, 任务书: dict) -> tuple[bool, str]:
    """LINK-03：回执的执行项编号 ⇄ 任务书的执行项编号，必须**一一对应**。

    ★ 为什么必须一一对应（而不是"回执项 ⊆ 任务书项"）：
      少一项 = 任务书要的没做完（**漏**）；多一项 = 做了任务书没写的事（**越界**）。
      两种都是问题。只判"少"会漏掉越界，只判"多"会漏掉漏做。
      ⇒ 判**对称差**。
    ★ 认不出一边时（编号写得不规范）判"锚缺失"而不是通过 —— 不许猜。
    """
    if not 回执.get("存在"):
        return False, "回执读不到"
    if not 任务书.get("存在"):
        return False, "任务书读不到"
    a, b = set(回执.get("执行项") or []), set(任务书.get("执行项") or [])
    if not a:
        return False, "回执里**认不出任何执行项编号** ⇒ 无法对齐（锚缺失，不许猜）"
    if not b:
        return False, "任务书里**认不出任何执行项编号** ⇒ 无法对齐（锚缺失，不许猜）"
    少 = sorted(b - a)
    多 = sorted(a - b)
    if 少 or 多:
        段 = []
        if 少:
            段.append(f"**任务书有、回执没有**：{少}（漏做）")
        if 多:
            段.append(f"**回执有、任务书没有**：{多}（越界）")
        return False, "执行项不对称 —— " + "；".join(段)
    return True, f"执行项一一对应（{len(a)} 项）"


def link04_回执依据覆盖(回执: dict, 任务书: dict) -> tuple[bool, str]:
    """LINK-04：回执的判定依据，必须**覆盖**任务书标注的依据编号。

    ★ 为什么要这条：任务书说"按 PR-X 判"，回执却按别的东西判完了 ——
      结果"测试通过"是真的，但**判的不是要求的那件事**。
      本项目吃过这类亏（判据口径不对正：门绿了但门判的对象错了）。
    """
    if not 回执.get("存在") or not 任务书.get("存在"):
        return False, "回执或任务书读不到"
    要 = set(任务书.get("引用") or set())
    if not 要:
        return True, "任务书没标注依据编号 ⇒ 无需覆盖核查"
    有 = set(回执.get("依据") or set())
    缺 = sorted(要 - 有)
    if 缺:
        return False, (f"任务书标注了 {len(要)} 个依据，回执**少判据 {len(缺)} 个**："
                       f"{'、'.join(缺[:6])} ⇒ 门可能绿了，但判的不是要求的那件事")
    return True, f"回执依据覆盖任务书全部 {len(要)} 个依据"


def link05_回执已归档(回执: dict, 状态索引: dict) -> tuple[bool, str]:
    """LINK-05：回执必须**已归档**进状态索引的「回执归档记录」。

    ★ 为什么这条最实在：本项目实测，状态索引里那几十行归档**全是人手工补的**。
      ⇒ 只要人忘了，回执就"没发生过"：**下一轮的人（或 AI）读状态索引，会以为那轮没做。**
      这正是"哪里断了看不出来"的源头。

    ★ 认法：拿回执的**文件名**或**批号**去状态索引里找。两者认一个即可
      （有人按文件名归档，有人按批号）。
    """
    if not 回执.get("存在"):
        return False, "回执读不到"
    if not 状态索引.get("存在"):
        return False, "状态索引读不到"
    档 = 状态索引.get("归档") or []
    if not 状态索引.get("有归档章节"):
        return False, ("状态索引里**没有『回执归档记录』这一章** ⇒ 结构没按约定写，"
                       "先去补章节（这跟「归档这一步没做」是两回事，修法不同）")
    if not 档:
        return False, ("『回执归档记录』**这一章是空的** ⇒ 一章都没归档过。"
                       "读状态索引的人会以为这些轮次从没发生过")
    名 = Path(回执["路径"]).name
    批 = 回执.get("批号")
    命中 = [x for x in 档 if x and (x in 名 or 名 in x or (批 and (x == 批 or 批 in x)))]
    if not 命中:
        return False, (f"回执 `{名}`（批号 {批 or '未标'}）**未归档** ⇒ "
                       f"读状态索引的人会以为这轮没做。已归档 {len(档)} 条：{档[-3:]}")
    return True, f"已归档（命中 {命中[-1]}；状态索引共 {len(档)} 条归档）"


# ══════════════════════════════════════════════════════════════════════════
# 整体联动体检（一条命令给出四者是否对得上）
# ══════════════════════════════════════════════════════════════════════════
def 联动体检(*, 快照, 任务书=None, 回执=None, 状态索引=None) -> dict:
    """把四条文档的路径给进来，返回五条判据的结论。

    允许缺省（缺的条目标"未提供"，**不判红**）—— 因为日常不一定同时有四份文档。
    ★ 但缺省**不算通过**：结论里明写"未提供"，免得"没验"被读成"验过了"。
    """
    出: dict = {"时间": time.strftime("%Y-%m-%d %H:%M:%S"), "判据": {}, "通过": True}
    S = 解析快照(快照) if 快照 else {"存在": False}
    R = 解析任务书(任务书) if 任务书 else {"存在": False}
    回 = 解析回执(回执) if 回执 else {"存在": False}
    状 = 解析状态索引(状态索引) if 状态索引 else {"存在": False}

    待判 = []
    if R.get("存在") and S.get("存在"):
        待判.append(("LINK-01 任务书引用可查", lambda: link01_任务书引用可查(R, S)))
        待判.append(("LINK-02 任务书版本不漂移", lambda: link02_任务书版本不漂移(R, S)))
    if 回.get("存在") and R.get("存在"):
        待判.append(("LINK-03 回执执行项对齐", lambda: link03_回执执行项对齐(回, R)))
        待判.append(("LINK-04 回执依据覆盖", lambda: link04_回执依据覆盖(回, R)))
    if 回.get("存在") and 状.get("存在"):
        待判.append(("LINK-05 回执已归档", lambda: link05_回执已归档(回, 状)))

    for 名, f in 待判:
        try:
            ok, 说明 = f()
        except Exception as e:                       # noqa: BLE001
            ok, 说明 = False, f"这条判据自己崩了（{type(e).__name__}: {e}）⇒ 别当通过"
        出["判据"][名] = {"通过": ok, "说明": 说明}
        if not ok:
            出["通过"] = False
    出["文档"] = {
        "快照": {"存在": S.get("存在"), "版本": S.get("版本"),
                 "条目": len(S.get("条目") or []), "概念": len(S.get("概念") or [])},
        "任务书": {"存在": R.get("存在"), "版本": R.get("版本"),
                   "引用": len(R.get("引用") or []), "执行项": len(R.get("执行项") or [])},
        "回执": {"存在": 回.get("存在"), "批号": 回.get("批号"),
                 "执行项": len(回.get("执行项") or [])},
        "状态索引": {"存在": 状.get("存在"), "归档": len(状.get("归档") or [])},
    }
    if not 待判:
        出["通过"] = False
        出["判据"]["（未提供）"] = {"通过": False,
                                  "说明": "没有一对文档同时提供 ⇒ **一条判据都没跑**（这不是通过）"}
    return 出


def 摘要(体: dict) -> str:
    段 = []
    for 名, v in (体.get("判据") or {}).items():
        段.append(f"{'✓' if v['通过'] else '✗'} {名}")
    return f"联动{'通过' if 体.get('通过') else '不通过'}：" + " · ".join(段)
