"""R276：把「规划 → 裁决 → 定位 → 改码 → 复验」串成一次调用（闭环）。

★ 为什么（真读数，2026-11-05）：
  R275 之后，各段都在了，但**仍然要调用方自己串**：
    `auto_goal`（规划+清单）→ `run_goal`（裁决）→
    红了之后 `generic_goal` 的逐文件/整批应用（改码）→ 再 `run_goal`（复验）
  串不起来就不是"无人值守"——调用方少串一步，链条就静默断在半路。

★ 诚实边界（本模块最要紧的一条）：
  **改码必须由模型产出**（`adopted: {rel: 新全文}`）。本机上游整段不可用时，
  本函数**必须如实报 `blocked_on_model`**，而不是"跑完了、绿了"或"跑完了、红了"——
  那两种说法都会让人以为"闭环试过了"。
  ⇒ 「没测到不能当通过了」在闭环层面的等价形态：
     **没有改码输入时，闭环只证明"裁决和定位是通的"，不证明"目标能达成"。**
"""
from __future__ import annotations

from pathlib import Path

from . import auto_goal as _ag
from . import generic_goal as _gg
from . import goal_runner as _gr


def close_loop(plan: dict, 仓根: Path | str, *,
               adopted: "dict[str, str] | None" = None,
               源码根: "list[str] | None" = None,
               上限文件: int = 12) -> dict:
    """一次调用跑完：规划 → 裁决 → （有改码输入才）应用 → 复验。

    参数：
      plan    : `auto_goal.plan_tasks()` 的返回（或工具 `auto_goal` 的回执）
      adopted : `{相对路径: 新全文}`。**为 None 表示这次没有模型产出**
                ⇒ 本函数只跑「裁决 + 定位」，并明确报 `blocked_on_model`。
      源码根  : 改动面搜索根（默认 `src` / 仓根下已存在的前两个目录）

    返回：
      {
        "ok": bool,
        "阶段": "裁决" | "定位" | "已应用" | "复验" | "阻塞",
        "首轮": run_plan 的结果,
        "改动面": {"文件": [...]} 或 {"原因": str},
        "应用": {...} | None,
        "复验": run_plan 的结果 | None,
        "blocked_on_model": bool,
        "诚实边界": str,
      }
    """
    def _红段数(果: dict) -> int:
        """红段数 = 判据说"这段还不绿"的个数。用于判"这个改动到底有没有变好"。"""
        return sum(1 for x in (果.get("段") or []) if x.get("状态") in ("红", "拒跑", "异常"))

    根 = Path(仓根).resolve()
    出: dict = {"ok": False, "阶段": "", "首轮": None, "改动面": None,
                "应用": None, "复验": None, "blocked_on_model": False,
                "诚实边界": "闭环只证明裁决/定位/复验是通的；改码内容由模型产出。"}

    # ── ① 裁决 ──────────────────────────────────────────────
    首 = _gr.run_plan(plan, 根)
    出["首轮"] = 首
    出["阶段"] = "裁决"
    if 首.get("达成"):
        出.update(ok=True, 阶段="已达成")
        出["诚实边界"] = "起始就全绿：没有需要修的东西（这不是闭环的功劳）。"
        return 出

    # ── ② 定位（失败栈 → 改动面）────────────────────────────
    # 把 run_plan 的逐段裁决合成为 gate_spec 形状的红条目，交给同一个改动面解析器。
    红条目: list[dict] = []
    for x in (首.get("段") or []):
        if x.get("状态") != "红":
            continue
        _门 = x.get("门") or {}
        红门 = [k for k, v in _门.items() if not v]
        # ★ R276c：**必须把门自己声明的目标文件带上**（`in`/`file`/`path`），
        #   否则改动面只能靠失败栈推；而文本门（grep_required 等）没有失败栈
        #   ⇒ 改动面恒空 ⇒ 闭环在"定位"这一阶段就断了。
        _条 = {"gate": "、".join(红门) or x.get("tid"), "ok": False,
               "err": f"{x.get('tid')}（{x.get('kind')}）红：{红门}",
               "tid": x.get("tid")}
        for _g in (x.get("_门规格") or []):
            for _k in ("in", "file", "path", "target"):
                if _g.get(_k):
                    _条.setdefault(_k, _g[_k])
        红条目.append(_条)
    if not 红条目:
        出.update(阶段="定位", ok=False)
        出["改动面"] = {"原因": "没有红的段（但整体未达成）⇒ 通常是段被级联跳过；"
                                "先修最上游那段"}
        出["诚实边界"] += " 未达成但不是某段红 ⇒ 上游级联，本轮不给改动面。"
        return 出
    _根们 = [根 / s for s in (源码根 or []) if (根 / s).is_dir()]
    if not _根们:
        候选 = [p for p in ("src", "lib", "app", "pkg") if (根 / p).is_dir()]
        _根们 = [根 / c for c in 候选[:2]] or [根]
    面 = _gg._失败栈改动面236(红条目, 根, _根们)
    出["改动面"] = {"文件": 面, "搜索根": [str(p) for p in _根们], "红条目": len(红条目)}
    出["阶段"] = "定位"
    if not 面:
        出["改动面"]["原因"] = ("这次的红没有指向任何源码文件 ⇒ 多半是判据门本身/命令问题，"
                                "不是改源码能修的")
        出["诚实边界"] += " 改动面为空 ⇒ 不要派模型改码（会把无关文件改坏）。"
        return 出

    # ── ③ 改码：没有模型产出就如实阻塞 ──────────────────────
    if not adopted:
        出.update(blocked_on_model=True, 阶段="阻塞")
        出["诚实边界"] = (
            "已定位到改动面，但**没有改码输入**（adopted 为空）⇒ 无法应用、无法复验。"
            "这一档只证明「裁决 + 定位」是通的，**不证明目标能达成**；"
            "别把它当'试过了'。")
        return 出

    # ── ④ 应用（逐文件 keep/rollback，R180 整批兜底）─────────
    基线 = _gg._红门违规点([
        {"gate": 条["gate"], "ok": False, "err": 条["err"]} for 条 in 红条目])
    交付 = [{"path": p, "focus": 0, "agent_instruction": "",
             "gates": [], "depends_on": [], "machine": None}
            for p in 面 if p in adopted]
    # ★★★★★ R276d（真读数抓的）：**基线为空时 `_增量应用` 直接返回空结果。**
    #   真证据（真仓跑 close_loop）：`应用: {'保留': [], '剩红': 0, '回退': []}`
    #   —— 改码一个字都没落盘，而它**不报错**。
    #   源码原文：`if not 基线: return {}, [], [], []`。
    #   而基线来自 `_红门违规点`：文本门（grep_required 等）**没有违规点位置**
    #   ⇒ 基线恒空 ⇒ 逐文件裁决这条链对文本门**整条失效**。
    #   ⇒ 不能硬套这条链。基线为空时走**"全批应用 + 复验裁决"**：
    #     应用 → 用同一份计划复验 → 绿则保留，红则**整批回滚**（有备份）。
    #     ★ 这条路径的安全性不靠"违规点减少"，靠**最终门全绿**——更硬。
    if not 基线:
        _红段数_基 = _红段数(首)
        _备份 = {}
        _应用列 = []
        for _rel, _文 in adopted.items():
            if _rel not in 面:
                continue                       # 只改改动面内的文件
            try:
                _bk = _gg._backup_file(_rel, 根)
                _gg._apply_file(_rel, _文, 根)
                _备份[_rel] = _bk
                _应用列.append(_rel)
            except Exception as _e1:           # noqa: BLE001
                出["应用"] = {"异常": f"{_rel}: {type(_e1).__name__}: {_e1}"}
                return 出
        出["应用"] = {"保留": [], "剩红": 0, "回退": [],
                      "路径": "全批应用（基线为空：文本门没有违规点可逐文件比较）",
                      "已写": _应用列}
        if not _应用列:
            出["应用"]["原因"] = "adopted 里没有一个文件落在改动面内 ⇒ 不写盘"
            出["阶段"] = "定位"
            return 出
        # ★★★★★ R278b（真读数抓的）：**整批回滚让迭代永远前进不了。**
        #   真证据（真仓，三段目标，模型每轮只改对一个文件）：
        #     轮1 应用 a/b/c 三个文件，只有 a.py 改对 ⇒ 复验红 ⇒ **整批回滚** ⇒
        #     连改对的 a.py 也被丢掉 ⇒ 轮2 又从零开始 ⇒ 永远到不了。
        #   这正是 `_增量应用` 文档里那句「用整 crate 的布尔去裁决一批文件，
        #   只能是全有或全无 ⇒ 中长线任务永远不可能收敛」——我上一轮绕开了
        #   逐文件裁决（因为文本门没有违规点），却掉进了**同样的坑**。
        #   ⇒ 修法：**逐文件应用 + 逐文件复验**。每个文件单独试写、单独复验，
        #     绿了留下、红了回退这一个。仓在任何时刻都只含"已被判据确认的改动"。
        #   ★ 安全性不变：留下的每一个改动都被**目标仓自己的判据**确认过；
        #     最终验收仍然是 run_plan 全绿（不因为"接受了部分进展"就判达成）。
        留下列: list[str] = []
        退回列: list[str] = []
        for _rel in _应用列:
            _文 = adopted[_rel]
            _bk2 = _备份[_rel]
            # 单独试：把这个文件写回去，其他文件保持当前（已确认）状态
            try:
                _gg._apply_file(_rel, _文, 根)
            except Exception:                  # noqa: BLE001
                退回列.append(_rel)
                continue
            _试 = _gr.run_plan(plan, 根)
            if _试.get("达成"):
                留下列.append(_rel)
                break                          # 已达成，剩余文件不必再试
            # 没达成也要看"是不是变好了"：**剩下的红段数严格减少**才留
            if _红段数(_试) < _红段数_基:
                留下列.append(_rel)
                _红段数_基 = _红段数(_试)
            else:
                try:
                    _gg._rollback_file(_bk2)
                except Exception:              # noqa: BLE001
                    pass
                退回列.append(_rel)
        复0 = _gr.run_plan(plan, 根)
        出["应用"]["保留"] = 留下列
        出["应用"]["回退"] = 退回列
        出["应用"]["路径"] = "逐文件应用 + 逐文件复验（红段数严格减少才留）"
        出["复验"] = 复0
        出["阶段"] = "复验"
        if 复0.get("达成"):
            出.update(ok=True)
            出["诚实边界"] = ("闭环通过：定位→逐文件应用→复验全绿。"
                            "留下的每个改动都被目标仓自己的判据确认过。")
        else:
            出["诚实边界"] = ("未达成，但**逐文件保留了仍使红段数减少的改动**"
                            "（整批回滚会让迭代永远前进不了）；"
                            "被回退的文件见 应用.回退。")
        return 出
    try:
        _res, red, 留, 退 = _gg._增量应用(dict(adopted), 基线, 根, 交付)
    except Exception as e:                          # noqa: BLE001
        出.update(阶段="应用")
        出["应用"] = {"异常": f"{type(e).__name__}: {e}"}
        return 出
    出["应用"] = {"保留": [r for r, _ in 留], "剩红": len(red), "回退": 退,
                  "路径": "逐文件违规点裁决"}
    出["阶段"] = "已应用"

    # ── ⑤ 复验：用同一份计划再裁一次 ────────────────────────
    复 = _gr.run_plan(plan, 根)
    出["复验"] = 复
    出["阶段"] = "复验"
    出["ok"] = bool(复.get("达成"))
    if 出["ok"]:
        出["诚实边界"] = "闭环通过：定位→应用→复验全绿。改码内容来自调用方，机器只判不改。"
    else:
        出["诚实边界"] = "应用后仍未达成 ⇒ 见 复验.未达成的原因"
    return 出
