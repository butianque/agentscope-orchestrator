"""语义入口 —— 给一个场景，一次返回**关联好的一整块项目事实**。

## 这个模块治的病：不是"AI 没工具"，是"**AI 要查六次才对得上一件事**"

六根柱子各自都有读接口了（坐标链能查、知识库能查、盲区能查…）。
但对干活的 AI 来说，**最贵的是上下文和次数**：

```
按现在各查一次：  口径查一次 · 引用查一次 · 历史查一次
                 · 盲区查一次 · 联动查一次   ⇒ 5 次调用 + 5 块割裂的返回
```

而 AI 真正想知道的是一句话：**"这件事在这个项目里该怎么办、我以前踩过什么坑。"**
⇒ 那就**一次把它要的那些事实关联好交给它**，别让它自己拼。

## 为什么这叫「语义」入口，而前面六个不叫

前六个是**结构入口**：坐标链只能按坐标查、知识库只能按关键词查 ——
**问法必须知道模块长什么样**（"我要查坐标链"）。
语义入口反过来：**按"我现在在干什么"问**，模块由工具去挑。

```
问：我要改 plot/kHz.py 里这段
⇒ 回：这个项目的口径（3 条命中）· 谁引用了这个文件 · 这文件改过几次
      · 有没有相关的盲区 · 四方文档状态
```

## 上下文纪律（本模块的硬要求）

**一次调用返回的总字数有上限**（默认 2000 字），超了就按关联度砍 ——
**返回长度不可控的"语义工具"会把 AI 的上下文吃掉**，比没有这个工具更坏。
⇒ 每一段都必须给出"**为什么这段在这儿**"，让 AI 知道砍掉了什么、还能问什么。

★ 本模块**只做关联与裁剪，不产生任何新事实**：
  每条信息的真值来源都在原来的六根柱子里，这里只负责"一次给全 + 排序 + 截断"。
  它若与源头不一致，**错的是它**。
"""
from __future__ import annotations

import os
import re
from pathlib import Path

# 一次返回的总字数上限。★ 可调，但**必须有上限** ——
# 语义工具最危险的失败方式是"每次都很全" ⇒ 上下文被吃光，AI 反而更笨。
默认上限 = 2000


def _截(文: str, 上限: int) -> str:
    if not 文:
        return ""
    if len(文) <= 上限:
        return 文
    return 文[:max(0, 上限 - 14)].rstrip() + "…（已截断）"


def _相对(路径: str, 根: str = "") -> str:
    """尽量给相对路径 —— 绝对路径在提示里又长又无用。"""
    try:
        p = Path(str(路径))
        if 根:
            return p.relative_to(Path(根)).as_posix()
        return p.name if p.is_absolute() else str(路径)
    except Exception:                            # noqa: BLE001
        return str(路径)


# ══════════════════════════════════════════════════════════════════════════
# 各柱的"取一段"适配（每个都**绝不抛**，坏了返回空串 + 原因）
# ══════════════════════════════════════════════════════════════════════════
def _口径段(关键词: str, 上限: int) -> tuple[str, list[str]]:
    """项目口径：**永远排第一** —— 它决定"该怎么做"，别的只是"以前怎么做的"。

    ★★★ 这里有个**必须写下来的坑**（第一版就踩了，判据抓出来的）：

      `KB.命中()` 的返回值长这样：
        ```
        True,
        "命中 1 条够格（最高分 1.0 · 命中 999 词元 · id=口径-xxx）",   ← 只有 42 字！
        {"条数": 1, "最高分": 1.0, "条目": "口径-xxx"}
        ```
      **它只回答"有没有答案"，不给答案正文。**（这是它的本分 —— 分工线只需要
      "有没有"，见 `dispatch` 那一轮的口径。）

      ⇒ 第一版我直接把这个 42 字的统计串当"材料"塞进提示，
        于是 AI 看到的是一句 **"知识库里有答案"**，却**看不到答案本身**。

    ★ 这是"**接上了但接错对象**"的又一例 —— 而且静默：不报错、不为空、
      甚至看起来很合理（提示里确实出现了"项目口径"四个字）。
      ⇒ 正确做法：**用 `命中()` 判"有没有"，用 `查()` 取正文**。两件事两个函数。
    """
    行: list[str] = []
    来源: list[str] = []
    try:
        from . import project_kb as KB
        有, 说明, 详 = KB.命中(关键词 or "", 最低分=0.25, 最少词元=2)
        # ★ 无论够不够格，**都要去取正文** —— "有没有答案"和"答案是什么"是两件事。
        正文 = _取知识正文(关键词, 上限, 只要熟的=有)
        if 有:
            行.append(f"### 项目口径（命中，**优先于通用做法**）\n"
                     + (正文 or f"（命中但取不到正文：{说明[:80]}）"))
            来源.append("project_kb")
        elif 正文:
            # 没到"命中"的门，但有沾边条目 ⇒ **如实标注"沾边不确切"**。
            # 装成"命中"比不给更坏（会让 AI 拿无关的东西当依据）。
            行.append(f"### 项目口径（**沾边但不确切**，自行判断）\n{正文}")
            来源.append("project_kb:沾边")
    except Exception as e:                       # noqa: BLE001
        行.append(f"### 项目口径\n（读不到：{type(e).__name__}）")
    return "\n\n".join(行), 来源


def _取知识正文(关键词: str, 上限: int, *, 只要熟的: bool = False) -> str:
    """把知识条目的**正文**取出来（`命中` 只给"有没有"，正文要自己取）。

    `只要熟的=True` ⇒ 优先取高相关的；否则按检索顺序取前几条。
    """
    try:
        from . import project_kb as KB
        条们 = KB.查(关键词=关键词 or "", 上限=6) or []
        if not 条们:
            return ""
        # ★ 按相关分排序（`查` 的顺序不保证）；没有分的按原序。
        条们 = sorted(条们, key=lambda x: -(x.get("_相关分") or 0))[:4]
        块 = []
        for t in 条们:
            # 只在**够格**时把"必须/禁止"这类硬口径带星号强调；
            # 沾边的时候不加，免得看起来像结论。
            idv = str(t.get("id") or "")
            正 = re.sub(r"\s+", " ", str(t.get("正文") or "")).strip()
            强 = str(t.get("强度") or "")
            标 = f"**{强}** · " if (只要熟的 and 强 in ("必须", "禁止")) else ""
            块.append(f"- {标}{idv}：{正}")
        全 = "\n".join(块)
        return _截(全, 上限)
    except Exception:                            # noqa: BLE001
        return ""


def _外部段(关键词: str, 上限: int) -> tuple[str, list[str]]:
    """外部资料（可选，没配就没有 —— 不说"不可用"，只说"这个项目没接"）。"""
    try:
        from . import semsearch_link as SL
        if not SL.可用():
            return "", []
        材料 = SL.注入(关键词 or "", 上限=上限)
        if not 材料:
            return "", []
        return f"### 外部资料\n{_截(材料, 上限)}", ["semsearch"]
    except Exception:                            # noqa: BLE001
        return "", []


def _引用段(引用: str, 上限: int) -> tuple[str, list[str]]:
    """谁牵动它：历史坐标 + 四方联动（一次给全）。

    ★ 为什么把"历史"和"联动"合成一段而不是两段：它们回答的是**同一个问题**
      （"这件事牵动什么"），分成两段会让 AI 以为要分两次查。
    """
    行: list[str] = []
    来源: list[str] = []
    try:
        from . import coord_chain as CC
        条 = CC.查(引用含=(引用 or "")) if 引用 else []
        if 条:
            # ★ 只给"最近几次 + 总次数"，不给全部 —— 719 条全列会把上下文吃光，
            #   而 AI 需要的是"改过几次、最近什么时候"，不是逐条历史。
            最近 = 条[-3:]
            行.append("### 历史坐标\n"
                     f"共 **{len(条)}** 次 · 最近："
                     + "；".join(f"{c.显示()}" for c in 最近))
            来源.append("coord_chain")
    except Exception:                            # noqa: BLE001
        pass
    try:
        from . import linkage as LK
        目 = os.environ.get("ORCH_LINKAGE_DIR", "")
        if 目:
            d = Path(目)
            快照 = _挑(d, "快照")
            任务 = _挑(d, "任务书")
            回执 = _挑(d, "回执")
            索引 = _挑(d, "索引")
            if 快照 and 任务:
                体 = LK.联动体检(快照=快照, 任务书=任务, 回执=回执, 状态索引=索引)
                s = LK.摘要(体)
                行.append(f"### 四方联动\n{_截(s if isinstance(s, str) else str(s), 上限 // 2)}")
                来源.append("linkage")
    except Exception:                            # noqa: BLE001
        pass
    return "\n\n".join(行), 来源


def _挑(目录: Path, 关键: str) -> Path | None:
    """按内容挑最像的那种文档（**不按文件名排序** —— 本仓在这里栽过）。"""
    try:
        if not 目录.is_dir():
            return None
        cands = [p for p in 目录.glob("*.md") if 关键 in p.name]
        if not cands:
            return None
        # 内容长的信息更全（真实项目实测：同名文件里短的往往是别人的）
        return max(cands, key=lambda p: p.stat().st_size)
    except Exception:                            # noqa: BLE001
        return None


def _盲区段(关键词: str, 上限: int) -> tuple[str, list[str]]:
    """以前在这儿踩过什么坑：盲区台账 + 该加门的（**记下即提**，已无门槛）。

    ★ 两样都要给，因为它们回答的是**不同的问题**：
      · `提示()` 给的是"沾边的已知盲区"（按相关度）；
      · `该加门的()` 给的是"**记下还没被门盖住的**" —— 这一档 AI 最该看，
        因为它是"我即将重复一个已经重复过 N 次的错误"的预警。
      ⇒ 只给前者的版本我第一版写过，等于**把这套东西最想要的那个信号藏起来了**。
    """
    行: list[str] = []
    来源: list[str] = []
    try:
        from . import blind_spot as BS
        该 = BS.该加门的()
        if 该:
            行.append("### ⚠ 该加门了（记过的、还没被门盖住）\n"
                     + "；".join(f"{str(x.get('症状', ''))[:70]}（{x.get('次数')} 次）"
                                for x in 该[:3])
                     + "\n⇒ 这类问题**不是靠注意能避免的**，该转成判据门。")
            来源.append("blind_spot:该加门")
        提 = BS.提示(关键词 or "", 上限字=上限)
        if 提:
            行.append(f"### 已知盲区（机器判不了的地方）\n{_截(提, 上限)}")
            来源.append("blind_spot")
    except Exception:                            # noqa: BLE001
        pass
    return "\n\n".join(行), 来源


def _事件段(上限: int) -> tuple[str, list[str]]:
    """这台机器最近干了什么（步数/检查点/告警）—— 让 AI 知道"我在哪一步"。"""
    try:
        from . import events as E
        st = E.统计()
        if not st.get("检查点数"):
            return "", []
        行 = (f"### 机器步数\n检查点 **{st.get('检查点数')}** · 步数 {st.get('步数')}"
             f" · 周期 {st.get('周期')}")
        if st.get("高级告警"):
            行 += f"\n⚠ **{st['高级告警']} 条 ERROR 以上告警**：" \
                  + "；".join(str(x)[:60] for x in (st.get("高级告警示例") or [])[:2])
        return 行, ["events"]
    except Exception:                            # noqa: BLE001
        return "", []


# ══════════════════════════════════════════════════════════════════════════
# 主入口：一次给全
# ══════════════════════════════════════════════════════════════════════════
# ★ 拆词后**不该当检索词**的东西：文件后缀名与量词 —— 它们几乎匹配一切，
#   放进检索只会把真正的答案挤下去（实测栽过一次）。
_检索停用词 = frozenset((
    "md", "py", "rs", "txt", "json", "lean", "toml", "yml", "yaml",
    "lock", "csv", "html", "css", "js", "ts", "sh", "bat", "ps1",
    "文件", "多少", "几个", "哪些", "相关", "有没有", "份",
))


def _逐条读数行(逐条: list[dict]) -> str:
    """把「逐条声明」渲染成**人能直接读**的一行。

    ★ 提成独立函数的理由（实测栽过两次）：段里改了输出格式、判据里手抄的
      期望串没跟着改 ⇒ **假红**。判据要能调用**同一个函数**，两边才不会漂。
    ★ 多根不许用 `/` 拼 —— 会拼出一条**看着像真路径的假路径**，
      而假路径比没路径更坏（人会当成"真有这个目录"）。
    """
    return " · ".join(
        f"{' + '.join('`' + r + '`' for r in 条['roots'])}"
        f"({条['kind']}) **{条['命中']}**"
        for 条 in 逐条) or "（没读逐条）"


def _项目文件段(词: str, 上限: int) -> tuple[str, list[str]]:
    """**本项目相关文件** —— 按名字从记忆索引**直接取回**，不是遍历。

    ★ 这一段存在的理由（本轮真跑取证）：记忆索引建好之后，
      `context` 原来只查知识库与坐标链 ⇒ **看不见项目本体的 4,354 个文件**。
      索引没人读 = 没接线。这一段就是那根线。

    ★ 四条不许含糊的：
      ① 命中要说**怎么命中的**（精确/后缀/前缀/包含），否则"差一点"看着像"就是它"；
      ② 命中太多要**明说截断**，不许让 AI 以为列全了；
      ③ 每类覆盖多少要**一起报**，否则"这一类没命中"与"这一类根本没进索引"
         在返回里长得一样；
      ④ ★ `场景` 是**一句话**，不是查询词。整串查不到就说"没有"是**假没有**
         （实测：一个「XX 相关的文件都有哪些」式的自然语言场景整串查 ⇒ 没命中，
         而那个文件明明就在索引里）⇒ **先整串、再拆词逐个查、合并**；
         仍然没有时要说清"我拿哪些词查过"。
    """
    try:
        from agentscope_orchestrator import autoengine as _ae
        idx = _ae.项目索引()
    except Exception as e:                       # noqa: BLE001
        return f"### 本项目相关文件\n（索引读不到：{type(e).__name__}）", []
    词 = (词 or "").strip()
    类 = [k for k in idx.kinds() if k != "formal"]
    # ★ 报**文件数**，不报键数。每个文件注册了两个键（路径键 + 名字键），
    #   所以 `count(k)` 大约是文件数的两倍 —— 报 `doc 4116` 会让人
    #   以为有 4,116 份文档（真值 2,059）。同一件事两个数最容易骗到人。
    _覆盖 = getattr(idx, "_覆盖", None) or {}
    _文件数: dict[str, int] = {}
    for 条 in (_覆盖.get("逐条") or []):
        _文件数[条["kind"]] = _文件数.get(条["kind"], 0) + 条["命中"]
    覆盖行 = " · ".join(
        f"{k} {_文件数.get(k, '?')}" + ("" if k in _文件数 else "（键数口径）")
        for k in 类)
    头 = "### 本项目相关文件（按名字从记忆索引取回，非遍历）"
    if not 词:
        return (f"{头}\n（没给检索词）各类覆盖（文件数）：{覆盖行}"
                f" · formal {idx.count('formal')}"), ["记忆索引"]


    # 整串 + 拆词（场景是一句话，不是词）
    #
    # ★ 拆词要**丢掉后缀类词**：实测场景「.audit_trail 有多少份回执 md」拆出
    #   `md`，而 `md` 匹配了**每一个** `.md` 文件的键（包含档）⇒
    #   `warnings_cmd.txt` 这类噪声排到了前面，真正想问的反而被挤下去。
    #   规则：纯 ASCII 词至少 3 个字符，且后缀名进停用表。
    试词: list[str] = [词]
    for t in re.split(r"[\s,，、;；:：/|（）()\[\]「」【】]+", 词):
        t = t.strip()
        if t in _检索停用词:
            continue
        if t.isascii() and len(t) < 3:
            continue
        if len(t) < 2 or t in 试词:
            continue
        试词.append(t)
    试词 = 试词[:8]

    def 查(kind: str, 限: int):
        try:
            return idx.index(kind).找(词, 上限=限)
        except Exception:                        # noqa: BLE001
            return []

    见到: dict[str, list] = {}                   # kind -> [(键, 路径, 种, 用词)]
    for t in 试词:
        for k in 类 + ["formal"]:
            if len(见到.get(k, [])) >= 3:
                continue
            try:
                命中 = idx.index(k).找(t, 上限=3)
            except Exception:                    # noqa: BLE001
                continue
            for 键, p in 命中:
                种 = ("精确" if 键 == t else
                      "后缀" if 键.endswith("." + t) else
                      "前缀" if 键.startswith(t) else "包含")
                现 = 见到.setdefault(k, [])
                if len(现) >= 3 or any(键 == x[0] for x in 现):
                    continue
                现.append((键, p, 种, t))

    行: list[str] = []
    for k in 类 + ["formal"]:
        if not 见到.get(k):
            continue
        标 = "formal（已证明单元）" if k == "formal" else k
        行.append(f"- **{标}**：")
        for 键, p, 种, 用词 in 见到[k]:
            尾 = "" if 用词 == 词 else f"，用词 `{用词}`"
            行.append(f"  - `{键}`（{种}{尾}）→ `{p.name}`")
    # ★ 逐条声明的命中数 —— 这一段存在的第二个理由：**「有多少份」要能直接读出来**。
    #   只报"按类"是不够的：声明里两条 `doc` 若合并成一个根，
    #   「`.audit_trail` 有多少份 .md」就拆不出来（一个 A/B 子代理正是卡在这，
    #   只能回退去列目录）。逐条报 ⇒ 与独立数真盘**逐条对得上**。
    _逐条 = (_覆盖.get("逐条") or [])
    条行 = _逐条读数行(_逐条)
    总文件 = sum(_文件数.values())
    脚 = (f"\n（**逐条声明**：{条行}；"
          f"合计 **{总文件}** 个文件 + {idx.count('formal')} 个形式化单元。"
          f"索引建好 {_ae.索引年龄():.0f} 秒前，本进程重建过 "
          f"{_ae.索引重建次数()} 次。要看别的名字就直接再问一次。）")
    if not 行:
        return (f"{头}\n**没命中** —— 我拿这些词查过："
                f"{' / '.join('`' + t + '`' for t in 试词)}；"
                f"各类都在索引里，但**这些词都不是已索引的名字**"
                f"（不是「这一类没进索引」）。{脚}"), ["记忆索引"]
    return 头 + "\n" + "\n".join(行) + 脚, ["记忆索引"]


def _概念段(词: str, 上限: int) -> tuple[str, list[str]]:
    """**概念召回**段：按名检索没命中时，用术语倒排表从"人话"里拉出代码/证明网络。

    ★ 为什么紧跟在「文件」段之后：`_项目文件段` 走**按名**检索（问句里得本来就有
      已索引的名字）。人问「让变换反复作用到不再变」这种**概念句**必然没命中 ——
      这一段就是那个缺口的补丁（实测概念词 → 代码侧召回 1.00、证明侧 0.48）。
    ★ 为什么**不在这里建索引**：建一次 ~40 秒（4185 文件切 n-gram）。放进一次
      `context` 调用就是把用户的十几秒换我的方便。缓存不在就明说，并给建法。
    ★ 只在「文件」段没命中时才出内容 —— 两条路是同一件事：**先按名，再按术语**。
    """
    try:
        from . import concept, real_task as _rt
        缓存 = Path(_rt.DIRS.WORKDIR) / concept._缓存名
        if not 缓存.is_file():
            return ("", [])
        r = concept.概念召回(词, 上限文件=6, 上限定理=6)
    except Exception:                                # noqa: BLE001 概念段坏不影响其它段
        return ("", [])
    if not (r.get("代码") or r.get("证明")):
        return ("", [])
    行 = ["### 概念网络（按术语倒排取回，**不是遍历**）"]
    for 名 in ("代码", "证明"):
        列 = r.get(名) or []
        if 列:
            行.append(f"- **{名}**：" + " · ".join(f"`{Path(p).name}`" for p, _ in 列[:6]))
    定 = r.get("定理") or []
    if 定:
        行.append("- **定理**：" + " · ".join(f"`{n}`" for _, n in 定[:6]))
    return ("\n".join(行), ["概念"])


def 看(场景: str = "", *, 引用: str = "", 关键词: str = "",
       上限: int = 默认上限, 要什么: str = "") -> dict:
    """给一个**场景**，返回关联好的一块项目事实。

    · `场景`  一句话说你在干什么（如"要改 plot 里的刻度输出"）
    · `引用`  具体文件/条款（有就给，能查到历史与引用关系）
    · `关键词` 单独指定检索词（不填就从 `场景` 抽）
    · `要什么` 只取某几段（逗号分隔：`口径,文件,引用,盲区,事件,外部`）；空=全要
    · `上限`  返回正文的字数上限（**必须有上限**，见模块 docstring）

    返回 `{正文, 段们, 来源, 用了多少段, 截断了吗}` —— 正文就是喂给 AI 的那一块。
    """
    词 = (关键词 or 场景 or "").strip()
    # 从场景里抽关键词（去掉"我要/帮我/改/看"这类无检索价值的词）
    抽 = re.sub(r"(我要|帮我|需要|看一下|查一下|怎么|如何|这个|那个|的|了|吧|呢)", " ", 词)
    抽 = " ".join(抽.split())[:120]
    要 = {x.strip() for x in (要什么 or "").replace("，", ",").split(",") if x.strip()}

    def 选(名: str) -> bool:
        return (not 要) or (名 in 要)

    段: list[str] = []
    来源: list[str] = []
    # ★★ 每段预算 = 总上限 ÷ 段数，**不许设下限**。
    #
    #   第一版写的是 `max(300, 上限 // 3)` —— 看着"保证每段至少有点内容"，
    #   实际是**总预算失控**：上限 500 时每段仍给 300，五段能出 1500+，
    #   而 `截断了吗` 按"拼接后总长 > 上限"判 ⇒ 判据抓出
    #   **正文 2117 字却标着"没截断"**。
    #
    #   ⇒ 口径：**子预算之和必须 ≤ 总预算**，这是算术约束，不是风格问题。
    #     想保证"每段至少有点内容"应该靠**段的取舍（顺序在先的优先）**，
    #     不是靠偷偷放大总预算。
    段数 = sum(1 for n in ("口径", "文件", "外部", "引用", "盲区", "事件")
               if 选(n))
    每段 = max(120, 上限 // max(1, 段数 + 1))       # +1：给「概念网络」留一份子预算

    # ★ 顺序是有讲究的：**口径在最前**（它决定该怎么做），
    #   历史/引用在其次（以前怎么做的），事件在最后（我在哪一步）。
    #   AI 读提示是线性的，放前面的更可能被用上。
    for 名, fn in (
        ("口径", lambda: _口径段(抽, 每段)),
        # ★ 「文件」紧跟口径：口径决定**该怎么做**，文件决定**去哪个文件做**。
        ("文件", lambda: _项目文件段(抽, 每段)),
        # ★ 「概念」紧跟「文件」：按名没命中时（人话问概念）它才真正给得出东西
        ("概念", lambda: _概念段(抽, 每段)),
        ("外部", lambda: _外部段(抽, 每段)),
        ("引用", lambda: _引用段(引用 or 抽, 每段)),
        ("盲区", lambda: _盲区段(抽, 每段)),
        ("事件", lambda: _事件段(每段)),
    ):
        if not 选(名):
            continue
        try:
            t, s = fn()
        except Exception as e:                   # noqa: BLE001 单段坏不影响其它段
            t, s = f"### {名}\n（这段读不到：{type(e).__name__}）", []
        if t:
            段.append(t)
            来源 += s

    正 = "\n\n".join(段)
    # ★ 判定"截断了吗"要**分两层**，否则会漏报：
    #   ① 段内被 `_截` 砍过（每段自己截的）—— 这个信号在拼完之后就看不出来了；
    #   ② 拼接后总长仍超上限 ⇒ 还要再砍。
    #   第一版只判 ② ⇒ 段内早就砍过、拼接后刚好不超 ⇒ **标成"没截断"**，
    #   而 AI 拿到的是被砍过的内容却以为完整 —— 这就是最该避免的那种静默失效。
    段内已截 = any(("…（已截断）" in t) for t in 段)
    总超 = len(正) > 上限
    截 = 段内已截 or 总超
    正 = _截(正, 上限)
    头 = f"## 项目事实（场景：{词[:50] or '未说明'}）\n"
    尾 = ""
    if 截:
        # ★ 截断必须**明确告诉 AI 还能问什么** —— 否则它会以为"这就是全部"，
        #   拿不完整的事实下结论，比不查更坏。
        尾 = ("\n\n---\n（上面按关联度截断过，**不是全部**。"
              "要继续看某一块，用 `要什么` 单项再问一次。）")
    return {"正文": 头 + 正 + 尾 if 正 else "", "段们": len(段), "来源": 来源,
            "截断了吗": 截, "段内截过": 段内已截, "上限": 上限, "关键词": 抽}


def 简述() -> str:
    """一行说明各段现在有没有内容 —— 给 doctor 用（不占上下文）。"""
    体 = 看("__体检__", 上限=600)
    return (f"{体['段们']} 段有内容 · 来源 {','.join(体['来源']) or '无'}"
            f" · 抽样 {len(体['正文'])} 字")
