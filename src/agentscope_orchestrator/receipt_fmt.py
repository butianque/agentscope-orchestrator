"""回执格式机判 —— 让**回执本身**成为可判的东西。

## 这个模块治的病

在此之前，本仓的回执是**自由文本**：想写什么写什么。
实测吃过两次亏（都在 `linkage` 那一轮）：

1. 回执里执行项编号写得不规范 ⇒ `LINK-03` 认不出 ⇒ 报"锚缺失"，
   **判据接不上，整条互锁白做**；
2. 更根本的：**没有任何判据能说"这份回执够不够格"**。
   回执写得再含糊（"我确认已修好"），也照样能提交。

⇒ 有了固定格式，回执就能被**机判**：缺哪一节、证据链编号对不对、
推导链有没有断、有没有用禁句式 —— 全都能红。

## 机制来源（写在这里而不是源码里：源码不许出现专有名词）

外部契约定义的五种模板、五类证据链、推导链格式、六部分返回结构、
禁止句式黑名单 —— 具体规格见 `ORCH_RECEIPT_TPL` 指向的文档。
★ 本模块**不硬编码任何项目路径**：模板文档位置由环境变量给。

## 最要紧的一条判据：**证据链编号要与证据类型匹配**

这是最容易被忽略、也最容易骗过审查的一条：

```
类型2（完整覆盖写入）必须给 EV-01~EV-07
类型3（增量替换）    必须给 EV-01 + EV-08~EV-11
类型4（追加）        必须给 EV-01~EV-03
```

写"我给了 4 条证据"是**看不出对错**的 —— 给的是类型1 的那 4 条，
却声称做的是类型2 的改动，**条数一样，意思完全不同**。
⇒ 判据必须比**编号集合**，不是比条数。
"""
from __future__ import annotations

import os
import re
from pathlib import Path

# ══════════════════════════════════════════════════════════════════════════
# 五种模板
# ══════════════════════════════════════════════════════════════════════════
# ★ 为什么"模板种类"本身要机判：不同模板的**必填项不同**。
#   不认种类就无从判必填项 —— 拿 T1 的必填项去要求一份 T4（断点恢复），
#   会把合法的东西判红（误伤），反之会漏判。
种类们 = ("T1", "T2", "T3", "T4", "T5")

种类信息 = {
    "T1": {"名": "正式推进", "用于": "切片激活后的常规任务"},
    "T2": {"名": "驳回修正", "用于": "审批不通过，附属于 T1 的执行项"},
    "T3": {"名": "冷启动", "用于": "新项目或快照严重损坏"},
    "T4": {"名": "断点恢复", "用于": "上下文丢失后恢复"},
    "T5": {"名": "状态变更", "用于": "项目切换 / 文档体系版本变更"},
}

# 每种模板的必填项。**键是给人看的中文名，值是在文中认它的正则。**
#
# ★ 口径：正则要"宽进"（多种写法都认），因为文档是人写的；
#   但**必填项本身不许降级**（认不出就报缺，不猜）。
#
# ★ 第一版漏了"字段式写法"，判据抓出来了：`执行项：1` 认不出，
#   只认行首的 `1. xxx`。而回执里**字段式写法更常见**（尤其模板骨架生成的）。
#   ⇒ 每条必填项都要同时覆盖"行首式"与"字段式"两种写法。
必填 = {
    "T1": {
        # ★ `轮次编号` 这个词里"轮次"后面还有"编号"两个字，第一版正则写成
        #   `(?:轮次|批次|批号)\s*[:：]` —— 匹配完"轮次"就直接要求冒号，
        #   于是**真回执里的 `轮次编号：ORCH-214` 一律认不出** ⇒ 报"缺必填项"。
        #   判据逼出来的（② 段连红三次）。⇒ 口径：**必填项的正则要覆盖那个词的完整写法**，
        #   不是"开头像就算"。
        "轮次编号": r"(?:轮次|批次|批号)(?:编号|号|批次号)?\s*\**\s*[:：]\s*\S+",
        "执行项": r"(?:^\s*(?:\d+[.、)]|执行项\s*\d+)|执行项\s*\**\s*[:：])",
        "证据链": r"EV-(?:SS-)?\d+",
        "审计依据": r"审计依据",
    },
    "T2": {
        # ★★ 三条的"别名"必须**互不覆盖**（判据逼出来的，第三轮才修对）：
        #   第一版 `驳回对象` 的正则里有裸的 `驳回`、`驳回理由` 里有裸的 `理由` ——
        #   于是 `驳回理由：依据不足` 这一行**同时满足两条** ⇒
        #   抹掉 `驳回对象` 时，`驳回理由` 那行仍然满足它 ⇒ **红不出来**。
        #   ⇒ 口径：一条必填项的判据，**不许被另一条的合法写法满足**。
        #     做法：一律用**带项名的显式写法**（`驳回对象：…`），别用裸词当"同义词"。
        #     裸词看着"宽进"，实际让判据互相串味，比窄更坏。
        "驳回对象": r"驳回对象\s*\**\s*[:：]\s*\S+",
        "驳回理由": r"驳回理由\s*\**\s*[:：]\s*\S+",
        "修正要求": r"修正要求\s*\**\s*[:：]\s*\S+",
    },
    "T3": {
        "冷启动步骤": r"(?:冷启动)?步骤\s*\**\s*[:：]?\s*\d+",
        "快照状态": r"快照\s*\**\s*[:：]\s*\S+",
    },
    "T4": {
        # ★ 同理：`已通过校验` 的正则原来含裸的 `校验`，而 `断点位置：执行项 3`
        #   之类不含"校验"、本该独立 —— 但 T4 的另一条值里有"校验"⇒ 互相满足。
        "断点位置": r"断点位置\s*\**\s*[:：]\s*\S+",
        "已通过校验": r"已通过校验\s*\**\s*[:：]\s*\S+",
    },
    "T5": {
        "变更对象": r"变更对象\s*\**\s*[:：]\s*\S+",
        "变更前后": r"(?:变更前后|变更前)\s*\**\s*[:：]\s*\S+",
    },
}

# ══════════════════════════════════════════════════════════════════════════
# 五类证据链（表格逐字来自外部契约）
# ══════════════════════════════════════════════════════════════════════════
# ★★ 这一张表是**判据的核心**：它把"条数"升级成"编号集合"。
#   只数条数（"有 4 条证据"）骗得过人，骗不过集合比较。
证据类型 = {
    1: {"名": "创建新文件", "要": ("EV-01", "EV-02", "EV-03", "EV-04"),
        "识别": r"(?:创建|新建|新增).{0,12}文件"},
    2: {"名": "完整覆盖写入", "要": ("EV-01", "EV-02", "EV-03", "EV-04",
                                "EV-05", "EV-06", "EV-07"),
        "识别": r"(?:完整覆盖|全文覆盖|整体覆盖|覆盖写入)"},
    3: {"名": "增量替换", "要": ("EV-01", "EV-08", "EV-09", "EV-10", "EV-11"),
        "识别": r"(?:增量替换|替换编辑|增量编辑)"},
    4: {"名": "文件追加", "要": ("EV-01", "EV-02", "EV-03"),
        "识别": r"(?:追加|append|扩充末尾)"},
    5: {"名": "命令执行", "要": ("EV-SS-01", "EV-SS-02", "EV-SS-03", "EV-SS-04"),
        "识别": r"(?:命令|command).{0,8}(?:执行|检索|扫描)"},
}

# ══════════════════════════════════════════════════════════════════════════
# 禁止句式黑名单（逐条来自外部契约）
# ══════════════════════════════════════════════════════════════════════════
# ★ 为什么这些句式必须红，而不是"建议改"：
#   它们每一类都对应一个**具体的失效方式**：
#   · 第一人称认知 ⇒ 把"事实"换成"我的判断"，后面无法复核；
#   · 模糊词       ⇒ 结论不可判真假（"应该是好的"到底是不是？）；
#   · 非法引用     ⇒ 用训练先验冒充项目依据（**这正是本仓最要治的病**）；
#   · 内部认知     ⇒ 引用一段谁都无法锚定的"之前"；
#   · 间接指令     ⇒ 把责任转给人类，链条断在这里；
#   · 凭记忆返回   ⇒ 用记忆替代检索（记忆会变，检索结果不会）。
禁句式 = {
    "第一人称认知": r"(?:我(?:判定|确认|推导|审查|认为|决定))",
    # ★ 模糊词：第一版写了 `(?!...是|为|会)` 的负向前瞻，想把"应该是/可能是"这类
    #   **正当用法**排除掉。结果把判据自己该抓的"大概是好的"也排除了（因为后面跟"是"）。
    #   ⇒ 口径：**别用负向前瞻去猜"哪些是正当用法"** —— 那是不可判的。
    #     模糊词的危害是"结论不可判真假"，`大概是好的` 恰恰就是这种。
    #     宁可抓宽（人真需要写"估计"时改成明确说法），也别漏（漏了等于这条判据不存在）。
    "模糊词": r"(?:可能|推测|大概|估计|似乎)",
    "非法引用": r"(?:契约§|交互契约|根据常识|按常规|通常做法|设计模式|最佳实践|业界标准|一般来说|普遍认为)",
    "内部认知": r"(?:基于我(?:之前|上次)|我上次|我之前|之前确认的|上一轮通过的)",
    "间接指令": r"(?:请人类|转告|口头|转达)",
    "凭记忆返回": r"(?:凭记忆|根据我对文档体系的理解|根据训练数据)",
}

# ══════════════════════════════════════════════════════════════════════════
# 推导链与六部分结构
# ══════════════════════════════════════════════════════════════════════════
_推导行 = re.compile(r"^(S\d+)\s*[·.]\s*(.+?)\s*\|\s*依据\s*[:：]\s*(.+?)\s*\|\s*等级\s*[:：]\s*(L\d)",
                     re.MULTILINE)
_等级合法 = {"L0", "L1", "L2", "L3", "L4", "L5"}
_节 = re.compile(r"^##\s*(.+?)\s*$", re.MULTILINE)
六部分 = ("原文引用", "执行证据链", "审计依据", "本地AI分析",
         "待AI指挥官裁定事项", "对AI指挥官约束要求")


def 模板(种类: str) -> str:
    """返回该种模板的骨架（带必填占位）。"""
    种类 = (种类 or "").strip().upper()
    if 种类 not in 种类信息:
        return ""
    信 = 种类信息[种类]
    段 = [f"# {种类}·{信['名']}",
          f"（用于：{信['用于']}）", ""]
    for 名 in 必填.get(种类, {}):
        段.append(f"{名}：{{{{{名}}}}}*")
    段 += ["", "## 原文引用", "（逐字摘抄，注明来源与等级）", "",
           "## 执行证据链", "（按证据类型给编号，不要只写【通过】）", "",
           "## 审计依据", "（条款全文 + 执行数据 + 对照关系）", "",
           "## 本地AI分析", "（推导链每步含依据与等级）", "",
           "## 待AI指挥官裁定事项", "（仅客观事实）", "",
           "## 对AI指挥官约束要求", "（下轮必填字段清单）"]
    return "\n".join(段)


def 必填项(种类: str) -> list[str]:
    种类 = (种类 or "").strip().upper()
    return list(必填.get(种类, {}))


def 认模板(文: str) -> list[str]:
    """认这份回执属于哪种模板。**认不出返回空表 —— 不猜。**

    ★★ 第一版写成"文里出现模板名就算"（`\bT1\b` 或 名字出现），判据当场抓出误判：
      一份 T5 的回执里写了"驳回"两个字，就被认成 **T1 + T2**；
      更糟的是**必填项按错的模板查** ⇒ 报出"T1 缺必填项：轮次编号、执行项"
      —— **拿 T1 的要求去判一份 T5 的东西**，报的问题全是假的。

    ⇒ 口径：模板种类**只在"声明处"认**，不在全文认。
      声明处 = 标题行（`# Tx`）或"模板：Tx"这类显式字段。
      ★ 这一条与整仓的其它判据是同一个道理：**判据接上了，但接错了对象**，
        而且错得安静 —— 它不报错，只报一串**看似合理**的假问题。
    """
    出 = []
    for k in 种类们:
        # ① 标题行里显式声明：`# T1·正式推进` / `# T1 正式推进`
        if re.search(rf"^#{{1,3}}\s*{k}\b", 文, re.MULTILINE):
            出.append(k)
            continue
        # ② 显式字段：`模板：T1` / `**模板**：T1`
        if re.search(rf"模板\**\s*[:：]\s*{k}\b", 文):
            出.append(k)
    return 出


# ══════════════════════════════════════════════════════════════════════════
# 解析
# ══════════════════════════════════════════════════════════════════════════
def 解析(文: str) -> dict:
    """从回执里抽出机判需要的结构。**认不出的一律空着，不猜。**"""
    文 = 文 or ""
    ev = sorted(set(re.findall(r"EV-SS-\d+|EV-\d+", 文)),
                key=lambda x: (x.startswith("EV-SS"), x))
    链 = [{"步": m.group(1), "描述": m.group(2), "依据": m.group(3),
           "等级": m.group(4)} for m in _推导行.finditer(文)]
    节 = [m.group(1).strip() for m in _节.finditer(文)]
    # ★ 执行项：**必须与 `必填["T1"]["执行项"]` 用同一套写法**。
    #   第一版这里单独写了一遍"行首式"正则，而 `必填` 那边改宽了忘了这边 ⇒
    #   判据报"执行项抽不出来（[]）"。
    #   ★ 这是本仓反复出现的**同一个病**：改一处要**把同类位置全找一遍**。
    #     所以这里直接**引用** `必填` 里的模式，而不是再抄一遍 ——
    #     抄一遍就有第二次改漏的机会。
    _执行项_pat = 必填["T1"]["执行项"]
    执行项: list[int] = []
    for m in re.finditer(r"(?:^|\n)\s*(?:(\d+)[.、)]\s|(?:执行项|项)\s*\**\s*[:：]\s*(\d+))",
                         文, re.MULTILINE):
        v = m.group(1) or m.group(2)
        if v:
            执行项.append(int(v))
    if not 执行项:
        # 兜底：骨架式 `执行项1` / `执行项 1`
        执行项 = [int(x) for x in re.findall(r"执行项\s*(\d+)", 文)]
    执行项 = sorted(set(执行项))
    # 认证据类型：文里出现"完整覆盖写入"这类词 ⇒ 就是那一类
    类 = []
    for n, 规 in 证据类型.items():
        if re.search(规["识别"], 文):
            类.append(n)
    return {"模板候选": 认模板(文), "证据链": ev, "推导链": 链, "节": 节,
            "执行项": 执行项, "证据类型": 类, "字数": len(文)}


# ══════════════════════════════════════════════════════════════════════════
# 校验（判据本体）
# ══════════════════════════════════════════════════════════════════════════
def 校验(文: str) -> tuple[bool, list[str]]:
    """返回 `(够不够格, 问题列表)`。**空文/乱码也要返回，不许抛。**"""
    问: list[str] = []
    try:
        文 = 文 or ""
        if not 文.strip():
            return False, ["回执是空的 ⇒ 够格无从谈起"]
        体 = 解析(文)

        # ① 模板
        if not 体["模板候选"]:
            问.append("认不出是哪种模板（T1~T5）⇒ 判据无从下手 —— "
                      "请在回执标题里写明")
        elif len(体["模板候选"]) > 1:
            # 不算错（T2 本来就附属于 T1），但要说清
            pass

        # ② 必填项（对每种认出的模板查）
        for k in 体["模板候选"]:
            缺 = [名 for 名, pat in 必填.get(k, {}).items()
                  if not re.search(pat, 文, re.MULTILINE)]
            if 缺:
                问.append(f"{k} 缺必填项：{'、'.join(缺)}")

        # ③ ★ 证据链编号要与类型匹配（比集合，不比条数）
        有 = set(体["证据链"])
        if 体["证据类型"]:
            for n in 体["证据类型"]:
                要 = set(证据类型[n]["要"])
                # 认出的类型里，只要有一个的编号集合被完全满足就算过；
                # 全都不满足才算错（一份回执可能同时做了几类操作）
                if not 要.issubset(有):
                    缺 = sorted(要 - 有, key=lambda x: (x.startswith("EV-SS"), x))
                    名 = 证据类型[n]["名"]
                    问.append(f"证据链与类型不匹配：声明做了「{名}」"
                              f"（需 {'、'.join(证据类型[n]['要'])}），"
                              f"但回执里缺 {('、'.join(缺))}")
        elif "证据" in 文 and not 有:
            问.append("提到了证据但**一个 EV 编号都没有** ⇒ 无法核对"
                      "（只写「通过/不通过」不算证据）")

        # ④ 推导链
        if 体["推导链"]:
            坏级 = [x["步"] for x in 体["推导链"] if x["等级"] not in _等级合法]
            if 坏级:
                问.append(f"推导链等级不合法（{('、'.join(坏级))}）"
                          f"⇒ 合法集合 {'/'.join(sorted(_等级合法))}")
            序 = [int(x["步"][1:]) for x in 体["推导链"]]
            if 序 != list(range(min(序), min(序) + len(序))):
                问.append(f"推导链**跳步**（{'、'.join(x['步'] for x in 体['推导链'])}）"
                          f"⇒ 缺中间步时推导是断的")
            空依 = [x["步"] for x in 体["推导链"] if not x["依据"].strip()]
            if 空依:
                问.append(f"推导链缺「依据」（{('、'.join(空依))}）")

        # ⑤ 禁止句式黑名单
        for 类, pat in 禁句式.items():
            m = re.search(pat, 文)
            if m:
                问.append(f"用了禁止句式〔{类}〕：`{m.group(0)}`"
                          f"（位置 {m.start()}）")

        # ⑥ 六部分结构（只在明确声明是标准返回时才要求）
        if any(s in 文 for s in ("原文引用", "执行证据链", "审计依据")):
            缺节 = [s for s in 六部分 if s not in 体["节"]]
            if 缺节:
                问.append(f"六部分返回结构缺节：{'、'.join(缺节)}")
    except Exception as e:                       # noqa: BLE001 校验自己崩了也算不够格
        return False, [f"校验过程崩了（{type(e).__name__}: {e}）⇒ 不许当通过"]
    return (not 问), 问


def 生成(种类: str, 字段: dict | None = None) -> str:
    """按模板渲染一份回执骨架，`字段` 里的值填进占位。"""
    文 = 模板(种类)
    if not 文:
        return ""
    for k, v in (字段 or {}).items():
        文 = re.sub(rf"\{{\{{{re.escape(str(k))}\}}\}}\*?", str(v), 文)
    return 文


