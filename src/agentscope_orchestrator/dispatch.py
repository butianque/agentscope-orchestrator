"""分工线 —— **机器做机器能判的，LLM 做需要项目知识的**，两者在同一个循环里互补。

## 这个模块回答的那个问题

用户的原话是：*"能机器无措处理的问题教回给机器，需要 LLM 知识执行的东西给到 LLM 执行，
机器机械做不到的事情给 LLM 做。"*

**分界点不是"难不难"，而是"有没有机器判据"**：

| 处境 | 谁做 | 行为 |
|:--|:--|:--|
| **有判据** | **机器** | 直接判、直接拒。LLM 参与只会引入不确定性 |
| **没判据，但知识库里有** | **机器照着做** | 人写的外挂知识**优先于**模型训练先验；不需要模型"想" |
| **没判据，也没知识，但是已知盲区** | **LLM + 台账** | 告诉它上次栽过，附上次的候选判据；**不重复造轮子** |
| **以上都不是** | **LLM** | 真需要项目知识的地方；答完**必须留判定依据** |
| **判据缺失本身** | **机器记账** | 记进盲区台账 —— **盲区不是失败，是资产** |

**最后一行是这套设计的关键**：它让"门判不了的东西"有地方沉淀，
于是"一边错一边加门"从口号变成机制。

## 为什么不能"全都交给 LLM"

本项目已经吃过这个亏，而且有实测：
- **知识库空转**：接在 fixloop 上、`注入()` 却永远返回空串 ——
  模型看着像"有知识可用"，其实每次拿到的都是空的；
- **注入不看相关度**：算好了关键词却没用，注入的是"按类别排好的固定 700 字前缀"，
  与当前这道题**毫无关系**。

⇒ 一条铁律：**能用判据判的，绝不交给 LLM**；能用知识库答的，绝不劳烦 LLM。
  LLM 只出现在**真的没有别的东西能答**的地方，而且它的输出**必须落成可查的东西**。
"""
from __future__ import annotations

import os
import time
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class 裁定:
    """分工线对"这一步该谁做"的裁定。"""
    该谁: str                      # 机器 / 知识 / 台账 / LLM
    为什么: str
    依据: str = ""                 # 命中的知识/台账原文（给 LLM 看的）
    要求留依据: bool = False       # 交给 LLM 时**必须**要求它留判定依据
    记盲区: bool = False           # 这一步结束后要不要记盲区
    来源: list[str] = field(default_factory=list)

    def 摘要(self) -> str:
        return f"[{self.该谁}] {self.为什么}"


def 裁(*, 命令=None, 证据: str = "", 判据已命中: bool = False,
       判据说明: str = "", 项目根=None) -> 裁定:
    """核心裁定：这一步该机器判、该查知识、该查台账，还是该交 LLM。

    调用顺序**有讲究**（这是"分工"二字的全部含义）：

    ```
    ① 有判据吗？           有 ⇒ 机器判，到此为止（不问 LLM）
    ② 知识库命中吗？       命中 ⇒ 照着做（不问 LLM）
    ③ 是已知盲区吗？       是   ⇒ 交 LLM，但**附上次的候选判据**，并要求留依据
    ④ 都不是              ⇒ 交 LLM，要求留依据；**这一步是盲区的来源**
    ```

    ★ ①为什么排最前：判据是**确定的**。让 LLM 在"有确定答案"的地方发挥，
      是把确定性换成不确定性 —— 这是纯亏。
    ★ ②③顺序不可换：知识是**人的裁定**（优先），台账是**还没裁定的经验**。
      先查人的裁定；人的没写，才看经验。
    """
    来源: list[str] = []
    键 = " ".join(str(x) for x in (命令 or [])) + " " + (证据 or "")
    未中: list[str] = []          # 前几档为什么没答 —— 必须带给 LLM

    # ① 判据
    if 判据已命中:
        return 裁定(该谁="机器", 为什么=f"判据已命中：{判据说明 or '（未说明）'}"
                    " ⇒ 直接判，不劳烦 LLM（有确定答案的地方不留不确定性）",
                    来源=["判据"])
    未中.append("没有能判它的判据")

    # ② 知识库（人写的口径，**优先于**模型先验）
    #
    # ★★ 这里必须用 `命中()` 而不是"`注入()` 非空"（2026-11-03 判据当场判红 6 项逼出来的）：
    #   `注入` 的口径是**宁滥勿缺**（命中 2 个词元就塞进来），拿它的非空当"有答案"，
    #   分工线会把**任何**问题都判成"知识库命中" ⇒ **第二档吞掉全部** ⇒
    #   "交给 LLM"那一档永远走不到 ⇒ **盲区永远记不下来** ⇒
    #   "一边错一边加门"这条链**在第一步就断了**。
    #   ⇒ 断言"有答案"要用更严的判据（分≥0.35 且 词元≥3），见 project_kb.命中。
    知识说明 = ""
    try:
        from . import project_kb as _KB
        够, 知识说明, _详 = _KB.命中(键[-1500:])
        if 够:
            块 = _KB.注入(关键词=键[-1500:], 上限字=700)
            来源.append("知识库")
            return 裁定(该谁="知识",
                        为什么=f"项目知识库命中 ⇒ 照它做（人的裁定优先于模型先验）。{知识说明}",
                        依据=块, 来源=来源)
    except Exception as e:                        # noqa: BLE001 知识库坏了不阻断分工
        知识说明 = f"知识库读不了（{type(e).__name__}）"
    未中.append(f"知识库里没有够格的答案（{知识说明 or '未命中'}）")

    # ③ 盲区台账（还没变成判据的经验）
    台说明 = ""
    try:
        from . import blind_spot as _BS
        块 = _BS.提示(键[-300:], 上限字=500)
        # ★ 2026-11-03 补：**「已加门但没验」的盲区要单独提醒**。
        #   理由：`已加门` 这个状态本身说明不了任何事 ——
        #   只有 `验证=拦得住` 才说明这类问题真有机器判据了。
        #   不提醒的话，台账上会积一堆"看起来处理过了"但其实没人验过的条目，
        #   而那正是**自欺最容易藏身的地方**。
        没验 = _BS.没验门的()
        if 没验 and not 块.strip():
            块 = ("（台账里有 **%d** 条标着「已加门」但**没验过拦不拦得住** —— "
                 "`已加门` 本身说明不了任何事，只有验过才算。）" % len(没验))
        if 块.strip():
            来源.append("盲区台账")
            return 裁定(该谁="台账",
                        为什么="这是**已知盲区**（门盖不到、以前栽过）⇒ 交 LLM，"
                               "但附上次的候选判据，别重犯同样的思路。"
                               f"（{未中[0]}；{未中[1]}）",
                        依据=块, 要求留依据=True, 记盲区=True, 来源=来源)
        台说明 = "台账里没记过这一类"
    except Exception as e:                        # noqa: BLE001
        台说明 = f"台账读不了（{type(e).__name__}）"
    未中.append(台说明)

    # ④ 真盲区：交给 LLM，而且**这次要留下痕迹**
    #
    # ★★ 必须把"前面几档为什么没答"一起带给 LLM（2026-11-03 判据判红逼出来的）：
    #   第一版的 `依据` 是空的 —— 交 LLM 时**空手交**，于是模型看不到
    #   "判据没有、知识库没有、台账没有"这个事实，它会**倾向于用通用做法**补上，
    #   而那正是本项目要治的病（用训练先验替代项目判定基准）。
    #   ⇒ 分工线的每一档都要**交代清楚自己为什么没答**，这是"分工"的另一半。
    #
    # ★★★ 2026-11-03 补：交 LLM 时**一律附一块「语义关联事实」**（不只在知识档附）。
    #
    #   为什么：前三档"没答"**不等于"这项目没有相关事实"** ——
    #     ②档问的是"知识库里有没有够格的答案"（窄），而 `context_view` 给的是
    #     "跟这件事有关联的全部事实"（宽，含历史坐标、四方联动、机器步数）。
    #   真事故（同日）：`KB.命中()` 只返回 42 字的统计串"命中 1 条够格…"，
    #     我把它当"材料"塞进提示 ⇒ AI 看到"知识库里有答案"却**看不到答案本身**。
    #     ⇒ 现在改成**从 `查()` 取正文**，并把三档的结论与关联事实**一次给全**。
    #
    #   这一条是「语义与关联为主、压低上下文压力」的落点：
    #     **一次调用拿到关联好的一块**，而不是让模型自己查五次。
    关联 = ""
    try:
        from . import context_view as _CV
        关联 = (_CV.看(键[-200:], 上限=1200).get("正文") or "").strip()
        if 关联:
            来源.append("语义关联")
    except Exception:                             # noqa: BLE001 关联不到不影响分工结论
        关联 = ""
    return 裁定(该谁="LLM",
                为什么="既没有判据、知识库也没写、台账里也没记过 ⇒ 这是**新盲区**，"
                       "只能交给 LLM；它答完必须留判定依据，"
                       "**这一步产出的就是「下次该加什么门」的原料**",
                依据="## 这一步为什么落到你这里（前面几档都没答）\n"
                     + "\n".join(f"- {x}" for x in 未中)
                     + "\n⇒ 所以**不要**用通用做法/最佳实践补，"
                       "要说清你是按哪条项目事实下的结论。"
                     + (f"\n\n{关联}" if 关联 else ""),
                要求留依据=True, 记盲区=True, 来源=来源)


def 记这次(*, 证据: str, 上下文: str = "", 候选判据: str = "", 来源: str = "") -> dict:
    """把一次"无判据"的经历记进盲区台账（**分工线的产出落在台账上**）。"""
    from . import blind_spot as _BS
    return _BS.记(证据, 上下文=上下文, 候选判据=候选判据, 来源=来源, 证据=证据)


def 给LLM的交代(裁: 裁定) -> str:
    """把裁定转成给 LLM 的**交代文本**（放在提示里，把"为什么找它"说清楚）。

    ★ 为什么要说清"为什么找你"：模型不知道自己是第几顺位。
      不告诉它"前面三道都没有答案"，它会**倾向于用通用做法**补上 ——
      那正是本项目要治的病（用训练先验替代项目判定基准）。
      告诉它"这是新盲区、没有现成判据"，它会**倾向于说明依据而不是直接给答案**。
    """
    段 = [f"## 这一步的定位：{裁.为什么}"]
    if 裁.依据:
        段.append("")
        段.append(裁.依据)
    if 裁.要求留依据:
        段.append("")
        段.append("★ **答完必须写清判定依据**：你是按哪条项目事实、哪份文档的哪一段下的结论。"
                  "写不出依据的结论会被当成「猜」—— 本项目已有实测："
                  "「猜的被记成知道的」比「不知道」更坏。")
    return "\n".join(段)


def 统计() -> dict:
    """分工线的健康度：多少落在机器/知识/台账上，多少真落在了 LLM 上。

    ★ 为什么值得看这个数：**LLM 占比越高，说明项目判定基准越薄**。
      这不是模型能力问题，是"门和知识还没攒够"。这个数上升或下降，
      比"这轮修好了几个 bug"更能说明长线进展。
    """
    出: dict = {"知识条数": 0, "盲区条数": 0, "该加门": 0}
    try:
        from . import project_kb as _KB
        出["知识条数"] = (_KB.统计() or {}).get("条数", 0)
    except Exception:                             # noqa: BLE001
        pass
    try:
        from . import blind_spot as _BS
        体 = _BS.统计()
        出["盲区条数"] = 体.get("条数", 0)
        出["该加门"] = 体.get("该加门", 0)
        出["按状态"] = 体.get("按状态", {})
    except Exception:                             # noqa: BLE001
        pass
    return 出
