def _在引号里(文本: str, 起: int, 止: int) -> bool:
    """命中的那段话是不是**在引用里**（`「…」` 或 `“…”` 包着）。

    ★ R300b（真读数，第一次拿口径门检查**我自己写的回答**就中）：
      我在回答里**引用**了那条推卸型结论来解释它（「结构本能是库存，得先让它在
      自主认知里进生产」），口径门**把它当成我又说了一遍** ⇒ 拦下。

      ⇒ 这是**假红**，而且方向很危险：**一个不允许引用错误的门，
        会让人无法讨论错误** —— 那样红就只会被藏起来，不会被改掉。

      ⇒ 口径：**引用不算主张。** 命中整段落在引号内 ⇒ 放行。
        反过来说：**去掉引号，就是主张。** 这条界线是可判的。
    """
    左 = 文本.rfind("「", 0, 起)
    if 左 >= 0 and 文本.find("」", 左) >= 止:
        # 「 与 」之间没有先闭合
        if 文本.find("」", 左, 起) < 0:
            return True
    左2 = 文本.rfind("“", 0, 起)
    if 左2 >= 0 and 文本.find("”", 左2) >= 止:
        if 文本.find("”", 左2, 起) < 0:
            return True
    return False


def 查(文本: str) -> dict:
    """按口径表查一段文本，返回**命中的口径**（不改文本、不判对错）。

    ★ 用法：模型在给结论/写回执/提交说明**之前**必须调它。
      口径：「需要调用方记得做的步骤，等于没做」⇒ 所以本函数必须被接线，
      不能只靠自觉（见模块 docstring 的诚实边界）。
    """
    命中: list[dict] = []
    for 条 in 规矩:
        for 式 in 条["红线"]:
            try:
                找 = re.search(式, 文本, re.M)
            except re.error as e:                     # noqa: BLE001
                命中.append({"id": 条["id"], "错": f"红线正则本身坏了：{e}"})
                continue
            if not 找:
                continue
            if _在引号里(文本, 找.start(), 找.end()):
                continue                              # 引用不算主张
            命中.append({
                "id": 条["id"],
                "规矩": 条["规矩"],
                "依据": 条["依据"],
                "命中": 找.group(0),
                "位置": 找.start(),
            })
            break
    return {
        "ok": not 命中,
        "命中数": len(命中),
        "命中": 命中,
        "查了": len(规矩),
        "口径": "**没命中 ≠ 结论正确** —— 这只是「没踩已登记的红线」。",
    }


def 必须过(文本: str) -> None:
    """硬门：命中任何口径就抛异常。给产出路径用（回执出口、结论出口）。"""
    果 = 查(文本)
    if not 果["ok"]:
        x = 果["命中"][0]
        raise ValueError(
            f"口径门拦下（{x['id']}）：{x['规矩']}\n"
            f"  命中：「{x['命中']}」\n"
            f"  依据：{x['依据']}")


def 自检() -> dict:
    """**逐条验证每条口径自己是不是装饰。**

    ★ 这是本模块存在的意义：一条报不出红的红线，等于没有。
      每条口径必须：
        · 拦下自己的**正样本**（我真实说过的错话）；
        · **放行**自己的负样本（对的话）。
      任何一条做不到 ⇒ 报出来。
    """
    坏: list[str] = []
    for 条 in 规矩:
        正 = 查(条["正样本"])
        if 正["ok"]:
            坏.append(f"{条['id']} 是**装饰**：拦不下自己的正样本 " f"「{条['正样本'][:40]}」")
        负 = 查(条["负样本"])
        if not 负["ok"]:
            坏.append(f"{条['id']} **误报**：把正确的话拦了 "
                     f"「{条['负样本'][:40]}」（命中 {[h['id'] for h in 负['命中']]}）")
    # ★ 引用必须放行：一个不允许引用错误的门，会让人无法讨论错误 ——
    #   那样红只会被藏起来，不会被改掉。（R300b，拿门检查我自己的回答时中的）
    _引用样本 = "我在章程里写过「得先让它在自主认知里进生产」，那是推卸，已改正。"
    if not 查(_引用样本)["ok"]:
        坏.append("**引用误报**：把「引用一条错话来讨论它」当成说了错话 ⇒ "
                 "这会让错误只能被藏、不能被讨论")

    # ★ 提到规矩必须放行（第三次自抓）：我在回答里**列举**「不许猜数据形状」，
    #   口径门把**规矩名本身**当成违规。与前两次同一类：**提到 ≠ 主张。**
    for _提到样本 in ("红线：不许猜数据形状 / 不许拿调用方和被调用方互比 / 结论必须带真读数。",
                     "本轮的七条口径含：不许猜数据的形状。"):
        if not 查(_提到样本)["ok"]:
            坏.append("**提到误报**：把「列举一条规矩的名字」当成违反它 ⇒ "
                     "那样连自己的规矩都不能写进文档")
            break

    return {
        "ok": not 坏,
        "口径数": len(规矩),
        "坏": 坏,
        "结论": (f"口径门自检：{len(规矩)} 条，"
                + ("全绿（每条都真能报红、不误报、允许引用、允许提到）" if not 坏
                   else f"红 {len(坏)}")),
    }
