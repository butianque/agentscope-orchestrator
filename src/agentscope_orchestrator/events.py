"""事件驱动增量 —— 把「定时全量扫」换成「变更即触发、只算变的那部分」。

## 这个模块治的病（**不是"再加一层调度器"**）

本项目的检查一直是**一把梭全量跑**：套件 44 个脚本、几千条断言，
每 5 分钟或每次提交都从头跑一遍。后果有两个，而且都会**掩盖真问题**：

1. **慢到没人愿意频繁跑** ⇒ 检查从"随时"退化成"交付前" ⇒
   中间发生的破坏**没人知道**（而长线工程上，破坏几乎都发生在中间）；
2. **全量跑出来的红，看不出"是哪次改动引起的"** ⇒
   只能知道"现在红了"，不知道"从哪一步开始红的"。

⇒ 换成**事件驱动**：文件变了 / 命令跑完了 / 状态翻了 / 链断了 ⇒
  **当场只算受影响的那部分**，并把这一步落成一个检查点。
  定时全量扫退居**兜底**（防"事件漏了"这种没法彻底排除的事）。

## 三条机制，各自的出处（写在这里而不是源码里：源码不许出现专有名词）

| 机制 | 名字 | 内容 |
|:--|:--|:--|
| 事件触发 | TRIG-01~04 | 文件变更/命令完成/状态转移/链断裂 ⇒ **立即**触发增量，不等定时器 |
| 增量范围 | SCHED-02 | 一部分检查可增量（只算受影响项），一部分**必须全量**（改了地基就得全查） |
| 调度周期 | SCHED-03 | 周期 = **相生环 5 步**：每步增量，每 5 步一次全量 |
| 检查点 | PERSIST-01~03 | 每次检测落一个检查点；**增量只存变化量**；检查点**绑坐标链** |
| 告警 | SCHED-06 | 五级：FATAL/ERROR/WARN/INFO/DEBUG，各级去向不同 |

★ 本模块**只做增量与落账**，不判断"哪条判据该跑" ——
  那是各判据自己的事（这里收的是"项目键 → 值"这种可比较的状态）。

## 为什么"增量只存变化量"是对的（而不是省空间的小聪明）

全量存的话，"这一步发生了什么"就被淹没在几千条没变的状态里 ——
**读的人得自己 diff 两次快照才知道变了什么**。而"变了什么"恰恰是唯一有价值的信息：
它就是**因果链上的一环**。⇒ 增量存不是省空间，是**让变化本身成为数据**。
"""
from __future__ import annotations

import json
import os
import time
from pathlib import Path

# ══════════════════════════════════════════════════════════════════════════
# 事件类型
# ══════════════════════════════════════════════════════════════════════════
文件变更 = "文件变更"
命令完成 = "命令完成"
状态转移 = "状态转移"
链断裂 = "链断裂"
事件类型s = (文件变更, 命令完成, 状态转移, 链断裂)

# ══════════════════════════════════════════════════════════════════════════
# 增量策略（SCHED-02）
# ══════════════════════════════════════════════════════════════════════════
# ★ 口径：**哪些能增量，不是"快不快"决定的，是"改这一处会不会影响别处的判定"决定的。**
#
#   判据：如果一个检查的**输入集合**能被"受影响的项"完整刻画 ⇒ 可增量；
#        如果它的判定依赖"全局某个不变量"（比如坐标链连续、层级完备）⇒ **必须全量**。
#        因为这类量**任何一处改动都可能破坏它**，只查受影响项会漏。
#
#   ⇒ 这条表就是"能不能省"的判据。省错了比不省危险得多：
#     增量漏掉的那条红，会**静默地**留在那里（全量跑至少能撞见）。
策略 = {
    "运行时": {"可增量": True, "说明": "每条命令只影响它碰到的那些项 ⇒ 按受影响项算"},
    "功能": {"可增量": True, "说明": "新增一个入口只影响它自己那几个 ⇒ 按受影响项算"},
    "操作覆盖": {"可增量": False, "说明": "判定依赖全局覆盖面 ⇒ 一处变动就可能破坏它，必须全量"},
    "隔离": {"可增量": False, "说明": "判定依赖隔离层整体状态 ⇒ 必须全量"},
    "语义": {"可增量": False, "说明": "判定依赖文档之间的全局一致性 ⇒ 必须全量"},
}

# 事件 → 该触发哪一类检查（SCHED-02 的触发表）
触发表 = {
    文件变更: ("操作覆盖", "运行时"),
    命令完成: ("运行时",),
    状态转移: ("语义",),
    链断裂: ("隔离",),          # 链断了按最重的那档走：立即全量隔离检测
}


def _根() -> Path:
    # ★ R549：收口到唯一取法（原来自己拼 `~/.orchestrator-state`，
    #   与 `profile.STATE_ROOT` 可能是两个根 ⇒ home 不可写时会重演
    #   「写不了被显示成空链/0 条」。）
    from . import profile as _pf549
    return _pf549.state_dir()


def 检查点目录() -> Path:
    return _根() / "checkpoints"


def 检查点索引() -> Path:
    return 检查点目录() / "index.json"


# ══════════════════════════════════════════════════════════════════════════
# 触发：事件 ⇒ 该跑哪些检查、该增量还是全量
# ══════════════════════════════════════════════════════════════════════════
def 触发(种类: str, 引用: str = "", 载荷: dict | None = None) -> dict:
    """把一个事件翻译成"该跑什么、跑多少"。**纯函数，不落盘。**

    ★ 为什么这一步要和"落盘"分开：**它必须能被单独验**。
      混在一起写的话，验它就得先准备文件系统状态 —— 而"事件→检查"的映射
      恰恰是最容易写错、也最该被单测的部分（映射错了，后面全都白跑）。
    """
    种类 = (种类 or "").strip()
    if 种类 not in 事件类型s:
        return {"种类": 种类, "合法": False,
                "说明": f"不认识的事件类型（认识：{'、'.join(事件类型s)}）⇒ 不猜，"
                        f"按最重的处理：全量", "检查": [{"类": k, "全量": True,
                        "说明": v["说明"]} for k, v in 策略.items()]}
    要跑 = 触发表.get(种类, tuple(策略))
    检查 = []
    for 类名 in 要跑:
        规 = 策略.get(类名, {"可增量": False, "说明": "未登记 ⇒ 按全量处理（不省）"})
        检查.append({"类": 类名, "全量": not 规["可增量"], "说明": 规["说明"]})
    # ★ 相生环周期：到整周期就**追加一次全量**（兜底，防"事件漏了"）
    该全 = 该全量扫描吗()
    return {"种类": 种类, "合法": True, "引用": 引用, "载荷": 载荷 or {},
            "检查": 检查, "周期全量": 该全,
            "说明": ("本次到了完整相生环周期 ⇒ **追加一次全量兜底**（防事件漏报）"
                     if 该全 else "未到周期 ⇒ 只做增量")}


# ══════════════════════════════════════════════════════════════════════════
# 检查点：落账 + 增量只存变化量（PERSIST-01/02）
# ══════════════════════════════════════════════════════════════════════════
def _读索引() -> list[dict]:
    p = 检查点索引()
    if not p.is_file():
        return []
    try:
        v = json.loads(p.read_text(encoding="utf-8"))
        return v if isinstance(v, list) else []
    except Exception:                            # noqa: BLE001 索引坏了当没有
        return []


def _写索引(行s: list[dict]) -> None:
    p = 检查点索引()
    p.parent.mkdir(parents=True, exist_ok=True)
    # ★ 原子写：先写临时再替换。落账中断留下半个 json ⇒ 下次读的人以为"没有检查点"，
    #   而**那正是最该被发现的情况**（有一步没落账）。宁可留旧的，不留半截的。
    tmp = p.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(行s, ensure_ascii=False, indent=1), encoding="utf-8")
    tmp.replace(p)


def _最新全量() -> dict:
    """找最近一次**全量**检查点的状态（增量要靠它做基准）。"""
    for r in reversed(_读索引()):
        if r.get("全量"):
            p = Path(r.get("路径", ""))
            if p.is_file():
                try:
                    v = json.loads(p.read_text(encoding="utf-8"))
                    return v.get("状态", {}) or {}
                except Exception:                # noqa: BLE001
                    continue
    return {}


def 检查点(状态: dict, *, 全量: bool = False, 事件: str = "",
           引用: str = "") -> dict:
    """落一个检查点。**首次自动全量；之后只存变化量。**

    · `全量=True` ⇒ 存全部状态
    · 否则 ⇒ 与"最近一次全量基准 + 已应用的变化量"比，**只存变了的那些**

    ★ 为什么要跟"合并后的当前状态"比、而不是跟"上一次增量"比：
      上一次增量只含它自己变的项；不合并的话，"A 变了 → B 变回原值"这种
      来回变动会被判成两次变化（第二次其实是回到原状）。
    """
    基准 = _最新全量()
    if 全量 or not 基准:
        # 首次（或显式全量）：存全部
        增量 = {k: {"旧": None, "新": v} for k, v in sorted(状态.items())}
        真全量 = True
        基准快照 = dict(状态)
    else:
        # 当前真实状态 = 基准 + 已应用的增量
        当前 = dict(基准)
        for r in _读索引():
            if r.get("全量"):
                continue
            p = Path(r.get("路径", ""))
            if not p.is_file():
                continue
            try:
                d = json.loads(p.read_text(encoding="utf-8"))
            except Exception:                    # noqa: BLE001
                continue
            for k, v in (d.get("增量") or {}).items():
                当前[k] = v.get("新")
        增量 = {}
        for k, v in sorted(状态.items()):
            if k not in 当前 or 当前[k] != v:
                增量[k] = {"旧": 当前.get(k), "新": v}
        for k in 当前:
            if k not in 状态:
                增量[k] = {"旧": 当前[k], "新": None}     # 项被删了也是变化
        真全量 = False
        基准快照 = 基准

    now = time.strftime("%Y-%m-%dT%H:%M:%S")
    标 = time.strftime("%Y%m%d_%H%M%S") + "_" + str(abs(hash(json.dumps(增量, sort_keys=True,
                                                                 ensure_ascii=False))) % 100000)
    体 = {"检查点": 标, "时刻": now, "全量": 真全量, "事件": 事件, "引用": 引用,
          "增量": 增量, "基准": (None if 真全量 else 基准快照),
          "状态": (dict(状态) if 真全量 else None)}
    # ★ 坐标链绑定（PERSIST-03）：检查点本身也是一个**事件**，要挂进链。
    #   挂不上不拖垮落账 —— 但**明写在回执里**（`链` 字段为 None 就是没挂上）。
    体["链"] = None
    try:
        from . import coord_chain as _CC
        坐标 = _CC.追加("检查点", 标, now)
        if 坐标 is not None:
            体["链"] = 坐标.指纹 if hasattr(坐标, "指纹") else str(坐标)
    except Exception:                            # noqa: BLE001 链坏了不影响落账
        pass

    d = 检查点目录()
    d.mkdir(parents=True, exist_ok=True)
    路径 = d / f"cp_{标}.json"
    tmp = 路径.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(体, ensure_ascii=False, indent=1), encoding="utf-8")
    tmp.replace(路径)
    行s = _读索引()
    行s.append({"检查点": 标, "时刻": now, "全量": 真全量, "事件": 事件,
                "引用": 引用, "变化数": len(增量), "路径": str(路径),
                "链": 体["链"]})
    _写索引(行s)
    return 体


def 合并(检查点s: list[dict] | None = None) -> dict:
    """**加载最新全量 + 依次应用增量 ⇒ 当前状态。**

    ★ 这是增量存储能成立的前提：存了 delta 却合不回来，等于数据丢了。
      所以这条必须**可机判**（判据里拿"合并结果"与"直接全量算的结果"对）。
    """
    if 检查点s is None:
        检查点s = _读索引()
    状态: dict = {}
    for r in 检查点s:
        if r.get("全量"):
            p = Path(r.get("路径", ""))
            if not p.is_file():
                continue
            try:
                v = json.loads(p.read_text(encoding="utf-8"))
                状态 = dict(v.get("状态") or {})
            except Exception:                    # noqa: BLE001
                continue
            continue
        p = Path(r.get("路径", ""))
        if not p.is_file():
            continue
        try:
            v = json.loads(p.read_text(encoding="utf-8"))
        except Exception:                        # noqa: BLE001
            continue
        for k, ch in (v.get("增量") or {}).items():
            if ch.get("新") is None:
                状态.pop(k, None)
            else:
                状态[k] = ch.get("新")
    return 状态


# ══════════════════════════════════════════════════════════════════════════
# 相生环周期 5（SCHED-03）
# ══════════════════════════════════════════════════════════════════════════
周期 = 5


def 步数() -> int:
    """已经落过多少个检查点 = 第几步。**读不了就当 0**，绝不抛。"""
    try:
        return len(_读索引())
    except Exception:                            # noqa: BLE001
        return 0


def 该全量扫描吗(步: int | None = None) -> bool:
    """到整周期了吗（每 `周期` 步一次全量兜底）。

    ★ 为什么周期是 5 而不是"随便定一个"：它对应一条**相生环的长度**——
      走满一圈就做一次"完整验证"，中间每步只做单步验证。
      这个数**可调**，但它不该是"拍脑袋的值"，所以写在这里而不是散落在调用点。
      ⇒ 诚实说：**具体是否该是 5，需要真实数据校准**（见回执的诚实边界）。
    """
    n = 步数() if 步 is None else int(步)
    return n > 0 and n % 周期 == 0


# ══════════════════════════════════════════════════════════════════════════
# 告警（SCHED-06）
# ══════════════════════════════════════════════════════════════════════════
# ★ 五级不是"严重程度排序"，是**去向不同**（这一条才是有用的部分）：
#   FATAL/ERROR ⇒ 阻断当前操作（不能"记一笔继续跑"）
#   WARN        ⇒ 自动修 + 记录
#   INFO/DEBUG  ⇒ 只记录
级别 = {
    "FATAL": {"码": 5, "阻断": True, "去向": ("终端", "回执", "状态索引异常章节")},
    "ERROR": {"码": 4, "阻断": True, "去向": ("终端", "回执", "状态索引异常章节")},
    "WARN": {"码": 3, "阻断": False, "去向": ("回执", "状态索引异常章节")},
    "INFO": {"码": 2, "阻断": False, "去向": ("审计日志",)},
    "DEBUG": {"码": 1, "阻断": False, "去向": ("审计日志",)},
}


def 告警(级别名: str, 条件: str, 描述: str, 建议: str = "") -> dict:
    """生成一条告警。**不主动阻断**（阻断是调用方的决策，不是通知方的）。

    ★ 为什么这里不阻断：这个函数只负责**说清楚**"多严重、该去哪"。
      让它去 `sys.exit` 或抛异常，会把"报告问题的部分"和"决定停不停的部分"焊死 ——
      那样任何一处想改用（比如只想记不想停）都得改这个模块。
      ⇒ 返回 `阻断=True` 让调用方自己决定，这是**能力与决策分离**。
    """
    级 = (级别名 or "").strip().upper()
    if 级 not in 级别:
        # 不认识的级别 ⇒ **按最重处理**（认不出就从严，与其它判据同一个口径）
        级 = "FATAL"
        _降级 = True
    else:
        _降级 = False
    规 = 级别[级]
    行 = (f"[{级}] [{time.strftime('%Y-%m-%d %H:%M:%S')}] [{条件}] [{描述}]"
          + (f" [{建议}]" if 建议 else ""))
    体 = {"级别": 级, "条件": 条件, "描述": 描述, "建议": 建议, "行": 行,
          "阻断": 规["阻断"], "去向": list(规["去向"]),
          "认不出级别": _降级}
    _落日志(体)
    return 体


def _落日志(体: dict) -> None:
    """写入审计日志。写失败**不出声**（告警本身不能因为写不进去就丢）。"""
    try:
        p = _根() / "alerts" / "alerts.jsonl"
        p.parent.mkdir(parents=True, exist_ok=True)
        with p.open("a", encoding="utf-8") as f:
            f.write(json.dumps(体, ensure_ascii=False) + "\n")
    except Exception:                            # noqa: BLE001
        pass


def 告警们(上限: int = 20) -> list[dict]:
    """读最近的告警（体检用）。读不了返回空表，绝不抛。"""
    try:
        p = _根() / "alerts" / "alerts.jsonl"
        if not p.is_file():
            return []
        行s = p.read_text(encoding="utf-8", errors="replace").splitlines()
        出 = []
        for ln in 行s[-上限:]:
            try:
                出.append(json.loads(ln))
            except Exception:                    # noqa: BLE001
                continue
        return 出
    except Exception:                            # noqa: BLE001
        return []


def 统计() -> dict:
    """给 doctor 用：检查点数、最近是否全量、有没有 ERROR 以上。"""
    try:
        行s = _读索引()
        高 = [a for a in 告警们(50) if a.get("级别") in ("FATAL", "ERROR")]
        return {"检查点数": len(行s), "步数": len(行s), "周期": 周期,
                "上次全量": next((r.get("检查点") for r in reversed(行s)
                                  if r.get("全量")), None),
                "变化数合计": sum(int(r.get("变化数", 0)) for r in 行s),
                "高级告警": len(高),
                "高级告警示例": [a.get("行", "")[:80] for a in 高[:3]]}
    except Exception as e:                       # noqa: BLE001
        return {"检查点数": 0, "错误": f"{type(e).__name__}: {e}"}
