# 判定：值 ∈ Fin 2 **带因由**（不是 Bool）
# ══════════════════════════════════════════════════════════════════

@dataclass(frozen=True)
class 判定:
    """一个门的判定：值 ∈ `Fin 2`，**带因由**。

    ★★★ 为什么不直接用 `Bool`（TS-442 无损读）：
      `Bool` 把「**红因为违反**」与「**红因为读不到**」塌缩成同一个值，
      而这两件事的处置**完全不同**（一个要改代码，一个要修门/补路径）。
      ⇒ 判定值抬到 `Fin 2` **并带因由**；因由是**结构**，不是附注。
    ★★★ 为什么不加「可判定」字段：可判定性是**结构给的**（TS-468 §4），
      不是要求来的。`Fin 2` 天然可判定，且**不花一分 EM**。
    """
    门: str
    值: int
    因由: str = ""
    可读: bool = True

    def __post_init__(self) -> None:
        if self.值 not in (FALSE, TRUE):
            raise ValueError(f"判定值必须 ∈ Fin 2，得 {self.值!r}")


def 保真方程(值_x: int, 值_σx: int) -> tuple[bool, str]:
    """★★★★★ **保真方程**（一条，取代「`all` + `witness_ok`」两个补丁）：

        `门(σ x) == flip2(门 x)`

    ★★★ 为什么**一条**方程够 —— **假绿与假红是同一个违反**：
      · **恒真门**：`门 x = 1`、`门 (σ x) = 1`，而 `flip2 1 = 0` ⇒ **破**；
      · **恒红门**：`门 x = 0`、`门 (σ x) = 0`，而 `flip2 0 = 1` ⇒ **破**；
      ⇒ 两者都是「**轨道退化为不动点**」—— 即 `orbit_is_a_pair` 的逆否。
    ★★★ 为什么只需 **2 次求值**（TS-468 §5 求解 = 2 步闭合）：
      判定侧载体是 `Fin 2`，对合 ⇒ 轨道闭合在 2 步内 ⇒ **不枚举变异**。
    """
    want = 翻转两仪(值_x)
    if 值_σx == want:
        return True, (f"保真：门(x)={值_x}，门(σx)={值_σx}=flip2({值_x}) ⇒ 有区分力")
    if 值_x == TRUE and 值_σx == TRUE:
        return False, ("保真破（**恒真门**）：门对变异**仍绿** ⇒ 轨道退化为不动点"
                       " ⇒ 该门无区分力（假绿）")
    if 值_x == FALSE and 值_σx == FALSE:
        return False, ("保真破（**恒红门**）：门对变异**仍红** ⇒ 轨道退化为不动点"
                       " ⇒ **与恒真门是同一个违反**（假红）")
    return False, f"保真破：门(x)={值_x}，门(σx)={值_σx}，应={want}"


def σ合法(σ: 平衡) -> tuple[bool, list[str]]:
    """**σ 本身必须是已验平衡**（对合 + 无不动点）。

    ★★★★★ 这是 `gate_witness` 原先的**真缺口**（实测）：
      它挑一个变异就当 σ 用，**从不检查这个变异是不是对合、有没有不动点**。
      若 σ 有不动点（变异没改动门真正读的东西）⇒ `门(σ x) = 门(x)` **恒成立**
      ⇒ 保真方程 `门(x) == flip2(门(x))` **对任何门都不成立**
      ⇒ **真门被误判为破** ⇒ 判 vacuous ⇒ 白白派生替换门（**假红**）。
      ⇒ ★★★★★ **σ 不是平衡，保真方程就没有判据力。**
    """
    坏 = σ.验()
    return (not 坏), 坏


# ══════════════════════════════════════════════════════════════════
# 顶层裁决 = 格 meet（取代 `all(results.values())`）
# ══════════════════════════════════════════════════════════════════

def 格裁决(判定集: Sequence[判定]) -> tuple[int, list[str], str]:
    """顶层裁决：在 `Fin 2^n` 的**积序**上取**下确界**（meet）。

    ★★★ 与 `all(results.values())` 的三处**结构**差别（每处治掉一类缺陷）：

      ① **空集**：`all({})` 恒 `True` ⇒ **零门判全绿**（实测踩过）。
         这里空判定集 ⇒ 值 `FALSE` 且因由写明「零个机器判据 ⇒ 无裁决依据」。
         ★ 不变量 **空门集不得判绿** 由**结构**给出，不靠额外判断。

      ② **因由无损**：`all` 只回一个 `Bool`，**丢掉了是哪个门红的**。
         这里回**全部**红门的因由（不压平 —— 压平就是 `Defect384`）。

      ③ **可读性**：`all` 把「读不到」与「违反」混成一个 `False`。
         这里**分开列** ⇒ 处置不同（改代码 / 修门或补路径）。
    """
    if not 判定集:
        return FALSE, [], "零个机器判据 ⇒ 无裁决依据（**空门集不得判全绿**）"
    值 = TRUE
    因由: list[str] = []
    读不到: list[str] = []
    for d in 判定集:
        if not d.可读:
            读不到.append(f"{d.门}：{d.因由 or '读不到'}")
            值 = FALSE
            continue
        if d.值 == FALSE:
            值 = FALSE
            因由.append(f"{d.门}：{d.因由 or '未给因由'}")
    注 = ""
    if 读不到:
        注 = "读不到 ≠ 违反（处置不同）：" + "；".join(读不到)
    return 值, 因由, 注


def 从门结果(结果: dict, 因由表: dict | None = None) -> tuple[int, list[str], str]:
    """便捷入口：把 `{门名: Bool}` + `{门名: 因由}` 收成格裁决。

    ★ 兼容既有调用点（`all(results.values())` 的替换），但**不丢因由**。
    ★ `结果` 为空 ⇒ 走 `格裁决` 的空集分支 ⇒ **不判绿**（与 `all` 相反）。
    """
    因由表 = 因由表 or {}
    判定集: list[判定] = []
    for 门, v in (结果 or {}).items():
        因 = str(因由表.get(门) or "")
        可读 = "读不到" not in 因 and "unreadable" not in 因
        判定集.append(判定(门=str(门), 值=TRUE if v else FALSE,
                            因由=因, 可读=可读))
    return 格裁决(判定集)


def 从审计(结果: dict, 审计: list | None
            ) -> tuple[int, list[str], str]:
    """便捷入口：直接吃 `evaluate` 的 `(results, audit)` 两件套。

    ★★★ 为什么值得单独给一个入口（不是重复）：
      `audit` 里带着**读到的因由**（`cause`）与**是否读不到**（`unreadable`），
      而 `results` 里只有 `Bool`。**只吃 `results` 就是经典层**——
      因由在那一层被压平掉了（`Defect384`）。
      ⇒ 这个入口的作用就是**把因由通道接上**，让裁决带上「为什么」。
    """
    判定集: list[判定] = []
    _因: dict = {}
    for a in (审计 or []):
        if isinstance(a, dict) and a.get("gate"):
            _因[str(a["gate"])] = a
    for 门, v in (结果 or {}).items():
        a = _因.get(str(门)) or {}
        因 = str(a.get("cause") or a.get("err") or "")
        可读 = not bool(a.get("unreadable"))
        判定集.append(判定(门=str(门), 值=TRUE if v else FALSE,
                            因由=因, 可读=可读))
    return 格裁决(判定集)


