@dataclass
class 增信格:
    """**增信 = 沿格单调上升**（TS-468 §4），且上升必须带**结构见证**。

    ★★★ 为什么不用 `ok/total` 两个计数：
      计数上涨**不等于**增信 —— 实测踩过：自检自身抛异常时，
      `total` 照样涨、`ok/total` 照样「全绿」⇒ **假绿**。
      ⇒ 计数是**记账**；增信要求在**格**上真的上升，且能指出**是哪一位、
        因为哪条门的哪次真跑**由 0 变 1。
    ★ 直引 TS-429 的裁定：「增信」是错的框架，「**可及性**」才对 ——
      所以本类判的是「这一位**可及**了吗」，不是「证据多了吗」。
    ★ 沿格上升**不需要新信息**（格序是结构）⇒ **免费**。
    """
    n: int
    态: tuple = ()
    见证: list = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.态:
            self.态 = tuple([FALSE] * self.n)

    def 上升(self, 新态: Sequence[int], 见证: dict | None = None) -> list[str]:
        """沿**积序**上升：**每一位只允许 0→1**；真上升**必须**给结构见证。

        返回违反清单（空 = 上升成立）。
        """
        坏: list[str] = []
        if len(新态) != self.n:
            坏.append(f"态长度 {len(新态)} ≠ {self.n} ⇒ 不是同一个格上的元素")
            return 坏
        for b in 新态:
            if b not in (FALSE, TRUE):
                坏.append(f"态含非 Fin 2 元素：{b!r}")
                return 坏
        真上升 = False
        for i, (旧, 新) in enumerate(zip(self.态, 新态)):
            if 旧 == TRUE and 新 == FALSE:
                坏.append(f"位 {i} 由 1 退回 0 ⇒ **沿格下降**（增信不得下降）")
            elif 旧 == FALSE and 新 == TRUE:
                真上升 = True
        if 真上升 and not 见证:
            坏.append("有位上上升但**无结构见证** ⇒ 是记账不是增信"
                      "（判非增信：计数上涨 ≠ 增信）")
        if not 坏:
            self.态 = tuple(新态)
            if 真上升:
                self.见证.append(dict(见证 or {}))
        return 坏

    def 见证数(self) -> int:
        return len(self.见证)


# ══════════════════════════════════════════════════════════════════
# 自检（判据力）
# ══════════════════════════════════════════════════════════════════

def _selftest() -> int:
    坏: list[str] = []
    计 = [0]

    def chk(名: str, 条: bool, 说明: str = "") -> None:
        计[0] += 1
        if not 条:
            坏.append(名 + (f"（{说明}）" if 说明 else ""))

    # ── ① 平衡：两仪（对合 + 无不动点，零公理）──
    F2 = 两仪()
    chk("① 两仪平衡无违反", F2.验() == [], str(F2.验()))
    chk("① 两仪无不动点（0↦1）", F2.σ(FALSE) == TRUE)
    chk("① 两仪对合（翻两次回原处）", F2.σ(F2.σ(FALSE)) == FALSE)

    # ── ① 积平衡：验证 O(1)，**结构上不可能枚举** ──
    P = 积平衡(名="判定空间 Fin 2^n", n=200)
    chk("① 积平衡 n=200 验证无违反（不枚举 2^200）", P.验() == [], str(P.验()))
    chk("① 积平衡**没有载体字段** ⇒ 结构上不可能枚举",
        not hasattr(P, "载体"), "有载体字段就可能被枚举")
    chk("① 积平衡逐位翻转（对合）",
        P.σ(P.σ((1, 0, 1))) == (1, 0, 1))
    chk("① 积平衡无不动点（逐位取反必改变每一位）",
        P.σ((1, 0, 1)) != (1, 0, 1))

    # ── ② 保真同态：id 保真、复合保真（零 EM）──
    chk("② id 保真", 保真恒等(F2) == [], str(保真恒等(F2)))
    chk("② 复合保真（保真沿链免费传播）",
        保真复合(F2, F2, F2, lambda x: x, 翻转两仪) == [])
    # 反面：不保真的映射必须被抓
    chk("② 常值映射**不保真**（被抓）",
        保真同态(F2, F2, lambda x: TRUE) != [])

    # ── ③ 生成：轨道恰为二元对 ──
    chk("③ 轨道是二元对", 轨道(F2, FALSE) == (FALSE, TRUE))
    chk("③ 轨道闭合（三步判据全过）", 轨道闭合(F2, FALSE) == [])
    # 造一个**有不动点**的退化平衡 ⇒ 轨道必须拒
    退化 = 平衡(名="退化(有不动点)", 载体=(FALSE, TRUE), σ=lambda i: FALSE)
    try:
        轨道(退化, FALSE)
        退化被抓 = False
    except ValueError:
        退化被抓 = True
    chk("③ 有不动点的载体 ⇒ 轨道退化**必被抓**", 退化被抓)
    chk("③ 退化平衡的验必须报「有不动点」",
        any("有不动点" in x for x in 退化.验()), str(退化.验()))

    # ── ④ 求解：恰好 2 步闭合 O(1) ──
    点, 步 = 求解(F2, FALSE)
    chk("④ 求解 2 步闭合且回到起点", 点 == FALSE and 步 == 2, f"{点},{步}")
    chk("④ 求解步数恒 ≤ 2（O(1)，与载体无关）",
        求解(积平衡(名="x", n=10 ** 6), tuple([0] * 3))[1] <= 2)

    # ── ★★★★★ 保真方程：假绿与假红是**同一个违反** ──
    ok真, 因真 = 保真方程(TRUE, FALSE)
    chk("★ 真门：门(x)=1，门(σx)=0 ⇒ 保真", ok真, 因真)
    ok绿, 因绿 = 保真方程(TRUE, TRUE)
    chk("★★ 恒真门（假绿）⇒ 保真破", not ok绿, 因绿)
    ok红, 因红 = 保真方程(FALSE, FALSE)
    chk("★★ 恒红门（假红）⇒ 保真破", not ok红, 因红)
    chk("★★★ 假绿与假红**是同一个违反**（都因轨道退化为不动点）",
        ("轨道退化" in 因绿) and ("轨道退化" in 因红),
        f"绿={因绿} / 红={因红}")
    chk("★★★ 同一违反的因由都指向 orbit_is_a_pair 的逆否",
        ("同一个违反" in 因红) or ("同一个违反" in 因绿))
    # 一条方程同时挡住两类 ⇒ 不需要两个补丁
    chk("★★★ 一条方程同时挡住假绿与假红（取代 all + witness_ok 两个补丁）",
        (not ok绿) and (not ok红) and ok真)

    # ── ★★★★★ σ 必须是已验平衡（gate_witness 原先的真缺口）──
    okσ, 坏σ = σ合法(F2)
    chk("★ 两仪是合法 σ", okσ, str(坏σ))
    okσ坏, 坏σ坏 = σ合法(退化)
    chk("★★ 有不动点的 σ **不合法**（缺了这一步，保真方程没有判据力）",
        not okσ坏, str(坏σ坏))
    # 实测退化 σ 的后果：**真门被误判**
    #   σ 有不动点 ⇒ 门(σx) = 门(x) ⇒ 保真方程对任何门都不成立
    for 门x in (TRUE, FALSE):
        ok误, 因误 = 保真方程(门x, 门x)
        chk(f"★★ 退化 σ 下门(x)={门x} 被误判为破（**假红**）", not ok误, 因误)

    # ── 顶层裁决：格 meet vs all(Bool) ──
    空值, 空因, 空注 = 格裁决([])
    chk("★★ 空门集**不判绿**（对照 `all({})` 恒 True）", 空值 == FALSE, str(空注))
    chk("★★ 空门集的因由写明「无裁决依据」", "无裁决依据" in 空注)
    全绿 = [判定("a", TRUE, "绿"), 判定("b", TRUE, "绿")]
    chk("★ 全绿 ⇒ 判绿", 格裁决(全绿)[0] == TRUE)
    chk("★ 全绿 ⇒ 无红因由", 格裁决(全绿)[1] == [])
    两红 = [判定("a", FALSE, "违反A"), 判定("b", FALSE, "违反B")]
    v2, 因2, _ = 格裁决(两红)
    chk("★★ 两个红门 ⇒ 判红", v2 == FALSE)
    chk("★★★ 因由**无损**：两个红门的因由都保留（`all` 会压平成一个 Bool）",
        len(因2) == 2 and any("违反A" in x for x in 因2)
        and any("违反B" in x for x in 因2), str(因2))
    混 = [判定("a", FALSE, "真违反"), 判定("b", TRUE, "读不到", 可读=False)]
    v3, 因3, 注3 = 格裁决(混)
    chk("★★ 读不到 ⇒ 判红", v3 == FALSE)
    chk("★★★ 「读不到」与「违反」**分开列**（处置不同）",
        len(因3) == 1 and "读不到" in 注3 and "真违反" in 因3[0],
        f"因由={因3} 注={注3}")
    chk("★ 从门结果：空 dict ⇒ 不判绿（与 `all({})` 相反）",
        从门结果({})[0] == FALSE)
    chk("★ 从门结果：全 True ⇒ 判绿", 从门结果({"a": True})[0] == TRUE)
    # ★ 从审计入口：因由通道必须真的接上（否则又是经典层）
    _v4, _因4, _注4 = 从审计(
        {"a": False, "b": True},
        [{"gate": "a", "ok": False, "cause": "编译失败 E0308"},
         {"gate": "b", "ok": True, "cause": "绿"}])
    chk("★★ 从审计：红门的**真因由**进裁决（不是空串）",
        _v4 == FALSE and any("E0308" in x for x in _因4), str(_因4))
    _v5, _因5, _注5 = 从审计(
        {"a": False},
        [{"gate": "a", "ok": False, "cause": "禁词门读不到被测文件",
          "unreadable": True}])
    chk("★★★ 从审计：`unreadable` ⇒ 归「读不到」而非「违反」（处置不同）",
        _v5 == FALSE and "读不到" in _注5 and not _因5, f"因={_因5} 注={_注5}")

    # ── ⑤ 增信 = 沿格单调上升 ──
    G = 增信格(n=2)
    chk("⑤ 初态是全 0（未判定，不是绿）", G.态 == (FALSE, FALSE))
    chk("⑤ 带见证的上升 ⇒ 成立",
        G.上升((TRUE, FALSE), {"门": "a", "真跑": "t1"}) == [])
    chk("⑤ 见证已记", G.见证数() == 1)
    chk("★★ 下降（1→0）⇒ 拒",
        any("下降" in x for x in G.上升((FALSE, FALSE), {"门": "a"})))
    chk("★★★ 无见证的上升 ⇒ 拒（**计数上涨 ≠ 增信**）",
        any("记账不是增信" in x for x in G.上升((TRUE, TRUE), None)))
    chk("★★ 态未被非法上升污染", G.态 == (TRUE, FALSE), str(G.态))
    chk("★ 带见证的第二次上升 ⇒ 成立",
        G.上升((TRUE, TRUE), {"门": "b", "真跑": "t2"}) == [])
    chk("★ 见证累计到 2", G.见证数() == 2)

    if 坏:
        print("shushu_logic 自检红：")
        for x in 坏:
            print(f"  ✗ {x}")
        print(f"shushu_logic 自检：{计[0] - len(坏)}/{计[0]} 通过")
        return 1
    print(f"shushu_logic 自检：{计[0]}/{计[0]} 全绿"
          "（平衡 · 保真 · 生成 · 求解 · 增信 · 保真方程）")
    return 0


if __name__ == "__main__":
    import sys
    if "--selftest" in sys.argv:
        raise SystemExit(_selftest())
    print("数术逻辑层（--selftest 跑自检）")
