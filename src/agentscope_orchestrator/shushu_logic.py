"""数术逻辑层（TS-468 的编排器接线）：平衡 · 保真 · 生成 · 增信 · 求解。

── 为什么需要这一层（本模块存在的唯一理由） ──

库件 `MathlibBridge/TS468_ShushuLogicLayer.lean` 已机证（零 EM）：

  **同一个「平衡」，经典层要付排中律，数术层是恒等式。**

  编排器的顶层此前**全程在经典层工作**：
    · 判定值 = `Bool`；
    · 合成   = `all(...)` / `and`；
    · 门有没有牙 = **另打一个补丁**（`witness_ok`）；
    · 求见证 = **枚举变异**（搜索）。
  而这三样在经典层里都是排中律的化身 ⇒ **每一次判定都在付 EM 的费**。

  ★★★★★ TS-468 §6 的修复口径：
    **不是把机器做强，而是把顶层从经典层挪回数术层。**

── 四操作在数术层的精确形态（本模块逐条实现） ──

  ① **平衡** = 载体 + 对合 σ + **无不动点**（§2 `Balance`）。
      ★ 没有第四个字段 —— 尤其**没有「可判定」字段**：
        可判定性是结构给的，不是要求来的（§4）。

  ② **保真** = 平衡同态 `IsBalancedHom B C f := ∀ x, C.σ (f x) = f (B.σ x)`。
      ★★★ 关键差别：**交换律不要求 `Decidable` —— 它是恒等式。**
      ⇒ `id` 保真、**复合保真（沿链免费传播）**，零 EM。

  ③ **生成** = 无不动点 ⇒ **轨道恰为二元对** `{x, σ x}`（§3）。
      ⇒ 载体基数必为偶数；**1-周期不存在**。
      ⇒ **生成不是外加的能力，是平衡的推论。**

  ④ **求解** = 对合 ⇒ **恰好 2 步闭合**（§5）⇒ **O(1)**，与载体大小无关。
      ⇒ ★★★ **求解不是查找，是翻转** —— **不需要搜索**。

  ⑤ **增信** = **沿格单调上升**（§4）。
      ★ 直引 TS-429 的裁定：「增信」是错的框架，「**可及性**」才对。
      ⇒ 沿偏序上升**不需要新信息**（格序是结构）⇒ 免费。

── 本层治掉的三类缺陷（原先各自打补丁，现在是一条方程） ──

  · **假绿（恒真门）**：`门 x = 1` 且 `门 (σ x) = 1`，而 `flip2 1 = 0` ⇒ **保真破**。
  · **假红（恒红门）**：`门 x = 0` 且 `门 (σ x) = 0`，而 `flip2 0 = 1` ⇒ **同一个违反**。
    ⇒ ★★★★★ **假绿与假红是同一个违反**：**轨道不是二元对**（不动点）。
      这正是 `orbit_is_a_pair` 的逆否 —— **一条方程取代两个补丁**。
  · **假绿（计数）**：`ok/total` 两个计数都涨，而结构没变 ⇒ 在格上**没上升**
    （增信要求带**结构见证**）⇒ 判非增信。

── 诚实边界（必读·不许含糊） ──

  ★★ **本层不判定任意命题。** TS-461/TS-465 已机证「任意 `Prop` 的判定」
    等价于排中律，**本层不改变这一点**。
    · **门本身**（如 `cargo` 编译）是**神谕**（TS-462 §3：神谕不可制造）；
    · 本层判的是「**编排器怎么读神谕的返回**」——
      而那个读侧的目标类型本来就是 `Fin 2`（TS-449 `nsReadFin`），
      **是顶层把它包进 `Bool`/`Prop` 才产生了错位**。
    ⇒ ★★★★★ **修复不是「改造门」，是「别再包」。**（`ns_read_balance_closes`）
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable, Sequence

# `Fin 2` 的两个元素（不用 `bool`：Bool 是经典层对象，会把因由压平）
FALSE, TRUE = 0, 1


# ══════════════════════════════════════════════════════════════════
# ① 平衡（TS-468 §2）：载体 + 对合 σ + 无不动点
# ══════════════════════════════════════════════════════════════════

def 翻转两仪(i: int) -> int:
    """`flip2`：`Fin 2` 的翻转（TS-468 §2）。"""
    return 1 - i


@dataclass(frozen=True)
class 平衡:
    """**平衡结构**：载体 + 对合 `σ` + **无不动点**（TS-468 §2）。

    ★★★ **这是「阴阳」的抽象形态** —— 三个字段分别对应：
      · `σ`：**翻转**（阴↔阳）；
      · `对合`：**翻两次回到原处**；
      · `无不动点`：**没有东西是它自己的反面**（平衡，不偏）。
    ★★ **注意：没有第四个字段** —— 尤其是**没有「可判定」字段**。
      ⇒ 可判定性在这里是**结构给的**，不是要求来的。
    """
    名: str
    载体: tuple
    σ: Callable[[Any], Any]

    def 验(self) -> list[str]:
        """机器验证「对合 + 无不动点」。有限载体 ⇒ 逐元素查，**零公理**。

        ★ 这是**结构事实**的机检，不是搜索：判定侧载体恒为 2 个元素。
        """
        坏: list[str] = []
        if not self.载体:
            坏.append(f"平衡[{self.名}]：空载体 ⇒ 没有平衡结构")
            return 坏
        for x in self.载体:
            try:
                σσx = self.σ(self.σ(x))
                σx = self.σ(x)
            except Exception as exc:      # noqa: BLE001 翻转不可算 ⇒ 如实报
                坏.append(f"平衡[{self.名}]：σ 在 {x!r} 上不可算（{type(exc).__name__}）")
                continue
            if σσx != x:
                坏.append(f"平衡[{self.名}]：**非对合** σ(σ({x!r}))={σσx!r} ≠ {x!r}")
            if σx == x:
                坏.append(f"平衡[{self.名}]：**有不动点** σ({x!r})={x!r}"
                          " ⇒ **不生成**（轨道退化为单点）")
        return 坏


def 两仪() -> 平衡:
    """**两仪平衡**（`Fin 2`）—— 判定侧的载体，NS 机制读侧的目标类型。"""
    return 平衡(名="两仪(Fin 2)", 载体=(FALSE, TRUE), σ=翻转两仪)


@dataclass(frozen=True)
class 积平衡:
    """判定空间 `Fin 2^n` 的平衡：**逐位翻转**。

    ★★★★★ 机器验证 **O(1)**，**绝不枚举 `2^n`** —— 因为「逐位取反必改变每一位」：
      · 对合：每位 `1-(1-b) = b`；
      · 无不动点：每位 `1-b ≠ b`。
      ⇒ **只看一个位就够**（TS-468 §2 `bagua_neg_no_fixed_point` 的同形证明：
        「证明只需看**一个爻位**」）。
      ⇒ ★★★ 这正是「**能不枚举就别枚举**」在这一层的落地。

    ★★ 本类**没有 `载体` 字段**（符号表示，不是元组）——
      所以它**在结构上就不可能枚举**。这是有意为之，不是省略。
    """
    名: str
    n: int

    def σ(self, v: Sequence[int]) -> tuple[int, ...]:
        return tuple(1 - b for b in v)

    def 验(self) -> list[str]:
        坏: list[str] = []
        if self.n <= 0:
            坏.append(f"积平衡[{self.名}]：n={self.n} ⇒ 空载体没有平衡结构")
            return 坏
        # ★ 只看**一个位**（逐位取反必改变每一位）—— 与 n 无关，O(1)
        b = FALSE
        if 1 - (1 - b) != b:
            坏.append(f"积平衡[{self.名}]：非对合")
        if 1 - b == b:
            坏.append(f"积平衡[{self.名}]：有不动点 ⇒ 不生成")
        return 坏


# ══════════════════════════════════════════════════════════════════
# ② 保真 = 平衡同态（TS-468 §2）
# ══════════════════════════════════════════════════════════════════

def 保真同态(B: 平衡, C: 平衡, f: Callable[[Any], Any]) -> list[str]:
    """`IsBalancedHom B C f := ∀ x, C.σ (f x) = f (B.σ x)`（TS-468 §2）。

    ★★★ **这是「保真」的精确形态** —— 与轨道式保真同型：
      保真**不是**「存在一个 `Bool` 扛住真值」（那是经典层要付 EM 的形态），
      而是**映射与翻转可交换**。
    ★★★★★ **关键差别**：交换律**不要求 `Decidable`** ——
      **它是恒等式，两侧都写在结构里。**
    """
    坏: list[str] = []
    for x in B.载体:
        lhs = C.σ(f(x))
        rhs = f(B.σ(x))
        if lhs != rhs:
            坏.append(f"保真破：x={x!r} ⇒ σ_C(f x)={lhs!r} ≠ f(σ_B x)={rhs!r}")
    return 坏


def 保真恒等(B: 平衡) -> list[str]:
    """`id` 保真（TS-468 `balancedHom_id`·零 EM）。"""
    return 保真同态(B, B, lambda x: x)


def 保真复合(B: 平衡, C: 平衡, D: 平衡, f: Callable, g: Callable) -> list[str]:
    """保真**可复合**（TS-468 `balancedHom_comp`）⇒ **保真沿链免费传播**。

    ★ 先验两个因子，再验复合；任一破都如实报。
    """
    坏 = 保真同态(B, C, f) + 保真同态(C, D, g)
    坏 += [f"复合保真破：{x}" for x in 保真同态(B, D, lambda x: g(f(x)))]
    return 坏


# ══════════════════════════════════════════════════════════════════
# ③ 生成（TS-468 §3）：无不动点 ⇒ 轨道恰为二元对
# ══════════════════════════════════════════════════════════════════

def 轨道(B: 平衡, x: Any) -> tuple:
    """**生成**（TS-468 §3）：对合 + 无不动点 ⇒ 轨道**恰为二元对** `{x, σ x}`。

    ★★★ 读法：
      · 一个轨道 = 一对阴阳，**不多不少**；
      · ⇒ 载体基数必为偶数；
      · ⇒ **1-周期不存在**（周期 1 就是不动点，被排除）。
    ★ 轨道退化为单点 ⇒ **不是二元对** ⇒ 抛错（这是结构违反，不是普通失败）。
    """
    y = B.σ(x)
    if y == x:
        raise ValueError(f"轨道退化：σ({x!r}) = {x!r} ⇒ 不动点 ⇒ **无生成性**"
                         f"（平衡[{B.名}] 未验或已破）")
    return (x, y)


def 轨道闭合(B: 平衡, x: Any) -> list[str]:
    """机检 `orbit_is_a_pair`：两步回到原处 ∧ 不等于自身 ∧ **翻后翻也不等自身**。"""
    坏: list[str] = []
    σx = B.σ(x)
    if B.σ(σx) != x:
        坏.append(f"轨道不闭合：σ(σ({x!r}))={B.σ(σx)!r} ≠ {x!r}")
    if σx == x:
        坏.append(f"轨道退化：σ({x!r})={x!r}")
    elif B.σ(σx) == σx:
        坏.append(f"σ x 是 σ 的不动点：{σx!r}")
    return 坏


# ══════════════════════════════════════════════════════════════════
# ④ 求解（TS-468 §5）：对合 ⇒ 恰好 2 步闭合 ⇒ O(1)
# ══════════════════════════════════════════════════════════════════

def 求解(B: 平衡, x: Any) -> tuple[Any, int]:
    """**求解**（TS-468 §5）：对合 ⇒ **恰好 2 步闭合** ⇒ **O(1)**。

    ★★★★★ 读法：
      · 求解 = **沿翻转走到轨道闭合**；
      · ⇒ 复杂度 **O(1)**（恰好 2 步，与载体大小无关）。
    ⇒ ★★★ **求解不是查找，是翻转** —— **不需要搜索**。
      这正是用户的口径：「全局读不需要搜索」「O(1)」——
      **在数术层它是恒等式，在经典层它才需要搜索。**
    """
    y = B.σ(x)
    步 = 1
    if y != x:
        y = B.σ(y)
        步 = 2
    return y, 步


