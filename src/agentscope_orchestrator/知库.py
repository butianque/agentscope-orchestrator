def _库目录(根: Path) -> Path:
    """根 → 它的索引目录。**显式名字表**（禁哈希折叠，与 `memory8._取号` 同款）。

    ★ 为什么不用哈希：同一个名字必须**永远**映射到同一格（否则「重扫」变成
      「每次新建一份索引」）；不同名字**必须**不同格（否则两个项目串台）。
      哈希两头都不保证（碰撞），而名字表两头都保证 —— 满了就抛错，绝不静默折叠。
    ★ 名字含路径分隔符 ⇒ 用**根名 + 号**做目录名，原名记在 `表.json` 里（可读、可查）。
    """
    基 = _状态根()
    基.mkdir(parents=True, exist_ok=True)
    表档 = 基 / "表.json"
    表 = {}
    if 表档.is_file():
        try:
            表 = json.loads(表档.read_text(encoding="utf-8"))
        except Exception:                                      # noqa: BLE001
            表 = {}
    键 = str(根)
    for 号, 条 in 表.items():
        if 条.get("根") == 键:
            d = 基 / 条["目录"]
            d.mkdir(parents=True, exist_ok=True)
            return d
    下 = max([int(k) for k in 表] or [0]) + 1
    if 下 > 9999:
        raise RuntimeError("知库名字表已满（上限 9999）—— 拒绝折叠："
                           "宁可失败，也不许两个不同的根共用一个索引格")
    名 = re.sub(r"[^0-9A-Za-z\u4e00-\u9fff_.-]+", "_", 根.name)[:32] or "根"
    d = 基 / f"{下:04d}_{名}"
    d.mkdir(parents=True, exist_ok=True)
    表[str(下)] = {"根": 键, "目录": d.name, "建于": time.time()}
    表档.write_text(json.dumps(表, ensure_ascii=False, indent=1), encoding="utf-8")
    return d


def _顶层段(相: str) -> str:
    """路径的第一个有效段（`memory8.子系统名` 的同款信号：壳目录要往里再取一段）。"""
    段 = [x for x in 相.split("/") if x]
    if not 段:
        return "."
    if 段[0] in ("src", "lib", "app", "source", "pkg", "packages") and len(段) > 1:
        return 段[1]
    return 段[0]


def _后缀(名: str) -> str:
    """后缀。★ 无后缀**不是空串**，是 `(无)` —— 空串会被当成「没记」，两者必须分得开。"""
    i = 名.rfind(".")
    if i <= 0:
        return "(无)"
    return 名[i:].lower()[:24]


def 建索引(根, 打印=lambda *a: None) -> dict:
    """① **有什么** —— 只走目录、只 stat、**不读内容**（这就是它秒级的原因）。

    产物（都落在 `<根>/.知库/`）：
      · `索引.jsonl` —— 一行一个文件：`[相对路径, 后缀, 字节, mtime, 顶层段]`
      · `知库.json`  —— 汇总读数（含**排除的目录**，口径 260 不许静默丢）

    ★★★★★ R536h：**索引不许索引自己**（口径 391）。

      真读数（2026-11-16，`--root <本包>` 真跑 CLI 抓到的）：
        `知库·建索引 agentscope_orchestrator：文件 **311,069** · 20453.7MB · **542.71s**`
      —— 而 docstring 里写的是「**秒级**」✗ 差 100 倍以上，**没人量过**（口径 389）。

      查到底是**自指**：状态根（`ORCH_STATE_DIR/知库/`）默认落在 `work/` 下，
      而 `work/` **正在被索引的根里面** ⇒ `_库目录(根)` 在遍历**之前**建好目录，
      遍历就把**它自己历次建的索引格与临时目录**也数了进去 ✗
        · `$pkg` 实测 351,129 个文件里 **305,100 个在 `work`**（87%）；
        · 而 `work/知库/` 下是 `0001_tools` / `0002_判188可用_*` / …
          ⇒ **索引在数自己的残渣** ✓
      ⇒ 后果是**自我放大的正反馈**：跑得越多 → 残渣越多 → 索引越大 → 越慢 ✗

      ★ 为什么不能靠「把 `work` 加进 `壳目录`」了事：`work` 里**也有真东西**
        （脚本、实验、暂存），一刀切会**把真源码排掉**（那是 R532「剪掉 3,914 个
        真源码目录」的同一个错）。**只有状态区自己是逻辑必然要排的** ——
        索引自己的产物不是「被索引对象」的一部分。
    """
    根 = Path(根).resolve()
    assert 根.is_dir(), f"不是目录：{根}"
    出 = _库目录(根)
    # ★ 自指闸：**编排器自己的产物**恒排除（不论它落在根的哪里）。
    #   · 状态区（索引自己）—— 逻辑必然：索引自己的产物不是「被索引对象」的一部分；
    #   · 降级临时目录（`<状态根>/../临时`）—— ★ 口径 392：
    #     「系统临时目录全不可写 ⇒ 降级到自己的目录」是对的（能跑总比跑不了好），
    #     **但降级没有上限** ⇒ 实测这台机器 `work/临时` 堆了 **254,999 个文件**，
    #     而它是**每次运行**（包括每一次判据）留下的 ⇒ **一个环境问题
    #     变成了索引的性能问题**：`盘点` 要 stat 它们 ⇒ 128 秒 ✗。
    #   ★ 为什么这两条可辩护、而「把 `work` 一刀切排掉」不可辩护：
    #     `work` 里**也有真东西**（脚本/实验/暂存），一刀切会排掉真源码
    #     （那是 R532「剪掉 3,914 个真源码目录」的同一个错）；
    #     只有「编排器自己的产物」是**逻辑必然**不该被索引的。
    状态 = _状态根().resolve()
    自指 = {os.path.normcase(str(状态))}
    降级临 = 状态.parent / "临时"
    if 降级临.is_dir():
        自指.add(os.path.normcase(str(降级临.resolve())))
    t0 = time.time()
    行 = []
    排除目录 = {}
    总数 = 总字节 = 0
    for 目, 子目们, 文件们 in os.walk(根):
        目p = Path(目)
        # ★★★ 自指必须断：走到「编排器自己的产物」就**整棵剪掉**（连文件都不数）
        目n = os.path.normcase(os.path.abspath(目))
        if 目n in 自指:
            键 = "(知库自己的状态区)" if 目n == os.path.normcase(str(状态)) else "(降级临时目录)"
            排除目录[键] = 排除目录.get(键, 0) + 1
            子目们[:] = []
            continue
        保留 = []
        for d in 子目们:
            if d in 壳目录:
                排除目录[d] = 排除目录.get(d, 0) + 1
            else:
                保留.append(d)
        子目们[:] = 保留
        for f in 文件们:
            try:
                st = (目p / f).stat()
            except OSError:
                continue
            相 = (目p / f).relative_to(根).as_posix()
            行.append([相, _后缀(f), st.st_size, int(st.st_mtime), _顶层段(相)])
            总数 += 1
            总字节 += st.st_size
    行.sort(key=lambda x: x[0])
    档 = 出 / "索引.jsonl"
    档.write_text("\n".join(json.dumps(x, ensure_ascii=False) for x in 行), encoding="utf-8")
    后缀计 = {}
    顶层计 = {}
    for _, s, n, _, t in 行:
        后缀计[s] = 后缀计.get(s, 0) + 1
        顶层计[t] = 顶层计.get(t, 0) + 1
    汇 = {
        "根": str(根),
        "建于": time.time(),
        "文件数": 总数,
        "总字节": 总字节,
        "★排除了哪些目录理由": "只排外壳（VCS/包缓存/虚拟环境）—— 每条一句话能说清；"
                        "**不排**「看起来像运行副本」（`kg.py` 那样按同前缀兄弟剪，"
                        "实测剪掉 3,914 个真源码目录，见 R532）",
        "★排除的目录个数": 排除目录,
        "★排除了多少文件（未计入）": "**未统计** —— 排掉的目录没进去数（口径 92："
                            "允许没有 + 必须说明；这里明说没数）",
        "后缀分布（前 30）": dict(sorted(后缀计.items(), key=lambda x: -x[1])[:30]),
        "后缀种数": len(后缀计),
        "顶层段分布（前 30）": dict(sorted(顶层计.items(), key=lambda x: -x[1])[:30]),
        "★没有后缀的文件": 后缀计.get("(无)", 0),
        "耗时秒": round(time.time() - t0, 2),
        "★怎么重扫": "盘动了就再跑一次 `建索引(根)`；索引是**快照**（口径 367），带 `建于`",
        "★这一层不做什么": "**不解析内容、不建节点、不建边** —— 那是 ②「问」和 "
                     "③「看」的按需动作。全量预编译已被实测否掉（63k 文件 12 小时 0 产物）",
        "索引文件": str(档),
        "★索引放在哪": "**编排器状态区**，不在被索引的目录里 —— "
                  "实测 `D:\\tools` 是只读的 ⇒ 写进根里直接 `WinError 5`；"
                  "而且不该污染被索引的目录（`ORCH_STATE_DIR/知库/`）",
    }
    (出 / "知库.json").write_text(json.dumps(汇, ensure_ascii=False, indent=1), encoding="utf-8")
    打印(f"   知库·建索引 {根.name}：文件 {总数:,} · {总字节/1048576:.1f}MB · "
         f"后缀 {len(后缀计)} 种 · 无后缀 {后缀计.get('(无)', 0):,} · {time.time()-t0:.2f}s")
    return 汇


def _分词(问句: str) -> list[str]:
    """零依赖分词：英文/数字按词，中文按 **2-gram + 3-gram**（中文没空格）。

    ★ 为什么 2-gram 够：`点云的解析脚本` → `点云/云的/的解/解析/析脚/脚本`，
      只要有**一个** 2-gram 命中，就能把候选缩下来；精确排序交给内容阶段。
    """
    s = (问句 or "").strip()
    词 = re.findall(r"[A-Za-z_][A-Za-z0-9_]{1,}", s)
    汉 = re.findall(r"[\u4e00-\u9fff]+", s)
    for 段 in 汉:
        for n in (2, 3):
            for i in range(0, max(0, len(段) - n + 1)):
                词.append(段[i:i + n])
    return [w for w in dict.fromkeys(词) if len(w) >= 2]


def _像文本(b: bytes) -> bool:
    """有没有 NUL —— 二进制不扫（省时间，且不会假命中）。"""
    return b"\x00" not in b[:4096]


def _读一点(f: Path, 上限: int) -> bytes:
    """**有界读**：最多读 `上限` 字节，绝不把整个文件读进内存。

    ★ 为什么要单写一个（R534c）：`f.read_bytes()[:N]` 先读**全部**再切片 ——
      靶里就有 93.3MB 的 `ispc.exe`，一个 2MB 的用途会吃 93MB 内存。
      ★ 60 个候选里有 3 个大文件就够把一次「问」变成几百 MB 的内存峰值。
    """
    try:
        with open(f, "rb") as h:
            return h.read(上限)
    except OSError:
        return b""


def _选扫描器(根: Path) -> tuple[str | None, str]:
    """内容阶段用**系统已有的 grep**，不自己写（R309：用别人做好的做到更好）。

    ★★ 为什么（实测，R534d）：我第一版用 Python 逐文件 `in` 做全文扫 ——
      `D:\\tools`（10,362 文件 / 225MB）：**50.17 秒**，而且因为「小文件先扫」
      的排序，只覆盖了前 4MB **全是 0 字节垃圾** ⇒ 返回 3 个 **0 分的假命中**，
      而 `findstr /s /i /m /c:"excel"` 同一棵树 **3.2 秒找到 16 个真文件**。
      ⇒ **我在重新实现一个慢 15 倍、还漏结果的 grep。**
    ★ 每个扫描器带**它自己的局限**（口径 307：不许假装没有边界）：
      · `rg`        —— 最好；但这台机器上**没装**（实测）
      · `git grep`  —— 能处理中文；**只看 git 跟踪的文件**（新增/未跟踪的看不见）
      · `findstr`   —— 到处都有；**中文按 ANSI 匹配，UTF-8 中文词会漏**
    """
    if shutil.which("rg"):
        return "rg", "★ `rg` 全仓扫，词按字面匹配"
    if (根 / ".git").exists() and shutil.which("git"):
        return "git-grep", ("★ `git grep` —— **只看 git 跟踪的文件**："
                          "新增/未跟踪的文件它看不见（口径 92：边界要说出来）")
    if shutil.which("findstr"):
        return "findstr", ("★ `findstr` —— **中文按 ANSI 匹配** ⇒ UTF-8 中文词可能漏；"
                        "英文/拉丁词没问题")
    return None, ""


