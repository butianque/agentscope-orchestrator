"""登记缺口源 —— 让编排器**自己找到**项目自己登记的活。

## 为什么需要它（实测缺口，不是推测）

`unattended --auto` 的活源是 `autoengine.scan_all` → Lean 产物库 → 未闭合声明。
**实测该源为空**（2026-10-14 真跑）：

    ok      = False
    error   = 库内已无未闭合声明（全闭合）或索引为空

⇒ `--watch --auto` 会**立刻退出**（「无可拉件 ⇒ 停止」）
⇒ **「无人值守」在实测上根本不成立** —— 它只能由人打字给目标，那就退化成了
   「窗口会话单智能体 + 一层机器门」。

而项目**自己的源码里登记着真实缺口**（`【未核】` / `【登记待办】`），实测 11 处。
它们才是「有活可干」的源。

## ★ 但不许全派 —— 这一条是本库踩过的坑

登记项分**四类**，前三类**不派**，第四类派（★ R79 改了这条线）：

| 类别 | 判据 | 能否自动派 |
|:--|:--|:--|
| **需裁定** | 要人在**两个方案间选**（「二选一」「需与 C1 一起裁决」） | ❌ 不派 |
| **显式推迟** | 人**已经说了**这轮不做（「本轮不做」「暂不」） | ❌ 不派 |
| **调查类** | 先查清事实、**不改代码**（「生产可达性未逐点实测」） | ❌ 不派 |
| **可自动化 / 待试** | 有明确工程规格，**或**机器没认出来 | ✅ 派（**试一次**，由判据裁决） |

★★★★★ R79（2026-10-17 · 真跑跑到边界时抓出）：

  原来的表里第四类是「**未定** ⇒ 默认不派」。那句话把两件事**混成了一件**：

  > **「我没认出来」** 和 **「做不到」** 不是同一件事。

  前一句是**关于我的关键词表**的陈述，后一句是**关于那处缺口**的陈述。
  用前一句去推后一句，就是**拿枚举代替结构** —— 表里没有的词，
  在系统里就等于"这件事不存在"。而**现实不会因为我的表短而变小**。

  【真跑证据】跑到边界时，8 处登记项里：
    · 3 处是**人明确推迟**（「本轮不做」「属键宽问题，本轮不做」）⇒ 真不该派；
    · 2 处是**要人在方案间选**（「下一步须二选一：①…②…」）⇒ 真该人裁；
    · 2 处是**要先查事实**（「未逐点追可达性」「未逐点实测」）⇒ 派出去只能空转；
    · **2 处落在「未定」** —— 而它们**明明有活**：
        - 一处说「此处只修『同一个量两套实现』」← **这就是一件明确的活**；
        - 一处说「生产读者在种子列清空后恒返回空」← **这是一个可判的行为断言**。
      ⇒ 「未定」这个类别**替我把两件真活判成了死**，只因为词表里没有那个说法。

  ★ 修法**不是**去把词表加长（那是把枚举做得更勤快，病根不动）。
    修法是**取消「未定 ⇒ 不派」这条推论**：认不出来 ⇒ **派一次，让判据说话**。
    · 代价可控：`已派缺口` 已经保证**同一处一轮内只派一次**；
    · 失败也是信息：回执里记「试过、没闭合」，比"我猜它不能"**诚实得多**；
    · 真正该拦的三类（推迟 / 裁定 / 调查）**仍然拦着**，一个都没放松。

  ★ 与 R72「可用性是时间的函数」**同构**：
    **可派性不是文本的函数，是尝试的函数。** 判据才是唯一裁决者 —— 包括
    裁决"这处缺口机器干不了"。

## 诚实边界

· 本模块产出的是**候选**，不是判决。派发前仍应过人眼（或另加机器门）。
· 分类是**关键词启发式**，不是语义理解 ⇒ 会漏、会错。已在 `_selftest` 里用
  **反例**钉住「不得虚报」这一侧（宁可漏，不可乱派）。
  ★ R79 之后这条边界的**方向变了**：认不出来的不再被"宁可漏"吞掉，
  而是进「待试」—— 但**显式推迟/需裁定/调查类**仍然"宁可漏"。
· **已闭合的登记项不会被自动剔除** —— 例如 `涌现引擎/mod.rs:262` 那条已在
  2026-10-14 被真跑闭合，但源码里那行注释还在。`--gaps` 会把它列出来，
  需要靠人去删那行注释或加机器判据。**如实登记，不假装能自动判。**
"""
