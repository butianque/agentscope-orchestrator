def _相对(p: Path, 根: Path) -> str:
    """统一成 posix 风格的仓库相对路径（门的 key 用这个口径）。"""
    try:
        return p.relative_to(根).as_posix()
    except ValueError:
        return p.as_posix()


# ★ 声明形态（用于抽「必须逐字保留的键」）
_声明RE = re.compile(
    r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+|unsafe\s+|const\s+|extern\s+)*"
    r"(fn|struct|enum|trait|impl|mod|union|type|static|const)\s+"
    r"([A-Za-z_\u4e00-\u9fff][A-Za-z0-9_\u4e00-\u9fff]*)")


def 关键结构键(文件路径: Path, 行号: int, 扫描半径: int = 300) -> list[str]:
    """从目标行附近抽**必须逐字保留**的键（声明名）。返回去重后的名字列表。

    ★ 为什么必须由**机器**抽（2026-10-14 实测教训）：
      我原来的目标书只写「外加一条 whole_reading 门，要求关键结构键逐字仍在」——
      **没说是哪些键**。模型看不到整个大文件 ⇒ 只能**猜**键名 ⇒ 猜出不存在的符号
      ⇒ 那条门**恒红**（假红发生器），任务永远不可能收敛。
      实测症状：`src/模块甲/mod.rs@mod_rs_key_structures` 在轮 1 就红。
      ⇒ 键必须由**能读到真文件的一方**（机器）给出，模型只负责照抄。
    """
    try:
        行们 = 文件路径.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return []
    n = len(行们)
    if n == 0:
        return []
    行号 = max(1, min(int(行号), n))
    候选: list[tuple[int, str]] = []
    lo = max(1, 行号 - 扫描半径)
    hi = min(n, 行号 + 扫描半径)
    for i in range(lo, hi + 1):
        m = _声明RE.match(行们[i - 1])
        if m:
            候选.append((i, m.group(2)))
    if not 候选:
        return []
    # 优先取「声明在目标行**之后**」的（目标行常是该声明的文档注释）
    下 = [c for c in 候选 if c[0] >= 行号]
    上 = [c for c in 候选 if c[0] < 行号]
    排序 = sorted(下, key=lambda t: t[0] - 行号) + sorted(上, key=lambda t: 行号 - t[0])
    出: list[str] = []
    for _, 名 in 排序:
        if 名 not in 出:
            出.append(名)
        if len(出) >= 3:
            break
    return 出


def 扫描登记缺口(根: Path, roots=("src",), globs=("**/*.rs",), skip=()) -> list[dict]:
    """扫源码树里的登记缺口。

    返回 [{file, line, marker, text, 后续, 文件路径}]，按 (file, line) 排序。
    `后续` = 标记行之后最多 6 行的合并文本（分类要看它，规格常写在下一行）。
    """
    根 = Path(根)
    skip = tuple(skip or ())
    出: list[dict] = []
    见 = set()
    for r in roots:
        for g in globs:
            for p in sorted((根 / r).glob(g)):
                if not p.is_file():
                    continue
                if any(s and s in p.as_posix() for s in skip):
                    continue
                try:
                    文本 = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
                行们 = 文本.splitlines()
                for i, 行 in enumerate(行们):
                    # ★ 已闭合的登记**跳过**（否则同一处缺口被反复派发 ⇒ 空转）
                    if any(cm in 行 for cm in _已闭合标记):
                        continue
                    for m in _缺口标记:
                        if m not in 行:
                            continue
                        键 = (p.as_posix(), i + 1)
                        if 键 in 见:
                            break
                        见.add(键)
                        # ★ 后续窗口**必须在下一处登记处截断** —— 否则一条缺口会
                        #   继承邻居的信号（自检 #⑭ 实测抓到：一条「O(1) 账本」的
                        #   可派缺口，因为下一行是「须二选一」而被误判为需裁定）。
                        #   这是同一个病：判据读了它不该读的东西。
                        后续行: list[str] = []
                        for j in range(i + 1, min(i + 7, len(行们))):
                            if any(mm in 行们[j] for mm in _缺口标记):
                                break
                            if any(cm in 行们[j] for cm in _已闭合标记):
                                break
                            后续行.append(行们[j])
                        后续 = "\n".join(后续行)
                        出.append({
                            "file": _相对(p, 根),
                            "line": i + 1,
                            "marker": m,
                            "text": 行.strip(),
                            "后续": 后续,
                            "文件路径": str(p),
                        })
                        break
    出.sort(key=lambda d: (d["file"], d["line"]))
    return 出


