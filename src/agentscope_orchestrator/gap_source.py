    # ③ ★ R79：**认不出来 ⇒ 试一次**（不再是"默认不派"）。
    #   ★ 理由必须诚实说「我没认出来」，不许假装"它不可做"。
    return True, "待试", ("机器**没认出**明确工程规格 ⇒ 仍然派一次，"
                          "**由判据裁决**能不能闭合（「我没认出来」≠「做不到」）")


