# ★★★★★ R85：**结构缺口** —— 缺口源不能只认「人写下来的标记」
# ════════════════════════════════════════════════════════════════
# 【真缺陷（2026-10-17 夜 · 用户指出）】
#   编排器在真项目上找到 8 处缺口、全部闭合、报「可派 0」——
#   而 `判据_复用` 这类**写好了、有测试、但没有任何生产消费者**的判据
#   一个都没被找到。用户手工发现：「写好了，6 个调用点，没接到任何门上」。
#
# 【根因】`扫描登记缺口` 只认 `_缺口标记`（`【未核】`/`【待办】`/…）——
#   那全是**人写下来的**。⇒ 编排器只能找到「人已经写下来的缺口」，
#   **找不到「结构上存在、但没人写下来的缺口」**。
#   这是 R79 那个病的**更深处**：R79 修的是「认出来了却当做不到」，
#   这里连**认**都做不到 —— 因为它是拿词表去找，而缺口是**结构**。
#
# 【修法 · 全称机制，不枚举】
#   判据不是靠"哪个名字"识别的，是靠**引用结构**识别的：
#     一个 `pub fn` 是**对外承诺的接口**；
#     若它**没有任何生产消费者**（测试之外零引用），
#     那这个承诺是**空的** —— 它不裁决任何事，只是一段死代码。
#   ⇒ 机器算：每个 `pub fn <前缀>*` 的定义处，剥掉 `#[cfg(test)] mod` 后
#     数**生产引用**。零 ⇒ 结构缺口。
#
#   ★ 前缀**不写死**：它由**项目档案**声明（`orphan_api_prefixes`）。
#     机制是通用的（任何语言、任何项目），参数是项目自己的本体约定。
#     ⇒ 换一个项目，只要它声明自己的命名约定，这条就自动适用。

def _剥测试模块(源: str) -> str:
    """把 `#[cfg(test)] mod … { … }` 整块剥掉（按大括号配平）。

    ★ 为什么必须按**结构**剥，不按行剥：测试模块里也有大括号、字符串、注释，
      按行剥会把 `}` 当模块结束 ⇒ 后面整段生产代码被误删 ⇒ 假"零引用"。
    """
    import re as _re
    区间 = []
    for m in _re.finditer(r"#\[cfg\(test\)\]\s*(?:pub\s+)?mod\s+\w+\s*\{", 源):
        j, 深 = m.end(), 1
        while j < len(源) and 深:
            if 源[j] == "{":
                深 += 1
            elif 源[j] == "}":
                深 -= 1
            j += 1
        区间.append((m.start(), j))
    if not 区间:
        return 源
    出, 上 = [], 0
    for a, b in 区间:
        出.append(源[上:a])
        上 = b
    出.append(源[上:])
    return "".join(出)


def _剥注释与字面量(源: str) -> str:
    """把注释与字符串/字符字面量替换成空格（**保留换行**，行号不变）。

    ★ 为什么必须剥（R85d · 实测）：
      计数用的是 `名字` 出现，若**注释里**提到它就当成消费者 ⇒
      「`/// 供 判据_复用 在真产出上求值`」会被算作"有人用" ⇒ **漏报真缺口**。
      实测 `判据_复用` 测试外有 3 处出现，**全是注释** ——
      结论对，但那是**运气**：只要有人在注释里写 `判据_复用(...)`，它就会消失。

    ★ 与 `测试防假::去注释与字面量` 同一口径（那是对 Rust 的权威实现）；
      这里是本工具的**语言无关**版本，够用即可，不追求解析器级正确。
    """
    出 = list(源)
    i, n = 0, len(源)
    while i < n:
        c = 源[i]
        # 行注释：// …（含 ///、//!）
        if c == "/" and i + 1 < n and 源[i + 1] == "/":
            j = 源.find("\n", i)
            if j < 0:
                j = n
            for k in range(i, j):
                出[k] = " "
            i = j
            continue
        # 块注释：/* … */（Rust 可嵌套）
        if c == "/" and i + 1 < n and 源[i + 1] == "*":
            j, 深 = i + 2, 1
            while j < n and 深:
                if 源[j] == "/" and j + 1 < n and 源[j + 1] == "*":
                    深 += 1
                    j += 2
                    continue
                if 源[j] == "*" and j + 1 < n and 源[j + 1] == "/":
                    深 -= 1
                    j += 2
                    continue
                j += 1
            for k in range(i, min(j, n)):
                if 出[k] != "\n":
                    出[k] = " "
            i = j
            continue
        # 字符串字面量："…"（Rust 普通串，不处理 r#""#，够用）
        if c == '"':
            j = i + 1
            while j < n:
                if 源[j] == "\\":
                    j += 2
                    continue
                if 源[j] == '"':
                    j += 1
                    break
                j += 1
            for k in range(i, min(j, n)):
                if 出[k] != "\n":
                    出[k] = " "
            i = j
            continue
        # 字符字面量：'x'（避开生命周期 'a，只处理单字符闭合）
        if c == "'" and i + 2 < n and 源[i + 2] == "'":
            for k in range(i, i + 3):
                出[k] = " "
            i += 3
            continue
        i += 1
    return "".join(出)


def 扫描无消费者接口(根: Path, 前缀们, roots=("src",), globs=("**/*.rs",),
                     skip=()) -> list[dict]:
    """扫「声明了但没有任何生产消费者」的接口 —— **结构缺口**，不靠标记。

    参数：
      · `前缀们`：项目自己声明的命名约定（如 `("判据_",)`）。空 ⇒ 不做这项扫描。
        ★ 机制通用、参数由项目给 ⇒ 不把某个项目的词表写进通用工具。

    返回 [{file, line, marker, text, 后续, 文件路径, 结构缺口: True}]，
    形状与 `扫描登记缺口` **一致** ⇒ 下游 `判可派`/`转目标` 不必改就能接。
    """
    根 = Path(根)
    前缀们 = tuple(x for x in (前缀们 or ()) if x)
    if not 前缀们:
        return []
    skip = tuple(skip or ())
    源: dict[Path, str] = {}
    for r in roots:
        for g in globs:
            for p in sorted((根 / r).glob(g)):
                if not p.is_file() or any(s and s in p.as_posix() for s in skip):
                    continue
                try:
                    源[p] = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    continue
    # 全库的**生产净文本**：先剥测试模块，再剥注释与字面量
    # ★ R85d：只剥测试模块不够 —— 注释里的提及会被当成消费者（漏报真缺口）；
