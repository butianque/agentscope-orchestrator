"""R281：**通道体检表**——无人值守开工前，先拿到"每个通道为什么不能用"。

★ 为什么（真读数，2026-11-07）：
  上一轮把探活判准了（`200+error` 不再算活），但那份结论**只活在一次调用的
  异常信息里**。真正无人值守时，第一次失败往往发生在**跑到一半**：
  模型调到第 3 个文件才没通道，前面全白做。
  ⇒ 开工前必须有一张**结构化的体检表**：哪个通道、什么状态、什么原因、
    责任在谁（我配 key / 找权限 / 等上游）、该做什么。

★ 与 `doctor.check_channels` 的分工（不是重复）：
  · `doctor` 是**安装自检**：只查"能不能拿到 key"，**不联网**（装完就能跑）。
  · 本模块是**开工体检**：真探活，慢一点，但结论是"现在能不能用"。

★ 诚实边界：
  探活是**启发式**（发一次最小请求推断以后能不能用），不是保证。
  Router 有换槽与冷却，**真调用才是判据**。本模块给的是"开工前的最好判断"，
  并明确标出哪些是"没测到"而不是"测过不行"。
"""
from __future__ import annotations

from pathlib import Path

#: 死法 → (责任方, 该做什么)。★ 这三种死法的处理动作**完全不同**，
#: 混成一档会让人做错决定（上一轮的真教训）。
死法对策 = {
    "缺key": ("你", "设置对应的 *_API_KEY 环境变量（或在凭据文件里补上）"),
    "无权访问": ("你", "换一个有该分组的 key / 找管理员开权限（本地代码改不了）"),
    "上游异常": ("上游", "只能等；本地不重试（与 R166 一致：慢错重试拿不到新信息）"),
    "模型不存在": ("你", "通道配置里的模型 id 写错了，改配置"),
    "连不上": ("环境", "网络/端点不通；确认代理与 base_url"),
    "未探测": ("未知", "没测到，不等于不行"),
}


def 归类(说明: str) -> str:
    """把探活的说明文字归到上面那几档。**认不出就说认不出**，不硬塞。"""
    s = (说明 or "")
    low = s.lower()
    if "key not found" in low or "凭据不可读" in s:
        return "缺key"
    if "403" in s or "无权访问" in s:
        return "无权访问"
    if "上游服务异常" in s or "稍后重试" in s or "上游瞬态" in s:
        return "上游异常"
    if "404" in s or "model" in low and "not found" in low or "模型不存在" in s:
        return "模型不存在"
    if "timeout" in low or "timed out" in low or "超时" in s or "连接" in s:
        return "连不上"
    return "未探测"


def 体检(channel_name: str = "", timeout: float = 25.0) -> dict:
    """真探活一遍，返回结构化体检表。

    返回：
      {
        "能开工": bool,                  # 有没有**任何**一个可交给 Router 的槽
        "结论": "可开工"|"无通道可用",
        "逐通道": [{通道, 模型, 类, 死法, 责任, 该做什么, 原文}],
        "汇总": {死法: [通道名...]},
        "可交给router": [通道名...],
        "诚实边界": str,
      }
    """
    from agentscope_orchestrator import gateway as _gw

    # ★★★★★ R281c（真读数，2026-11-07）：**别猜常量的字面值。**
    #   我第一版写 `if 类 != "硬死"`，而 `gateway.硬死` 的值其实是 **`'dead'`**
    #   （`活='live'`、`硬死='dead'`、`读不到='unreadable'`，全是英文）。
    #   结果：**7 个 (通道,模型) 对里 6 个硬死，却全部被放进"可交给 router"**
    #   ⇒ 体检表说"有 5 个槽可试"，而实际只有 1 个。
    #   ⇒ 一律走常量，不写字面量。这样以后常量改名也不会静默失效。
    _活, _硬死, _读不到 = _gw.活, _gw.硬死, _gw.读不到

    逐: list[dict] = []
    try:
        通道们 = _gw.select_channels(channel_name)
    except Exception as e:                          # noqa: BLE001
        return {"能开工": False, "结论": "通道配置读不出来",
                "逐通道": [], "汇总": {}, "可交给router": [],
                "error": f"{type(e).__name__}: {e}",
                "诚实边界": "配置都读不出来 ⇒ 这不是'通道不行'，是**没配好**。"}

    # ★ 不复用 select_live_channels 的汇总，要**逐 (通道,模型) 对**的原文：
    #   同一个通道下不同模型的死法可能不同（实测 mf 两个模型都缺 key，
    #   而 dddddd 三个模型都 403——但形状上必须能分别记录）。
    能试: list[str] = []
    for ch in 通道们:
        名 = getattr(ch, "name", "?")
        模型们 = list(getattr(ch, "models", None) or [])
        if not 模型们:
            逐.append({"通道": 名, "模型": "（未配）", "类": _硬死,
                       "死法": "未探测", "责任": 死法对策["未探测"][0],
                       "该做什么": "通道里一个模型都没配", "原文": ""})
            continue
        for m in 模型们:
            类, why = _gw.probe_model(ch, m, timeout=timeout)
            死 = "" if 类 == _活 else 归类(why)
            责, 做 = 死法对策.get(死, 死法对策["未探测"])
            逐.append({"通道": 名, "模型": str(getattr(m, "id", m)), "类": 类,
                       "死法": 死, "责任": 责, "该做什么": 做,
                       "原文": str(why)[:300]})
            # ★ 与 select_live_channels 一致：**只有硬死才排除**，
            #   「读不到」仍然交给 Router 试（R18：一次抖动不该让整台机器拒跑）。
            if 类 != _硬死 and 名 not in 能试:
                能试.append(名)

    汇总: dict[str, list[str]] = {}
    for x in 逐:
        if x["死法"]:
            汇总.setdefault(x["死法"], [])
            if x["通道"] not in 汇总[x["死法"]]:
                汇总[x["死法"]].append(x["通道"])
    有活 = any(x["类"] == _活 for x in 逐)
    能试_sorted = sorted(能试)

    # ★ R281b（自查）：字段名必须**不夸大**。
    #   实测本机：`能开工=True` 而 `有确认活的通道=False`。
    #   按 R18 口径这没有错（读不到的仍交给 Router 试），但**名字会骗人**：
    #   调用方看到"能开工"就以为"现在真能跑"，而实际是"只有一次机会，且大概率是坏的"。
    #   ⇒ 拆成三档，名字各自说自己的事，不许一个字段承担两个意思。
    if 有活:
        键 = "可开工"
    elif 能试_sorted:
        键 = "仅剩未确认的槽"
    else:
        键 = "无通道可用"
    结论 = {
        "可开工": "可开工（有通道被确认是活的）",
        "仅剩未确认的槽": ("**没有通道被确认为活**；有 "
                        f"{len(能试_sorted)} 个「读不到」的槽会交给 Router 试一次 —— "
                        "这是兜底，不是可用的保证"),
        "无通道可用": "无通道可用（全部硬死）",
    }[键]
    return {
        "可开工": 键 == "可开工",
        "能开工": bool(能试_sorted),      # 保留：有槽可试；**但别把它当"能用"**
        "结论": 结论,
        "档": 键,
        "有确认活的通道": 有活,
        "逐通道": 逐,
        "汇总": 汇总,
        "可交给router": 能试_sorted,
        # ★★★★★ R294：**渠道是从哪来的，必须说出来。**
        #   用户当面指出：渠道原来是 `channels.yml` 里**硬编码**的快照，
        #   插件挂到任何一台 DSH 上都用那份旧快照 ⇒ DSH 换了 provider 本仓不知道。
        #   现在改成跟随宿主（`dsh_channels`）。但"跟随"这件事如果**看不出来**，
        #   调用方就无法判断"我看到的这 5 条到底是宿主的，还是包里那份过期快照"。
        #   ⇒ 把来源摊在体检结果里。
        "渠道来源": _渠道来源294(),
        "诚实边界": (
            "探活是**启发式**（发一次最小请求推断以后能不能用），不是保证；"
            "Router 有换槽与冷却，**真调用才是判据**。"
            "`未探测`档是「没测到」，**不等于**「测过不行」。"
            "责任方那一栏是给你分工用的：`你`=要你动手，`上游`=只能等，"
            "`环境`=查网络/代理。"
            "`渠道来源` 说明这份通道表是**跟随宿主 DSH** 还是包里那份静态快照 —— "
            "后者可能已过期。"
        ),
    }


def _渠道来源294() -> dict:
    """渠道表的来源（宿主 DSH / 静态快照），给调用方一个能判断的读数。"""
    try:
        from . import dsh_channels as _dc
        _宿 = _dc.宿主线索引()
        _r = _dc.发现渠道()
        return {
            "在dsh里": _宿.get("在dsh里", False),
            "profile": _宿.get("profile", ""),
            "跟随宿主": bool(_r.get("ok")),
            "宿主声明": [c["name"] for c in (_r.get("渠道") or [])],
            "读自": _r.get("来源", ""),
            "没找到的原因": _r.get("没找到的原因", ""),
            "说明": ("渠道表**跟随宿主 DSH**（同名以宿主为准 —— DSH 是活的，"
                    "包里那份是快照）" if _r.get("ok") else
                    "**没有跟随宿主**，用的是包里/目录下的静态快照 —— 它可能已过期"),
        }
    except Exception as e:                          # noqa: BLE001
        return {"在dsh里": False, "跟随宿主": False,
                "说明": f"来源探测自身异常（≈没测到，不等于没有）：{type(e).__name__}"}


def 体检摘要(表: dict) -> str:
    """把体检表压成一段人可读的话（MCP 工具返回时用）。"""
    行 = [f"通道体检：{表.get('结论')}（可交给 router：{表.get('可交给router') or '无'}）"]
    for 死, 通道 in (表.get("汇总") or {}).items():
        _, 做 = 死法对策.get(死, ("?", "?"))
        行.append(f"  · {死}〔{len(通道)} 个：{', '.join(通道)}〕→ {做}")
    return "\n".join(行)
