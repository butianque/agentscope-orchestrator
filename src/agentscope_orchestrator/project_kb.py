def _文路径(条id: str) -> Path:
    return 库根() / "items" / f"{re.sub(r'[^0-9A-Za-z_\-一-鿿]+', '_', 条id)}.md"


def _解析_文(文: str) -> dict | None:
    m = _FM.match((文 or "").strip() + "\n")
    if not m:
        return None
    头, 正文 = m.group(1), m.group(2)
    条: dict = {}
    for 行 in 头.splitlines():
        if ":" not in 行:
            continue
        k, v = 行.split(":", 1)
        k, v = k.strip(), v.strip()
        if not k:
            continue
        if v.startswith("[") or v.startswith('"'):
            try:
                条[k] = json.loads(v)
                continue
            except Exception:                    # noqa: BLE001 当普通字符串
                pass
        条[k] = v
    条["正文"] = 正文.strip()
    return 条


def _格式(条: dict) -> str:
    头 = []
    for k in ("id", "类别", "强度", "来源", "等级", "范围", "版本"):
        if k not in 条:
            continue
        v = 条[k]
        头.append(f"{k}: {json.dumps(v, ensure_ascii=False) if isinstance(v, (list, dict)) else v}")
    头 += [f"更新: {条.get('更新') or time.strftime('%Y-%m-%dT%H:%M:%S')}"]
    return "---\n" + "\n".join(头) + "\n---\n" + (条.get("正文") or "") + "\n"


def 写(条: dict, *, 覆盖: bool = False) -> dict:
    """写一条知识。默认**不覆盖**已存在的 id（要改请用 `改`，这样版本与变更日志才不会丢）。"""
    if not 条.get("id"):
        raise ValueError("必须给 id")
    if 条.get("类别") not in 类别们:
        raise ValueError(f"类别必须是 {类别们} 之一")
    if 条.get("强度") and 条["强度"] not in 强度们:
        raise ValueError(f"强度必须是 {强度们} 之一")
    if 条.get("等级") and 条["等级"] not in 等级们:
        raise ValueError(f"等级必须是 {等级们} 之一")
    p = _文路径(条["id"])
    if p.exists() and not 覆盖:
        raise FileExistsError(f"已存在 {条['id']}；要改请用 改()，要覆盖显式传 覆盖=True")
    p.parent.mkdir(parents=True, exist_ok=True)
    条.setdefault("版本", 1)
    条["更新"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    p.write_text(_格式(条), encoding="utf-8")
    重建索引()
    return 条


def 改(条id: str, **字段) -> dict:
    """**人改一条知识**：自增版本，把变化写进 changelog（谁改的、何时、改了什么）。"""
    p = _文路径(条id)
    if not p.exists():
        raise FileNotFoundError(f"没有 {条id}")
    旧 = _解析_文(p.read_text(encoding="utf-8")) or {}
    新 = dict(旧)
    变化 = {k: v for k, v in 字段.items() if k not in ("版本", "更新", "变更")}
    新.update(变化)
    新["id"] = 条id
    新["版本"] = int(旧.get("版本") or 1) + 1
    新["更新"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    日志 = list(旧.get("变更") or [])
    日志.append({"版本": 新["版本"], "时间": 新["更新"],
                 "改": {k: {"旧": 旧.get(k), "新": v} for k, v in 变化.items()}})
    新["变更"] = 日志
    p.write_text(_格式(新), encoding="utf-8")
    重建索引()
    return 新


def 删(条id: str) -> bool:
    p = _文路径(条id)
    if not p.exists():
        return False
    p.unlink()
    重建索引()
    return True


