# ══════════════════════════════════════════════════════════════════════════════
# 检索：把「整串子串匹配」换成「分词 + 覆盖度打分」
#
# ★★★★★ 2026-11-03 真事故（本模块最值钱的一段注释，别删）：
#   症状：外挂知识库**看起来在接**，实际**结构上查不出来**，于是"没效果"。
#   两个缺陷叠加：
#     D1 库是 0 条 ⇒ `注入()` 返回空串（功能完整但空转）；
#     D2 检索算法错：`查(关键词=…)` 原来是 `关键词.lower() not in 文 ⇒ 跳过`
#        ——**整串子串匹配**；而唯一真调用方传进来的是 `证据[-300:]`
#        （一整段红门证据，几百字）。**三百字的串不可能整段出现在一条 60 字的规则里**
#        ⇒ 命中数恒为 0。
#        更糟的是 `fixloop.py` 连关键词都没传，注入的是**排序后的固定 700 字前缀**
#        —— 与当前任务毫无关系。"随时查"于是退化成"每次给你同一段"。
#
#   ⇒ 修法要点（三条，缺一条就等于没修）：
#     ① **分词**：中文没有空格，必须自己切；本仓不许引依赖（离线安装是硬要求），
#        所以用 **2-gram / 3-gram**。ASCII 按词切，并把下划线/点/横线再拆一层
#        （`PYTHONIOENCODING` 与 `IOENCODING` 都该被认出来）。
#     ② **按覆盖度打分**：规则短（几十字）、查询长（几百字），
#        所以量的是「**这条规则有多少被查询覆盖**」= |命中| / |规则词元|，
#        不是「查询有多少被覆盖」。后者会让长证据永远压过短证据。
#     ③ **设门槛**：命中至少 2 个不同词元才算相关 ——
#        单个公共 bigram（如"编码"）就命中的话，等于没过滤。
# ══════════════════════════════════════════════════════════════════════════════

# 高频虚词/祈使词的 bigram 碰撞没信息量，剔掉（保留它们在正文里，只是不参与打分）
_停用元 = frozenset({
    "必须", "建议", "禁止", "一律", "不许", "不得", "不要", "可以", "如果", "否则",
    "的时", "时候", "这个", "那个", "我们", "你们", "它们", "因为", "所以", "但是",
    "就是", "不是", "一个", "已经", "还是", "或者", "以及", "并且", "而且",
})


def _切词(文: str) -> set:
    """把文本切成可比对的**词元集合**（ASCII 词 + 中文 2/3-gram）。"""
    文 = (文 or "").lower()
    if not 文:
        return set()
    出: set = set()
    # ASCII / 数字：先整词（保留 `_`/`.`/`-` 以便认出完整标识符），再拆一层子词
    for w in re.findall(r"[a-z0-9_\-\.]{2,}", 文):
        出.add(w)
        for 片 in re.split(r"[_\-\.]+", w):
            if len(片) >= 3:          # 两个字母的子词噪声太大
                出.add(片)
    # 中文：连续汉字段取 2-gram 与 3-gram
    for 段 in re.findall(r"[\u4e00-\u9fff]+", 文):
        for n in (2, 3):
            for i in range(len(段) - n + 1):
                出.add(段[i:i + n])
    return 出 - _停用元


def _条词元(条: dict) -> set:
    """一条知识的可比对词元（含 id 与全部非正文字段 —— 范围/类别也该参与匹配）。"""
    文 = (str(条.get("id", "")) + " " + str(条.get("正文") or "") + " " +
          json.dumps({k: v for k, v in 条.items() if k != "正文"}, ensure_ascii=False))
    return _切词(文)


def _相关(条: dict, 关键词: str, 问元: set | None = None) -> tuple[float, int]:
    """返回 (相关分, 命中词元数)。

    · 关键词是**整条命中**（旧行为，短查询走这条路）⇒ 分 1.0；
    · 否则按「规则被查询覆盖的比例」打分。
    """
    关 = (关键词 or "").strip()
    if not 关:
        return 0.0, 0
    # ① 旧行为优先：短查询整串命中，给满分（保住"人输入一个词就能查到"的手感）
    文 = (str(条.get("id", "")) + " " + str(条.get("正文") or "") + " " +
          json.dumps({k: v for k, v in 条.items() if k != "正文"}, ensure_ascii=False)).lower()
    if 关.lower() in 文:
        return 1.0, 999
    # ② 分词打分
    问 = 问元 if 问元 is not None else _切词(关)
    if not 问:
        return 0.0, 0
    条元 = _条词元(条)
    if not 条元:
        return 0.0, 0
    命中 = 问 & 条元
    if len(命中) < 2:                 # ★ 门槛：单个公共词元命中不算相关
        return 0.0, len(命中)
    return len(命中) / max(1, len(条元)), len(命中)


def 查(*, 关键词: str = "", 类别: str = "", 范围: str = "", 上限: int = 0) -> list[dict]:
    项 = _读索引().get("项") or []
    出 = []
    问元 = _切词(关键词) if 关键词 else None
    for t in 项:
        if 类别 and t.get("类别") != 类别:
            continue
        if 范围 and not 范围命中(t, 范围):
            continue
        if 关键词:
            分, 命 = _相关(t, 关键词, 问元)
            if 分 <= 0:
                continue
            出.append({**t, "_相关分": round(分, 4), "_命中元": 命})
        else:
            出.append(t)
    if 关键词:
        # 相关度优先；同分按 id 稳定排序（否则每次注入块会在同分条目间跳动）
        出.sort(key=lambda t: (-t.get("_相关分", 0.0), str(t.get("id", ""))))
    return 出[:上限] if 上限 else 出


def 冲突() -> list[dict]:
    """冲突**报出来**：同 id 多文件、同 (类别,强度,范围) 下"必须 A"与"禁止 A"同时存在。"""
    项 = _读索引().get("项") or []
    出道: list[dict] = []
    ids: dict[str, int] = {}
    for t in 项:
        ids[t.get("id", "")] = ids.get(t.get("id", ""), 0) + 1
    for i, c in ids.items():
        if c > 1:
            出道.append({"型": "重复id", "id": i, "数": c})
    必须 = [t for t in 项 if t.get("强度") == "必须"]
    禁止 = [t for t in 项 if t.get("强度") == "禁止"]
    for a in 必须:
        for b in 禁止:
            if a.get("id") == b.get("id"):
                continue
            A, B = (a.get("正文") or "").strip(), (b.get("正文") or "").strip()
            if A and A == B and json.dumps(a.get("范围"), ensure_ascii=False) == json.dumps(
                    b.get("范围"), ensure_ascii=False):
                出道.append({"型": "必须与禁止同文", "id": [a.get("id"), b.get("id")], "正文": A})
    return 出道


def 命中(关键词: str, *, 最低分: float = 0.35, 最少词元: int = 3) -> tuple[bool, str, dict]:
    """判断"知识库对这个问题**到底有没有答案**"，返回 `(够不够格, 说明, 详情)`。

    ## 为什么必须有这个函数（`注入` 给不出这个答案）

    `注入` 的口径是**宁滥勿缺**：只要命中 ≥2 个词元就往里塞，按相关度排前面。
    对"修复时把口径递给模型"这是**对的** —— 多给一条无关的，最多浪费几个 token。

    但"分工线"要问的是**另一个问题**：
        *这里到底有没有能答这个问题的知识？有 ⇒ 别劳烦 LLM；没有 ⇒ 只能交给 LLM。*
    拿 `注入` 的非空当"有答案"，会**把无关知识误判成答案** ⇒
    分工线的第二档会吞掉所有问题，**永远不会走到"交给 LLM"那一档**，
    于是**盲区永远记不下来**，整套"一边错一边加门"就断了。

    ★ 这是 2026-11-03 实测抓到的（新写的分工线判据当场判红 6 项）：
      我拿一段**纯属虚构**的症状去问，`注入` 照样返回了一段知识（命中了
      两个常见词元），于是分工线判"知识库命中 ⇒ 照知识做"，**逻辑上把 LLM
      永远排除在外**。判据把这件事摆在了明面上。

    ## 判据（两条都要过）

    · `最低分`：相关分（命中词元数 / 条目词元数）≥ 0.35 —— 即**这条规则有
      三成以上被问题覆盖**。门槛不能只看命中数：一条很长的规则命中 3 个词元
      可能只覆盖 10%，那不算答案。
    · `最少词元`：命中 **≥3 个不同词元**。2 个是 `注入` 的门槛（够用来排序），
      但**不够用来断言"这就是答案"**（两个公共词常常是"编码""报错"这种大路货）。

    ★ 两条一起用的理由：**单一判据都能被骗**。
      只看分：短条目命中 2 个词元分就很高；
      只看词元数：长条目命中的全是常用词。
    """
    if not (关键词 or "").strip():
        return False, "没给关键词 ⇒ 无法判断知识库有没有答案", {}
    try:
        条们 = [t for t in 查(关键词=关键词)
                if t.get("类别") in ("规则", "禁则", "约定", "术语", "事实")]
    except Exception as e:                       # noqa: BLE001
        return False, f"知识库读不了（{type(e).__name__}: {e}）⇒ 不能断言有没有答案", {}
    合 = [t for t in 条们
          if float(t.get("_相关分") or 0.0) >= 最低分
          and int(t.get("_命中元") or 0) >= 最少词元]
    if not 合:
        顶 = max(条们, key=lambda t: float(t.get("_相关分") or 0.0), default=None)
        详 = (f"最高分 {顶.get('_相关分')}（命中 {顶.get('_命中元')} 词元，id={顶.get('id')}）"
              if 顶 else "一条都没命中")
        return False, (f"知识库**没有够格的答案**（要求 分≥{最低分} 且 词元≥{最少词元}；{详}）"
                       f" ⇒ 别拿无关知识冒充答案"), {"条数": len(条们), "最高": 详}
    顶 = 合[0]
    return True, (f"命中 {len(合)} 条够格（最高分 {顶.get('_相关分')} · "
                  f"命中 {顶.get('_命中元')} 词元 · id={顶.get('id')}）"), {
        "条数": len(合), "最高分": 顶.get("_相关分"), "条目": 顶.get("id")}


def 注入(*, 关键词: str = "", 范围: str = "", 上限字: int = 700) -> str:
    """生成**带优先级声明**的提示块。宁可少注入，也不截半句规则。

    ★ 排序键的次序是**有讲究的**（2026-11-03 改）：
      给了关键词 ⇒ **相关度第一**，类别/强度只用于同分时定序。
      原来把类别/强度放第一 ⇒ 无论任务是什么，注入的都是同一段固定前缀，
      "检索"名存实亡（那正是"外挂知识没效果"的直接原因）。
      没给关键词 ⇒ 保持"按类别/强度把口径整体交出去"的旧语义（人工查看用）。
    """
    条们 = [t for t in 查(关键词=关键词, 范围=范围)
            if t.get("类别") in ("规则", "禁则", "约定", "术语", "事实")]
    if not 条们:
        return ""
    # 规则/禁则优先，其次约定/术语，最后事实；同级按强度：必须 > 禁止 > 建议
    权 = {"规则": 0, "禁则": 0, "约定": 1, "术语": 1, "事实": 2}
    强权 = {"必须": 0, "禁止": 1, "建议": 2}
    if 关键词:
        条们.sort(key=lambda t: (-float(t.get("_相关分") or 0.0),
                                权.get(t.get("类别"), 3),
                                强权.get(t.get("强度"), 3),
                                str(t.get("id", ""))))
    else:
        条们.sort(key=lambda t: (权.get(t.get("类别"), 3),
                                强权.get(t.get("强度"), 3),
                                str(t.get("id", ""))))
    头 = "## 项目知识库（**优先于你的训练先验**；与你的常识冲突时按这里做，并回报冲突）"
    if 关键词 and 条们:
        头 += f"\n（已按当前任务的相关度检索，共命中 {len(条们)} 条，按相关度排列）"
    行 = [头]
    已用 = len(头)
    for t in 条们:
        尾 = f"（{t.get('id')}·v{t.get('版本', 1)}·{t.get('等级', 'SOLID')}）"
        s = f"- [{t.get('类别')}/{t.get('强度') or '建议'}] {(t.get('正文') or '').strip()} {尾}"
        if 已用 + len(s) > 上限字:
            break
        行.append(s)
        已用 += len(s)
    return "\n".join(行) if len(行) > 1 else ""


def _模式(条: dict) -> str | None:
    """从正文取"可 grep 的模式"：优先反引号里的原文；没有反引号就剥掉祈使词取到第一个分句。

    ★ 为什么允许无反引号：真人写规则时经常直接写"禁止 import numpy"，不会加反引号；
      要求反引号等于把"人随手写就能变门"这件事做废。但**有反引号优先**，避免整句被当正则。

    ★★★★★ 2026-11-03：**必须 `re.escape()`**（真缺陷，判据逮到的）。

      这里抽出来的是**人的自然语言片断**，而 `gate_spec` 把它当**正则**跑
      （`re.findall(p, text)`）。两边对不上的后果是**静默假绿**：

        规则：禁止 `if abs(x)>=1` 这种写法
        ⇒ 抽出的模式：`if abs(x)>=1`
        ⇒ 当正则跑：`(x)` 被当成**分组** ⇒ 实际匹配 `if absx>=1` 之类
        ⇒ 产物里明明写着 `if abs(x)>=1`，门却**永远绿**

      实测（2026-11-03）：惯性产物与合规产物**都过门**，判据完全失去区分力 ——
      而门表里那条"禁止自动切单位"看起来**管得严严的**。

      ⇒ 口径：**人的字面 ≠ 机器的正则**。人写的模式要 "字面地" 匹配，
        所以出这道门之前必须 `re.escape`。

    ★★★★★ 同日的**第二个**真缺陷：**极性会反**（判据逮到的）。

      规则：`刻度一律用 kHz，禁止按数量级自动切换 Hz/MHz`（类别=规则, 强度=禁止）
      ⇒ 旧 `_模式` 取反引号里**第一个**片断 ⇒ `kHz`
      ⇒ 而极性来自**条目整条**的"禁止" ⇒ 门变成 **"禁止出现 kHz"**
      ⇒ 语义**完全反了**，而且后果荒唐到一眼可见：
        **合规产物（正是写 kHz 的那种）被判红**，而它本该是唯一合格的写法。

      ⇒ 口径：**一条规则里的模式可能不是一个，极性也可能不是一个。**
        "必须 A 且禁止 B" 是**一条**规则，但它需要**两条门**（一 required 一 forbidden）。
        ⇒ 按模式**就近的祈使词**定极性，不再用整个条目的极性套所有模式。

    ★ 返回 `(必须的模式们, 禁止的模式们)` —— 两列分开，极性不再共享。
    """
    return _正反模式(条)


def _正反模式(条: dict) -> tuple[list[str], list[str]]:
    """把正文拆成 `(该出现的, 不该出现的)` 两列模式。

    ★ 极性按**就近原则**定（2026-11-03 修「极性反转」真缺陷）：

      `刻度一律用 kHz，禁止按数量级自动切换 Hz/MHz`
        · `kHz` 前面最近的祈使词是「一律」 ⇒ 该出现
        · `Hz/MHz` 前面最近的是「禁止」 ⇒ 不该出现

      ⇒ 一条规则拆成两条门，各管各的极性。**不再拿整条条目的极性套所有模式。**

      ★ 从旧行为到新行为的差别不是"更准了一点"，是**纠正了一个反的语义** ——
        旧行为在**合规产物上判红**，那比不判还坏：它会让"唯一正确的写法"被门拦住。

    ★★★★★ 2026-11-04（第229轮）：**"没有祈使词"不许猜 —— 一律不转门。**

      ## 第 226 轮修的那一半，另一半还在

      第 226 轮把"整条条目一个极性"改成"按就近祈使词"，但**没祈使词时**仍然
      退回条目级极性：

      ```python
      if 最近 is None:
          if 类别 == "禁则" or 强度 == "禁止": 不该有
          else: 该有          # ← **这一句就是猜**
      ```

      ## 实测：这一猜，把「症状」整段猜成了「要求」

      真库 16 条规则 → 98 道门，**极性分布实测**：

      ```
      Counter({'grep_required': 97, 'grep_forbidden': 1})
      ```

      **97/98 都是"产物里必须出现"** —— 而知识库几乎全是禁令。
      最荒唐的一条：规则 `口径-通用工具源码不许出现专有名词`（名字里就写着"不许出现"）
      产出了一道 `grep_required` 门，**要求产物里出现它自己的症状**
      `工具在无档案环境下导入失败`。

      ⇒ 后果分两层，一层比一层坏：

        · **门是反的**：带病产物**恰好满足**它，修好的产物反而红 ——
          这比没有门坏得多（它会把正确的写法拦住）。
        · **它同时解释了第224轮那个悬案**：「门集 10 条里 8 条无关门
          ⇒ **任何产物都必然红**」—— 根因就是这 36 条靠猜归堆的模式。

      ## 为什么改法是"不转门"而不是"猜得更准"

      实测：正文里的片断分两拨 ——

      ```
      有祈使词（极性有据）:  必须 29 条 + 禁止 1 条 = 30
      没有祈使词（极性靠猜）: 36
      ```

      36 条无据的，实测全是**症状/证据**：

        `PermissionError` / `WinError 5` / `E:\\Temp` / `cargo test` / `.tmp` /
        `want staged, got error` / `分类=None` / `precondition` / `regression_parity`

      **这些没有一条是该"必须出现"的。**

      ⇒ 而且"无据就不转"这条**顺带把"症状区 vs 修法区"也分对了**：
        人写修法时会带祈使词（`一律覆盖赋值（…）`），写症状时不会。
        **不需要去猜小标题，机制自己落在正确的边界上。**

      ★ 口径：**「判不了」永远不等于「正常」，也永远不等于「随便挑一边」。**
        极性判不了 ⇒ 不产门 + 如实记进 `未转门()` ——
        **宁可少给一道门，不许给一道方向反的门。**
    """
    正文 = (条.get("正文") or "").strip()
    if not 正文:
        return [], []
    # ★★★ 极性判定的**第一步必须是剥掉 markdown 强调符**。
    #
    #   真事故（2026-11-03，修了一版仍然反）：正文写的是
    #     `刻度一律用 `kHz`，**禁止**按数量级自动切换 `Hz/MHz``
    #   而"禁止"前面是 `**` 不是行首 ⇒ `^(禁止|…)` **匹配不到**
    #   ⇒ 掉进"极性未知"分支 ⇒ 兜底用条目级极性（这条条目强度=禁止）
    #   ⇒ `kHz` 被判成"禁止出现" ⇒ **语义仍然反的**。
    #
    #   ⇒ 口径：**判定之前先把"给人看的装饰"剥掉**。
    #     markdown 强调符（`*` `_` 与反引号里的内容）是排版，不是语义；
    #     让排版符号参与语义判定，就会得到"看起来对、其实反"的结论。
    正 = re.sub(r"[*_]+", "", 正文)
    # ★ 极性按**就近原则**定：看每个片断**前面最近**的那个祈使词。
    #
    #   为什么不能"看段首"（第二版仍然错的地方）：
    #     `刻度一律用 `kHz`` → 段首是"刻度"，不是"一律" ⇒ `^一律` 匹配不到
    #     ⇒ 又掉进"未知"分支 ⇒ 又出错。
    #   人写中文时祈使词**不一定在句首**（"刻度一律用 kHz" 就是），
    #   所以判定必须**按位置就近**，不能按行首。
    #
    #   ★ 2026-11-04：否定祈使词补了几个真实写法（`永不用` / `严禁` / `别`）——
    #     实测正文里 `**永不用 `setdefault`**` 这种写法，原来匹配不到任何祈使词
    #     ⇒ 会被"不转门"丢掉，而它**恰恰是一条该保留的禁令**。
    祈使 = r"(禁止|不许|不得|不能|不要|切勿|严禁|不准|永不|永不用|别|必须|一律|请|要)"
    # ★★★★★ 2026-11-04（第229轮）：**祈使词只管自己那一句 —— 不许跨句。**
    #
    #   实测残留（上面那版修完仍然错的地方）：`跑一个` / `print` / `setdefault`
    #   还是被判成了"必须出现"。查为什么 —— **不是极性规则错，是"就近"没有距离上限**：
    #
    #     正文 …`判据的运行环境必须由判据自己决定`。…。三轮实测（…）：① …；② …；③ 套件里…根因是 `跑一个` 用了 …
    #                                                      ↑ 这个 `必须` 隔了 3 个句号，
    #                                                        却仍然"就近"管到了 `跑一个`
    #
    #   ⇒ 口径：**一个祈使词管的是它所在的那一句。** 句子边界 = `。；！？` 与换行。
    #     （`，` **不算**边界 —— 真人写规则就是 `刻度一律用 kHz，禁止…`，
    #      切在逗号上会把 `一律` 和 `kHz` 拆开，那正好是第226轮修的那个坑。）
    界 = r"[。；！？\n]"
    该有: list[str] = []
    不该有: list[str] = []
    片们 = list(re.finditer(r"`([^`]+)`", 正))
    if not 片们:
        return _正反模式_无引号(条, 正)
    for m in 片们:
        片 = _为字面(m.group(1).strip())
        if not 片:
            continue
        # 看这个片断**前面同一句里**最近的祈使词（不含片断自身）
        前 = 正[:m.start()]
        # ★ 切到本句开头：最后一个句子边界之后才是"同一句"
        切 = [mm.end() for mm in re.finditer(界, 前)]
        同句 = 前[切[-1]:] if 切 else 前
        最近 = None
        for mm in re.finditer(祈使, 同句):
            最近 = mm.group(1)
        if 最近 is None:
            # ★★★ 极性未知 ⇒ **不猜、不产门**，只如实记下来（第229轮，理由见 docstring）。
            _极性无据.append((str(条.get("id") or ""), m.group(1).strip()[:60]))
            continue
        if 最近 in ("禁止", "不许", "不得", "不能", "不要", "切勿",
                    "严禁", "不准", "永不", "永不用", "别"):
            不该有.append(片)
        else:
            该有.append(片)
    return list(dict.fromkeys(该有)), list(dict.fromkeys(不该有))


def _正反模式_无引号(条: dict, 正: str) -> tuple[list[str], list[str]]:
    """正文里没有反引号时的兜底：剥掉祈使词，取**最后一个祈使词之后**的片断。

    ★ 取"最后一个"而不是"第一个"：中文规则句常写成
      `提交前必须跑 tools/ci.py，禁止直接 git push` ——
      极性跟着**离它最近**的祈使词，所以从尾部找才是对的。
    """
    if (条.get("类别") == "禁则") or (条.get("强度") == "禁止"):
        # 整条是禁则 ⇒ 抓"禁止"后面的东西
        m = list(re.finditer(r"(?:禁止|不许|不得|不能|不要|切勿|严禁|不准|永不)\s*", 正))
        if m:
            尾 = 正[m[-1].end():].split("，")[0].split("；")[0].split("。")[0].strip()
            return [], ([_为字面(尾[:60])] if 尾 else [])
    m = list(re.finditer(r"(?:必须|一律|请|要)\s*", 正))
    if m:
        尾 = 正[m[-1].end():].split("，")[0].split("；")[0].split("。")[0].strip()
        return ([_为字面(尾[:60])] if 尾 else []), []
    # ★★★★★ 2026-11-04（第229轮）：**连祈使词都没有 ⇒ 不猜、不产门。**
    #
    #   原来这里按条目级极性兜底（禁则 ⇒ 禁止，否则 ⇒ 必须）——
    #   **同一句"猜"的第二处**（另一处在 `_正反模式`，两处都改了）。
    #   实测后果见 `_正反模式` 的 docstring：97/98 道门都成了 `grep_required`。
    #
    #   整条正文没有祈使词 ⇒ 这段文字**只是在描述现象**（一个案例、一段证据），
    #   它当然可以描述坏现象 —— 把它当"必须出现"就是把症状当要求。
    _极性无据.append((str(条.get("id") or ""), 正[:60]))
    return [], []


def _为字面(模式: str) -> str:
    """把"人写的片断"变成**字面匹配**的正则。

    ★ 只在它**不是故意写的正则**时才转义 —— 判据是"有没有正则特征的元字符组合"：
      人写 `if abs(x)>=1` 是想匹配这段字面；人写 `\\btodo!` 是想用正则。
      两者的分界不好自动判，所以**从严选字面**（默认字面，想用正则的人自己写清楚）。

      本条口径的来源与另一处同族：**别用启发式去猜"哪些用法是合法的"** ——
      那样既漏又误伤。这里改成只认一个明确信号：**片断里出现 `re.escape` 后
      仍能匹配的普通字面**（即：只要含元字符就转义）。
    """
    模式 = (模式 or "").strip()
    if not 模式:
        return ""
    return re.escape(模式)


def 门(条们: list[dict] | None = None, 仓=None, *, 文件: str = "",
       上限门: int = 200) -> list[dict]:
    """把可机判的规则转成**判据门**（这才是硬约束；注入只是提示）。

    ★ 形状约束是被真跑纠正的：`gate_spec` 的 grep 门 `in` 是**单个文件路径**，
      不是 glob 列表。首版把范围 glob 原样塞进 `in` ⇒ 因由是
      `门规格非法|读不到|in=*.py`，看着像"规则没被遵守"，其实门压根没读文件。
      ⇒ 给了 `仓` 就把范围 glob 展开成**具体文件**，一条规则 × 一个文件一条门。

    ★★★ 2026-11-03 补两件事（都是真事故逼出来的）：

    **一、`文件=` 参数：只要**那一个**文件适用的门。**

    实测事故：拿一批规则（其中八条的口径跟"刻度"毫无关系）转门，去判一个刻度文件 ⇒
    **门集 10 条里 8 条无关门**（要求产物里出现 `precondition`、`分类=None`、
    `regression_parity` 这些字面）⇒ **任何产物都必然红**，而且**惯性产物和合规产物
    红得一模一样** —— 判据完全失去区分力。

    ★ 这是"门墙"最危险的失败方式：**门数很多、看起来管得很严，
      实际全部无关 ⇒ 永远红 ⇒ 谁也不看判据了。**
      ⇒ 有了 `文件` 就只保留**范围真的命中这个文件**的门。

    **二、没写范围的规则不许扩到 `**/*`。**

    第一版对空范围用 `范们 or ["**/*"]` —— 看着"兜底很全"，
    实际是**一条规则 × 全仓每个文件**一条门 ⇒ 几百条门里绝大多数是噪声。
    ⇒ 改为：**没写范围的规则不转门**（返回时记在因由里），
      因为"不知道它管哪些文件"本身就意味着不可机判 —— 不可判的东西转成门只是噪声。
    """
    出: list[dict] = []
    没范围的: list[str] = []
    略过的: list[str] = []
    # ★ 2026-11-04：每次调用重算 —— 不清就会把上一次的"无据片断"累进来，
    #   而 `未转门()` 的口径是"**上一次** `门()` 调用"（同一个模块级快照）。
    _极性无据.clear()
    _必有多文件.clear()
    _裸词禁令.clear()
    for t in (条们 if 条们 is not None else (查(类别="禁则") + 查(类别="规则"))):
        该有, 不该有 = _模式(t)
        if not 该有 and not 不该有:
            略过的.append(str(t.get("id")))      # 转不出模式 ⇒ 不可机判（如实记下）
            continue
        范 = t.get("范围") or []
        范们 = [str(x) for x in 范] if isinstance(范, list) else [str(范)]
        if not 范们:
            # ★ 没有范围 ⇒ 不转门（理由见 docstring 二）。
            没范围的.append(str(t.get("id")))
            continue
        目标们: list[str] = []
        if 仓 is not None:
            from pathlib import Path as _P
            根h = _P(str(仓))
            for pat in 范们:
                try:
                    目标们 += [str(p.relative_to(根h)).replace("\\", "/")
                               for p in 根h.glob(pat) if p.is_file()]
                except (ValueError, OSError):
                    continue
        else:
            目标们 = list(范们)
        目标们 = sorted(set(目标们))
        # ★ 只留**真的命中这个文件**的门（理由见 docstring 一）。
        #   用 fnmatch 而不是字符串相等 —— 范围本来就是 glob（`plot/*.py`）。
        if 文件:
            import fnmatch as _fn
            目标们 = [f for f in 目标们
                     if f == 文件 or _fn.fnmatch(f, 文件) or _fn.fnmatch(文件, f)]
        # ★★ 一条规则可以出**多条门**：该出现的按 `grep_required`、
        #   不该出现的按 `grep_forbidden`。**极性按模式走，不按条目走**
        #   （2026-11-03 修「极性反转」真缺陷，见 `_正反模式` 的 docstring）。
        #   原来"一个条目一条门"的表达力不够：`必须 A 且禁止 B` 表达不了。
        #
        # ★★★★★ 2026-11-04（第229轮）：**`grep_required` 铺到多个文件 ⇒ 不转门。**
        #
        #   ## 实测（真仓，97 道展开后的门）
        #
        #   ```
        #   铺到 1 个文件   绿 1
        #   铺到 12 个文件  红 1 / 绿 11     (forbidden)
        #   铺到 24 个文件  红 29 / 绿 19    (required + forbidden 各一套)
        #   铺到 36 个文件  红 25 / 绿 11
        #   ```
        #
        #   **所有必红的门都来自 4 条"范围铺开"的规则，单文件门是绿的。**
        #
        #   ## 为什么这不是"门太严"，是"这句话没法判"
        #
        #   `grep_required` 展开成 N 个文件后的意思是
        #   **"这 N 个文件每一个都必须含有这个串"**。
        #   而 `环境["PYTHONIOENCODING"]="utf-8"` 这样的处方，**只适用于
        #   "做那件事的那些文件"**（这里 = 会起子进程的文件），不是 `src/**/*.py` 每一个。
        #   ⇒ 于是它要求 `__init__.py` 也写上给子进程钉编码，
        #     而 `__init__.py` 一辈子不起子进程 —— **这门永远红，和产物好坏无关。**
        #
        #   ## 两种极性的语义本来就不一样
        #
        #   · `grep_forbidden` 铺到 N 个文件 = "这 N 个文件**都不许**含这个串"
        #     ⇒ **天然成立**（禁令本来就是"全都别做"）。实测 12 个文件里 11 绿，剩下 1 红
        #       （`tests/coord_chain.py` 里真有 `PYTHONIOENCODING`）= **一条真发现**。
        #   · `grep_required` 铺到 N 个文件 = "这 N 个文件**全都**要含这个串"
        #     ⇒ **几乎从来不是人想说的那句话**。人想说的是"产物里要有 kHz"，
        #       而**产物是一个确定的文件**，不是"范围内每一个源文件"。
        #
        #   ★ 口径：**「必须出现」只有指向一个确定的产物才可判。**
        #     判不了 ⇒ 不产门 + 如实记进 `未转门()` ——
        #     与上面"极性判不了就不猜"同一条纪律。
        #   ★ 这也解释了第224轮那个悬案（「门集 10 条里 8 条无关门 ⇒ 任何产物都必然红」）
        #     的另一半：**量词错了**。
        #   ★ 例外：`文件=` 明确指名了一个文件时照常出 ——
        #     人已经把它收敛到"就是这一个产物"上了，量词不再错。
        if 该有 and len(目标们) > 1 and not 文件:
            _必有多文件.append(
                (str(t.get("id") or ""), len(目标们), 该有[0][:50]))
            该有 = []
        # ★★★ 2026-11-04（第229轮）：**裸词禁令会拦合规代码 —— 如实标出来。**
        #
        #   实测（上面那轮修完，真仓上还剩 6 道红门，**6/6 全是误报**）：
        #
        #     规则正文 `**永不用 `setdefault`**`
        #       ⇒ 抽出的片断只有一个裸词 `setdefault`
        #       ⇒ 真仓里命中的是 `globals().setdefault(...)`、
        #         `acc.setdefault(gk, {...})`、`os.environ.setdefault("TAIXU_DB", …)`
        #         —— **dict 的 setdefault / 另一个环境变量**，跟"给子进程钉编码"毫无关系。
        #
        #     规则正文里的 `PYTHONIOENCODING`（禁则-判据不许依赖调用方编码，全部正文就一个词）
        #       ⇒ 命中的是 `env = dict(os.environ, PYTHONIOENCODING="utf-8", …)`
        #         —— **那恰恰是规则要求的合规写法**（判据自己钉住编码），
        #           只是它**提到了**这个名字就被判红。
        #
        #   ★ 口径：**一个裸标识符当禁令，等于"这个词不许出现"** ——
        #     而"不出现"和"不做那件事"是两回事。
        #     规则的本意带上下文（"给它钉编码时不许 setdefault"），
        #     抽成裸词之后**上下文丢了，量词就错了**（同上面那条"铺到多个文件"的病因）。
        #
        #   ★ 为什么**不丢、只标**：丢掉就把这条禁令的真价值也一起丢了
        #     （确实有"用 setdefault 钉编码"这种错写法）。而"该写具体"这件事
        #     **机器判不了** —— 只有人知道那句禁令的上下文是什么。
        #     ⇒ 如实报进 `未转门()`，让看的人去把片断写具体。
        #   ★ 与"极性判不了就不猜"的分界：那里是**判不了所以不产门**；
        #     这里是**能判、但判得比人想说的宽** ⇒ 产物照出，把偏差标出来。
        for 模式 in 不该有:
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", 模式 or ""):
                _裸词禁令.append((str(t.get("id") or ""), 模式))
        for 文件v in 目标们[:12]:                    # 上限防炸：一条规则最多 12 个文件门
            for 极性, 模式们 in (("required", 该有), ("forbidden", 不该有)):
                for 模式 in 模式们:
                    出.append({"name": f"KB:{t.get('id')}"
                                      + (f"@{文件v}" if len(目标们) > 1 else "")
                                      + (f"[{极性}]" if (该有 and 不该有) else ""),
                               "type": ("grep_required" if 极性 == "required"
                                        else "grep_forbidden"),
                               "in": 文件v, "patterns": [模式]})
                    if len(出) >= 上限门:
                        break
                if len(出) >= 上限门:
                    break
            if len(出) >= 上限门:
                break
        if len(出) >= 上限门:
            # ★ 硬上限：宁可少给门，不许给一坨没人看的门（那等于没有门）。
            break
    # ★★ 未转门的信息**不进返回列表**，改用模块级快照（`未转门()` 读）。
    #
    #   理由（这是被真调用方逼出来的）：返回列表的**唯一用途**是
    #   "原样塞进 `orch_run` 的 gates"（`kb` 工具的 docstring 就是这句）。
    #   往里面塞一个说明性字典 ⇒ 调用方拿到的门集里混进一条**非法门规格**，
    #   而 `gate_spec` 会以"门规格非法"整批拒掉 —— **为了让人看见"哪些没转门"，
    #   反而把能转的那些门也弄坏了**。
    #   ⇒ 口径：**一个返回列表只放一种东西**。
    #     想同时给"结果"和"元信息"，就给两条通道，不许混在一个 list 里。
    #   （本仓已有同型教训：判据之间不许互相串味。）
    global _未转门_快照
    _未转门_快照 = {"没写范围": 没范围的, "转不出模式": 略过的,
                   # ★ 2026-11-04：**"因为极性判不了而丢掉的片断"必须可见。**
                   #   只报产出，看的人会以为"知识库就这么多门"。
                   "极性判不了": [f"「{片}」(来自 {rid})" for rid, 片 in _极性无据],
                   # ★ 2026-11-04：**"必须出现铺到多个文件上"也必须可见** ——
                   #   否则看的人只会看到"门变少了"，看不到少的是**错的那些**。
                   "必须出现却铺到多文件": [
                       f"{rid}：要 {n} 个文件都含「{片}」"
                       f" ⇒ 要么把这条规则的「范围」收窄到**一个确定的产物**，"
                       f"要么调 `门(…, 文件=…)` 指名一个文件；"
                       f"真要求「范围内每个文件都要有」的话，请另写一条规则写明"
                       for rid, n, 片 in _必有多文件],
                   # ★ 2026-11-04：**裸词禁令如实报出来**（不丢，只标）。
                   "裸词禁令（过宽，建议写具体）": [
                       f"{rid}：禁止「{词}」—— 没有上下文，会拦合规写法"
                       for rid, 词 in dict.fromkeys(_裸词禁令)],
                   "有效门数": len(出), "上限门": 上限门}
    return 出


def 未转门() -> dict:
    """上一次 `门()` 调用里**没能转成门**的条目，以及为什么。

    ★ 为什么给未转门单开一条通道（而不是塞进 `门()` 的返回列表）：
      见 `门()` 里那段注释 —— 返回列表只放合法门规格，别的东西混进去会让
      `gate_spec` 整批拒掉。**如实报"哪些没转"也很重要**：
      不说的话，调用方会以为"我写的规则都变成门了"。
    """
    return dict(_未转门_快照)


def 门统计() -> dict:
    """可机判性概览：多少条能变门、多少条因为什么变不了。给 `doctor` 用。

    ★ 这个数字比"库里有几条"有意义：**库再大，转不出门的规则都只是提示**
      （提示级 = 模型可能不听）。"能变门的条数"才是这套东西的**硬约束存量**。
    """
    条们 = 全量()
    能 = 0
    无范 = []
    无模 = []
    for t in 条们:
        if not _模式(t):
            无模.append(str(t.get("id")))
            continue
        范 = t.get("范围") or []
        if not (范 if isinstance(范, list) else [范]):
            无范.append(str(t.get("id")))
            continue
        能 += 1
    return {"总数": len(条们), "可转门": 能,
            "没写范围": 无范, "转不出模式": 无模,
            "不可机判": len(无范) + len(无模)}


def 统计() -> dict:
    _自动播种一次()
    """统计**永远不抛**：库不可写/索引坏了也返回可读结论。

    ★ 实测教训（2026-11-02 部署侧）：首版只把 `全量()` 包进 try，`冲突()`/`门()` 在库不可写时
      直接抛 `PermissionError` ⇒ 一个"只读统计"的工具把调用方整个打崩。
      只读工具崩掉，比返回"库读不了"更糟：后者能修，前者只能猜。
    """
    try:
        条们 = 全量()
    except Exception as e:                       # noqa: BLE001
        return {"错误": f"{type(e).__name__}: {e}", "条数": 0, "库": str(库根())}
    按类: dict = {}
    for t in 条们:
        按类[t.get("类别", "?")] = 按类.get(t.get("类别", "?"), 0) + 1
    出 = {"条数": len(条们), "按类别": 按类, "库": str(库根())}
    # ★ 配置回落必须出现在统计里：否则"库 0 条"看着像"这个项目本来就没知识"，
    #   而真相是"你指的那个目录不存在" —— 这是两种完全不同的修法。
    if 回落原因():
        出["配置回落"] = {"ORCH_KB_DIR": 回落原因()[0], "原因": 回落原因()[1],
                         "实际使用": str(库根())}
    try:
        出["冲突"] = 冲突()
    except Exception as e:                       # noqa: BLE001
        出["冲突"] = f"读不到：{type(e).__name__}: {e}"
    try:
        出["可机判门"] = len(门(条们))
    except Exception as e:                       # noqa: BLE001
        出["可机判门"] = f"算不出：{type(e).__name__}: {e}"
    return 出
