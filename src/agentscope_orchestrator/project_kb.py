def 播种(*, 力: bool = False, 干跑: bool = False, 源: Path | None = None) -> dict:
    """把**随包的种子知识**播种进运行期库目录（`库根()`）。

    为什么不覆盖人的修改：这个库的硬要求是"**人可改**"。默认只**补缺失**；
    目标里已存在且内容不同的条目只报告、不动（那可能是人在运行机上改过的）。
    `力=True` 才是"以种子为准强制对齐"。

    返回 {"新增","相同","差异","已写","目标","是同一处"}，便于调用方（doctor / CLI）如实转述。
    """
    源 = 源 or 内建种子()
    目标 = 库根() / "items"
    出 = {"新增": 0, "相同": 0, "差异": 0, "已写": 0, "目标": str(目标), "是同一处": False}
    if not 源.is_dir():
        return 出 | {"说明": f"种子目录不存在：{源}"}
    try:
        if 源.resolve() == 目标.resolve():
            出["是同一处"] = True      # ORCH_KB_DIR 直接指向包内种子 ⇒ 无需播种
            return 出
    except OSError:
        pass
    增, 差 = [], []
    for f in sorted(源.glob("*.md")):
        t = 目标 / f.name
        if not t.exists():
            增.append(f)
        elif t.read_bytes() == f.read_bytes():
            出["相同"] += 1
        else:
            差.append(f)
    出["新增"], 出["差异"] = len(增), len(差)
    if 干跑:
        return 出
    目标.mkdir(parents=True, exist_ok=True)
    写 = 增 + (差 if 力 else [])
    for f in 写:
        shutil.copy2(f, 目标 / f.name)
    出["已写"] = len(写)
    if 写:
        出["重建索引"] = 重建索引()
    return 出


