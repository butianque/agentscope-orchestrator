        #     · 或含总账 `全部 PASS` / `n/n 全绿` / `自检：全绿|失败`
        #     · ★ 不再用「含某个词」这种**无位置约束**的匹配
        末 = [x for x in 出.splitlines()
              if re.match(r"^\s*(PASS|FAIL|✗|✓)\b", x)
              or "全部 PASS" in x
              or re.search(r"自检[：:]\s*(全绿|失败)", x)]
        # ★★★★★ R156b：**判红时要展示「哪一条失败」，不是「最后一条」**。
        #   实测：修好上面那行之后，`末[-1]` 仍可能挑到一条 **PASS** 行
        #   （探针最后一行常是「全部 PASS」总账）——
        #   于是「红了」却展示一条 PASS，人/模型看了会以为机器在胡说。
        #   ★ 这是「哪一条不合格没说出来」的第 N 次（R133 同族）。
        #   ⇒ 判红时优先用**失败行**；判绿时才用最后一条。
        _失败行156 = [x for x in 末
                      if re.match(r"^\s*(FAIL|✗)\b", x)]
        def _摘156(ok: bool) -> str:
            if not ok and _失败行156:
                return _失败行156[-1].strip()[:110]
            return 末[-1].strip()[:110] if 末 else ""
        # ★★★★★ R69b（2026-10-16 真事故）：**`checks/` 是产品目录，不是草稿纸**。
        #   我把 6 个临时调试脚本（`_调试R69.py` / `_校准R69*.py` / `_查R69残差.py` …）
        #   留在了 `checks/` 里 ⇒ 回归把它们**当成探针**跑 ⇒ 红 2 个。
        #   ★ 它们本身没问题，**问题是"非探针"和"探针"长得一样**：
        #     退出码非 0 的会被抓出来（响的），但**退出码恰好 0 的会静默算成绿**，
        #     于是"绿 57"里混着根本不是判据的东西 —— **无齿看起来像绿**。
        #   ⇒ 与 src 模块同一条口径：**退出码 0 只是必要条件**，
        #     还必须有**自证**（打印 `自检` / `全绿` / `PASS` / `n/n` 全等）。
        #   ⇒ 临时脚本一律放 `验证/`（不在本目录、不参与回归）。
        # ★★★★★ R146（第 59 层 · 2026-10-24 · 全量回归 R145_1215）：
        #   **探针输出里「自检」是它测的东西，不是它的自证。**
        #
        #   真证据：
        #     `绿 checks/数术层齿探针.py  generic_goal 自检：失败 5 · 判据点 769 —— 红 5`
        #   ★ 一个**被判绿**的探针，摘要里写着「自检：失败 5」。
        #     而下一个探针 `自举齿探针` 报「自检：失败 1」却**被判红**。
        #     同一个词，两种结论 —— 说明判据根本不是它。
        #
        #   ★★ 根因：`_有自证 = ("自检" in 出 or …)`。
        #     而**齿探针的整个工作方式就是注入 ⇒ 跑一遍产品自检 ⇒ 看它红**。
        #     ⇒ 它的输出里**必然**有「自检」二字（而且是「自检：失败 N」）。
        #     ⇒ 这个判据对探针**恒真** ⇒ 退出码 0 就绿 ⇒ **无齿看起来像绿**。
        #
        #   ★★★ 这是「手里那个量不是判据需要的那个量」的第 7 次：
        #     判据需要的是「**这个探针自己说它验过了**」，
        #     我拿到的是「**它的输出里出现了「自检」这个词**」。
        #     前者是断言，后者是噪音。
        #
        #   ★★★★ 修法：**探针的自证必须是它自己的结论行**，而不是它测到的东西。
        #     · `PASS` / `全部 PASS` / `全绿` / `n/n` 全等 —— 这些是自证
        #     · 「自检」二字**不算**（那是被测对象）
        #     · ★ 但 `src/` 模块（非探针）的自证就是「自检：全绿」⇒ 那里保留
        #   ⇒ 口径：`checks/` 下，**「自检」必须与「全绿」连用**才算自证；
        #     单说「自检：失败 N」是**被测对象的红**，不是探针的自证。
