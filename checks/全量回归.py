# ★★★★★ R143（真跑抓出的第 56 层 · 2026-10-24 · 第 34 次真跑之后的回归）：
#   **超时是硬编码的，而探针的成本是结构算出来的。**
#
#   真证据（全量回归 R142_2345）：
#     `超时 checks/规划层齿探针.py >1800s（★ 探针可能被强杀 ⇒ 补丁可能留在产品源码里）`
#     `★★★ 立刻停止：发现 **齿探针的尸体**（`.clean` 侧车残留）`
#   单独跑同一个探针：**45 分钟，全部 PASS**（不是缺陷，是慢）。
#   ★ 根因：这个探针有 **32 项**，每项注入一次 + 跑一遍完整自检。
#     而单次自检实测 **85 秒** ⇒ 32 × 85 ≈ **45 分钟** > 硬编码的 **30 分钟**。
#
#   ★★ 这不是"探针太慢"，是**判它的尺子和它的成本没有关系**：
#     1800 是个凭感觉写的数，而真实成本 = 项数 × 单次自检。
#     ⇒ 与 R140/R141/R142 同族：**手里那个量不是判据需要的那个量。**
#     这次是「手里那个**超时**不是它该覆盖的**成本**」。
#
#   ★★★ 而且后果比"多等 15 分钟"严重得多：
#     超时被杀 ⇒ 补丁留在产品源码里 ⇒ 报「产品源码未还原（R84）」
#     ⇒ **一个假红**。我为此白查了一轮。
#
#   ⇒ 修法：**按结构算**，不写死。
#     ① 静态数出这个模块自己声明的项数（`PASS ⓪`/`PASS ㉑`… 的出现处）；
#     ② 项数 > 1 ⇒ 它要跑多次自检 ⇒ 超时按 `项数 × 单次上限` 给；
#     ③ 项数 = 1（普通模块）⇒ 保持原来的 1800s。
#     ★ 单次上限给 **180 秒**（实测 85 秒，留 2 倍余量）；
#       超过就是真的卡住了，那时该红。
#     ★ 上限仍有界：32 项 × 180 = 96 分钟，不会无限等。
_超时 = 1800
_单次上限 = 180


def _按结构算超时(mod: Path) -> int:
    """★ R143：**超时按结构算，不写死。**

    一个模块跑 `--selftest` 需要多久，取决于它**自己**要跑几遍自检 ——
    而"跑几遍"是可以静态数出来的（`PASS ⓪`、`PASS ㉑` 这类标记的个数）。
    ★ 数不出来（0 或 1）⇒ 按普通模块给 `_超时`（老行为，零变化）。
    """
    try:
        t = mod.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return _超时
    # ★ 数「这个模块会跑几次自检」——**不是**数 PASS 字面量。
    #   实测：`规划层齿探针.py` 里 `PASS` 只出现 6 次（模板 + 少数固定项），
    #   而真实场景是 **23 个 `场景(...)` 调用** + 若干独立项 ⇒ 共 32 次。
    #   ⇒ 数 PASS 会严重低估（这正是我第一次改错的地方）。
    #   ★ 正确口径：**数「跑自检」的调用点**，因为它才是成本的来源。
    import ast as _ast
    _次 = 0
    try:
        _树 = _ast.parse(t)
        for _n in _ast.walk(_树):
            if isinstance(_n, _ast.Call) and isinstance(_n.func, _ast.Name) \
                    and _n.func.id in ("场景", "跑自检"):
                _次 += 1
    except (SyntaxError, ValueError):
        return _超时
    if _次 <= 1:
        return _超时
    return max(_超时, _次 * _单次上限)


_数 = re.compile(r"(\d+)\s*/\s*(\d+)")

# ★★★ 跑器自身的教训（**如实登记**）：第一版从零造 env（只给 PYTHONPATH+PATH）
#   ⇒ 丢掉 `USERPROFILE`/`HOMEDRIVE`/`HOMEPATH` ⇒ 子进程报
#     "Could not determine home directory"（8 个模块假红）；
#   ⇒ 丢掉 `PYTHONIOENCODING` ⇒ 子进程 stdout 落 gbk ⇒ 中文「全绿」变 mojibake
#     ⇒ 我的状态解析器读不到「全绿」⇒ 又把绿判成红（`doc_store` 假红）。
#   ★ 这是**跑器**的缺陷，不是产品的。修法：**继承**父进程环境，只**覆盖**需要的项。
_ENV = dict(os.environ)
_ENV["PYTHONPATH"] = str(_PKG.parent)
_ENV["PYTHONIOENCODING"] = "utf-8"       # 中文判据输出必须 utf-8
_ENV["PYTHONUTF8"] = "1"


def _跑(mod: Path) -> tuple[str, str, float]:
    """返回 (状态, 摘要, 秒)。状态 ∈ 绿/红/无自检/超时。"""
    t = mod.read_text(encoding="utf-8", errors="ignore")
    if "--selftest" not in t and "def _selftest" not in t:
        return "无自检", "", 0.0
    env = _ENV
    # ★ R143：**按这个模块自己的项数**给超时（不是全局写死的一个数）
    _此超时 = _按结构算超时(mod)
    t0 = time.time()
    try:
        cp = subprocess.run([str(_PY), str(mod), "--selftest"],
                            capture_output=True, text=True, encoding="utf-8",
                            errors="ignore", timeout=_此超时, env=env,
                            cwd=str(_PKG.parents[1]))
    except subprocess.TimeoutExpired:
        return "超时", f">{_此超时}s", time.time() - t0
    except OSError as _eOS:
        # ★ R150：`CreateProcess` 失败（WinError 1455 页面文件太小 /
        #   1450 系统资源不足）⇒ **这个模块没跑**，不是它坏了。
        #   实测：另一个 agent 跑 cargo 时，回归里连续多个模块报红，
        #   而单独跑每个都全绿 —— 那是**假红**，栽给了产品。
        return "跳过", (f"子进程起不来（{type(_eOS).__name__}: {_eOS}）"
                        f"⇒ 没跑，不是不绿"), time.time() - t0
    秒 = time.time() - t0
    出 = (cp.stdout or "") + (cp.stderr or "")
    # 取最后一行含「自检」的
    摘 = ""
    for line in 出.splitlines():
        if "自检" in line and ("全绿" in line or "/" in line):
            摘 = line.strip()
    if not 摘:
        for line in reversed(出.splitlines()):
            if line.strip():
                摘 = line.strip()[:160]
                break
    if cp.returncode != 0:
        return "红", 摘, 秒
    # ★ 判绿必须**两条都满足**：退出码 0 **且**输出里有「全绿」或 `n/n` 全等。
    #   只看出错码会让"没跑任何判据却退 0"的模块**假绿**。
    if "全绿" in 摘 or "全绿" in 出:
        return "绿", 摘, 秒
    m = _数.search(摘) or _数.search(出)
    if m and m.group(1) == m.group(2) and int(m.group(2)) > 0:
        return "绿", 摘, 秒
    return "红", 摘 + "（退出码 0 但未见「全绿」或 n/n ⇒ 判红，防假绿）", 秒


def _查未还原侧车(目录们=None) -> list[str]:
    """★ R84：找出**停在注入态**的产品源码（侧车 `.clean` 还在）。

    真事故（2026-10-17 20:19，本回归自己抓出来的）：
      `规划层齿探针` 某场景注入后**还原被拒**（`_原文守卫` 判"文件被改过"），
      产品源码 `generic_goal.py` **停在注入态**（少了一段 `{门态块}`），
      而本回归**照常打出总账**、退出码只看红/超时。
      后果：后续探针在这个**坏掉的**产品源码上跑 ⇒ 也红；我手工跑自检 ⇒ 红 4 条。

    ★ 侧车 `.clean` 本来就是为此设计的（R74c：防强杀留补丁）——**但没人读它**。
      这是「声明了保护 ≠ 保护在」的又一例：**侧车写得好好的，没人读**。

    判据（结构给的，不是猜的）：
      · 侧车在、主文件**不在** ⇒ **跳过**（不是残留，是孤儿；另有人管）
      · 侧车在、主文件在、**字节相同** ⇒ **一致但侧车未清**（脏，但不是注入态）
      · 侧车在、主文件在、**字节不同** ⇒ **主文件停在注入态**（最严重）
    """
    if 目录们 is None:
        _根 = Path(__file__).resolve().parent
        目录们 = (_根,
                  _根.parent / "验证",
                  _根.parent / "src" / "agentscope_orchestrator")
    残留: list[str] = []
    for _d in 目录们:
        try:
            _侧们 = sorted(Path(_d).glob("*.clean"))
        except Exception:            # 目录不存在 / 读不了 ⇒ 跳过（不静默当绿）
            continue
        for _c in _侧们:
            try:
                _主 = _c.with_suffix(".py")
                if not _主.is_file():
                    continue
                _同 = _主.read_bytes() == _c.read_bytes()
                残留.append(f"{_c.name}（主文件 {_主.stat().st_size} 字节 / "
                            f"侧车 {_c.stat().st_size} 字节 ⇒ "
                            f"{'**一致但侧车未清**' if _同 else '**主文件停在注入态**'}）")
            except Exception as _e:
                残留.append(f"{_c.name}（读不了：{_e}）")
    return 残留


