#   ⇒ 现在：锁在但持有者**已死** ⇒ 接管并明说；持有者**活着** ⇒ 照旧拒绝。
def _pid活(pid: int) -> bool:
    if pid <= 0:
        return False
    if os.name == "nt":
        import subprocess as _sp
        try:
            cp = _sp.run(["tasklist", "/FI", f"PID eq {pid}", "/NH"],
                         capture_output=True, text=True, timeout=15)
            return str(pid) in (cp.stdout or "")
        except Exception:                       # noqa: BLE001
            return True                          # 查不到 ⇒ 当作活着（保守）
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


