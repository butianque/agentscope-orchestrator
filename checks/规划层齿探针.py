def 退回(替换表: list[tuple[str, str]]) -> None:
    """按字节替换。锚点用文本模板，**行尾从文件自己的字节读出**（不假设）。

    ★ R74：**注入前先守卫** —— 若文件在我读过之后被别人改过（人用编辑器、
      或另一个不加锁的进程），这里就**拒绝注入**。理由：注入 + `finally`
      无条件写回会把别人的改动**安静地擦掉**（真事故，见 `_互斥.原文守卫`）。
    """
    global _最后写的
    _冲突 = _原文守卫(目标文件, 原字节, "规划层齿探针")
    if _冲突:
        失败.append(_冲突)
        raise _跳过注入(_冲突)
    行尾 = "\r\n" if b"\r\n" in 原字节 else "\n"
    b = 原字节
    for 旧文本, 新文本 in 替换表:
        旧 = 旧文本.replace("\n", 行尾).encode("utf-8")
        新 = 新文本.replace("\n", 行尾).encode("utf-8")
        n = b.count(旧)
        if n != 1:
            raise AssertionError(f"锚点出现 {n} 次（要求唯一）：{旧文本[:90]!r}")
        b = b.replace(旧, 新)
    原子写(目标文件, b)
    _最后写的 = b          # ★ R74：记下"我写的是什么"，还原前据此判冲突


