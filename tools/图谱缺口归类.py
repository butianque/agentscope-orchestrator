def _净文(文: str, 后缀: str) -> str | None:
    """**剥掉注释与字符串字面量**之后的文本；拿不到实现返回 `None`（= 该后缀不参与搜索）。

    ★ 为什么必须有（R567 · R560 的同一课）：
      逐字搜原文本 ⇒ **注释/文档里提到这个名字**就被算成"盘上有引用" ⇒
      明明只是"提过一嘴"，却判成"边抽取缺失"。`mem_anchor` 曾把**注释里提到的
      `.lean` 名**算成一条锚定边（112 条悬空里 97 条是这么来的）—— 同一个错犯第二次。

    ★ 返回 `None` 而不是原文本：**宁可不搜，不许制造假"边缺失"**。
    """
    s = 后缀.lower()
    if s == ".lean":
        try:
            from agentscope_orchestrator import kg as _kg
            return _kg._剥Lean注释(文)
        except Exception:                      # noqa: BLE001
            return None
    if s == ".py":
        import io
        import tokenize as _tk
        _丢 = {_tk.COMMENT, _tk.STRING, _tk.NL, _tk.NEWLINE, _tk.INDENT,
               _tk.DEDENT, _tk.ENCODING, _tk.ENDMARKER}
        部: list[str] = []
        try:
            for tok in _tk.generate_tokens(io.StringIO(文).readline):
                if tok.type in _丢:
                    continue
                部.append(tok.string)
        except (_tk.TokenError, IndentationError, SyntaxError):
            # 解析不了 ⇒ 当作"拿不到净文"（由调用方决定不搜）；**不要**退回原文本
            return None
        return " ".join(部)
    if s == ".rs":
        # `//` 行注释 + `/* */` 块注释（Rust 的 `///` 也走行注释这条路）
        出: list[str] = []
        深 = 0
        i = 0
        n = len(文)
        while i < n:
            if 深 == 0 and 文.startswith("//", i):
                j = 文.find("\n", i)
                i = n if j < 0 else j
                continue
            if 文.startswith("/*", i):
                深 += 1
                i += 2
                continue
            if 深 and 文.startswith("*/", i):
                深 -= 1
                i += 2
                continue
            if 深 == 0:
                出.append(文[i])
            i += 1
        return "".join(出)
    return None


def _建盘引用表(名们, 根, 表):
    """返回 {名字: 出现过它的**表内代码文件**集合}；拿不到就 None（= 未验）。

    ★★★ 这里踩过两次假绿/假红，都记在案：
      ① 第一版调 `rg`，而这台机器**没有 rg** ⇒ `FileNotFoundError` 被 `except` 吞成空集
         ⇒ 「盘上另有引用=空」⇒ 抽取缺失 0.0% ⇒ **判绿，但没有任何证据**。
         规矩：拿不到 oracle 就返回 None，调用方记**未验**（口径 545），不许记绿。
      ② 第一版把作用域定成"整个仓" ⇒ 41k 文件逐字搜索，**10 分钟不返回**（口径 390）。
         现在只在**表内代码文件**（9,225 个）里找：引用若来自表外文件，那是覆盖缺口，
         本来就不该算 adapter 洞 ⇒ 作用域收窄既快又更准。
    """
    global _表内集
    名们 = [x for x in 名们 if x and len(x) >= 3]
    if not 名们:
        return {}
    表内 = set(表._文哈希 or {})
    _表内集 = 表内
    候选 = [r for r in 表内
            if pathlib.PurePosixPath(r).suffix.lower() in _代码后缀们]
    表引 = {n: set() for n in 名们}
    数 = 0
    try:
        for 相对 in 候选:
            q = 根 / 相对
            try:
                文 = q.read_text(encoding="utf-8", errors="ignore")
                _后 = pathlib.PurePosixPath(相对).suffix
                _n = _净文(文, _后)
                if _n is None:            # 该后缀拿不到净文 ⇒ **不搜**（不许制造假"边缺失"）
                    continue
                文 = _n
            except OSError:
                continue
            数 += 1
            for n in 名们:
                # ★★ R567b：**标识符边界**匹配（`_界` 必须在 n 的作用域内算）。
                #   实测 `zero_point_energy_nonnegative` 匹配到了
                #   `zero_point_energy_nonnegative_for_A1_vacuum`（另一个引理）⇒
                #   子串误配被算成"盘上有引用" ⇒ 假"边缺失"。
                #   Lean/Rust/Python 标识符可含字母数字下划线与撇号 ⇒ 前后都不许是这些。
                if n not in 文:                      # 廉价预筛：绝大多数名字这步就出去
                    continue
                if re.search(r"(?<![A-Za-z0-9_'])" + re.escape(n) + r"(?![A-Za-z0-9_'])", 文):
                    表引[n].add(相对)
    except Exception as e:                    # noqa: BLE001
        print("  ⚠ oracle 不可用：%s: %s" % (type(e).__name__, e))
        return None
    print("  （oracle = 表内代码文件逐字搜索 · 扫了 %d 个）" % 数)
    return 表引


def _磁盘另有引用(名, 表):
    """除**全部定义文件**外，还有表内代码文件出现过这个名字吗？

    ★ 定义集合必须用 `表._活[名]`（全量），**不能用** `无调用者()` 给的 `定义在`：
      那个字段是 `[:3]` 截断的，当全集用就会把"第 4 份定义"误判成"别人在引用它"。
    """
    if _盘引用表 is None:
        return None
    定义 = {s.文件 for s in 表._活.get(名, ())}
    return bool(_盘引用表.get(名, set()) - 定义)


def _现场重抽(p, 相对):
    """对候选文件**现场跑一次抽取器**：抽得出符号 ⇒ 问题在**表陈旧**，不在抽取器。

    ★ `mem_symbols` 的 Lean 正则**已经认 `abbrev`**（`mem_symbols.py:131`），而盘上的符号表
      是**修复之前**建的 ⇒ `_dp_probe/sl_00_names.lean` 的 4 条 `abbrev` 表里没有。
      叫它"抽取器的洞"是错的，叫"表陈旧"才对 —— 处置也不同（重扫 vs 改正则）。
    """
    from agentscope_orchestrator import mem_symbols as _ms
    语言 = _ms._语言后缀.get(p.suffix.lower())
    if not 语言:
        return None
    try:
        文 = p.read_text(encoding="utf-8", errors="ignore")
        符们 = _ms.抽取符号(文, 语言, 相对)
    except Exception:                      # noqa: BLE001
        return None
    return len(符们)


