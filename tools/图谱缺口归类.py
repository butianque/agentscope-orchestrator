def _读头(p, n=65536):
    try:
        with p.open("rb") as f:
            return f.read(n)
    except OSError:
        return b""


def _归类无符号(p):
    """返回归类名。**只有 `真缺类名` 那一档才是真缺陷。**

    ★★ 第一版实测教训：它把 287 个判成"真缺陷"，逐条看下去**没有一个是抽取器的洞**：
       include! 转发（200B 的 `核心引擎_中枢方法.rs`）· 注释箱 · 模块 docstring + re-export 薄壳。
       ⇒ 必须先把 注释块/docstring/转发行/属性行/纯括号 剥掉，剩下的才叫主体代码。
    """
    头 = _读头(p)
    if not 头.strip():
        return "空文件"
    if b"\x00" in 头:
        return "二进制（含 NUL）"
    文 = 头.decode("utf-8", errors="ignore")
    if any(m in 文 for m in 生成标记):
        return "生成物（有生成标记）"

    在块注 = False
    在引 = ""
    剩 = []
    顶层: list[str] = []            # ★ 只收**顶格**（无缩进）的行 —— 声明必须顶格
    for 行 in 文.splitlines():
        s = 行.strip()
        if 在引:
            if 在引 in s:
                在引 = ""
            continue
        if 在块注:
            if "*/" in s:
                在块注 = False
            continue
        if "/*" in s and "*/" not in s.split("/*", 1)[1]:
            在块注 = True            # ★ `/*` 可能在行中间打开（实测 `持存.rs` 就是这样）
            continue
        if "/*" in s:
            s = s.split("/*", 1)[0].strip()      # 行内闭合的块注释：剥掉后半行
            if not s:
                continue
        if s.startswith(_引号们):
            标 = s[:3]
            if s.count(标) >= 2:
                continue
            在引 = 标
            continue
        if not s or s.startswith(("#", "//", "*", "*/", "--", ";", "<!--", "#[")):
            continue
        if s.startswith("@") or re.fullmatch(r"[\[\]{}();,:\\'\"`\s]+", s):
            continue
        if any(s.startswith(k) for k in 转发关键字):
            continue
        剩.append(s)
        if not 行[:1].isspace():
            顶层.append(s)
    if not 剩:
        return "无主体代码（注释/转发/文档/属性）"
    # ★★ 判准（2026-11-18 修订）：**「抽不出符号」只有在"本来就有声明可抽"时才是缺陷**。
    #   实测残留的三类形态都不是缺陷：
    #     · 块注释续行（`/*` 在行中间打开 ⇒ 续行不以 `*` 开头）
    #     · 被 `include!` 拼进去的**语句片段**（`中枢.注册能力(能力声明 {…` 全是 call，没有声明）
    #     · docstring/re-export 薄壳
    #   ⇒ 要求残留里出现**声明关键字**，才算"有东西没抽出来"。
    #   ★ 末尾词边界不能少：`var` 会匹配到 `variable`（实测 `_dp_probe/*.lean` 的
    #     `variable {G : Type*}` 就是这样把自己伪装成"有声明"的）。
    #   ★ 但 `namespace`/`section`/`example`/`instance` **不算**：它们是包裹，不是声明 ——
    #     实测 `形式化验证\_archive\**\*.lean` 就靠这几个词把自己伪装成"有声明"（135→ 实测）。
    声明式 = re.compile(r"^\s*(pub(\([^)]*\))?\s+)?(async\s+)?(unsafe\s+)?"
                    r"(def|class|fn|struct|enum|trait|impl|const|static|let|var|function|"
                    r"interface|type|module|macro_rules!|lemma|theorem|inductive|abbrev)" + _词界)
    首 = 顶层[0] if 顶层 else 剩[0]
    if not any(声明式.match(x) for x in (顶层 or 剩)):
        # ★ R568b：**只有 import / open / example / run_cmd / #命令** 的文件里
        #   **根本没有命名声明**可抽 —— 抽不出符号是**应该**的，不是抽取器的洞。
        #   实测（2026-11-18）：`_遗留探针/_probe_401*.lean` 只有 `example`、
        #   `_lead024/zhi_verify17/r7b_inst.lean` 只有 `run_cmd`；
        #   而残留首行是 `import …`，既不匹配"声明式"也不匹配"语句头" ⇒ 掉进「待现场重抽」⇒ 被当成缺陷。
        包裹式 = re.compile(r"^\s*(import|prelude|open|universe|variable|variables|namespace|"
                            r"section|end|set_option|attribute|example|run_cmd|run_elab|"
                            r"run_tac|elab|macro|syntax|notation|infixl|infixr|infix|"
                            r"@\[|omit|include|export)\b")
        # ★ 只看**首行**：走到这里已确认「没有任何一行匹配声明式关键字」，
        #   首行是 import/open/example/命令 ⇒ 文件里没有**命名**声明（续行是前面声明的体，
        #   不该拿来当"有声明"的证据 —— 实测 `_probe_401*.lean` 就栽在这）。
        if 包裹式.match(首):
            return "只有 import/open/example/命令（无命名声明可抽）"
        return "无声明式语句（只有调用/片段，没有可抽的符号）"
    # ★★ 模块层出现**语句**（match/if/for/while/let/return）却不是声明 ⇒ 必是被 `include!`
    #   拼进别处的**片段**，它自己没有符号是应该的。实测：`结构驱力_初始化_边界部署.rs`
    #   残留 232 行全是 `match 中枢.注册感知器_声明式(…` 这类语句 —— 不是抽取器的洞。
    语句头 = re.compile(r"^\s*(match|if|for|while|loop|return|let|guard|switch|try)\b")
    if 语句头.match(首):
        return "语句片段（模块层是语句，被 include! 拼进别处）"
    return "★待现场重抽"


